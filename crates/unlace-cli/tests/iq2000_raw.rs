//! The IQ2000 language decompiles a compare-and-branch routine (with delay slots) built with iq2000-elf-as.
use crate::common;
use common::{run_kuna, scratch_file};

#[test]
fn iq2000_compare_branch_decompiles() {
    let bin = scratch_file("iq2000_compare_branch_decompiles", "bin");
    std::fs::write(
        &bin,
        [
            0x00, 0x85, 0x10, 0x2a, 0x10, 0x40, 0x00, 0x03, 0x00, 0x00, 0x00, 0x00, 0x03, 0xe0,
            0x00, 0x08, 0x00, 0xa4, 0x10, 0x23, 0x03, 0xe0, 0x00, 0x08, 0x00, 0x85, 0x10, 0x23,
            0x27, 0xbd, 0xff, 0xf8, 0xaf, 0xbf, 0x00, 0x04, 0xaf, 0xb0, 0x00, 0x00, 0x00, 0x80,
            0x80, 0x25, 0x0c, 0x00, 0x04, 0x00, 0x24, 0x05, 0x00, 0x0a, 0x8e, 0x03, 0x00, 0x08,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x43, 0x10, 0x21, 0x00, 0x50, 0x10, 0x21, 0x30, 0x42,
            0x00, 0xff, 0x8f, 0xbf, 0x00, 0x04, 0x8f, 0xb0, 0x00, 0x00, 0x03, 0xe0, 0x00, 0x08,
            0x27, 0xbd, 0x00, 0x08,
        ],
    )
    .unwrap();
    let (stdout, stderr, code) = run_kuna(&[
        "decompile",
        bin.to_str().unwrap(),
        "0x1000",
        "--raw-image",
        "--target",
        "iq2000:BE:32:default",
        "--base",
        "0x1000",
    ]);
    assert_eq!(code, 0, "{stderr}");
    let lower = stdout.to_lowercase();
    assert!(!lower.contains("unimplemented"), "{stdout}");
    assert!(!lower.contains("bad instruction"), "{stdout}");
    assert!(stdout.contains("if (a0 < a1)"), "{stdout}");
    assert!(stdout.contains("return a1 - a0;"), "{stdout}");
    assert!(stdout.contains("return a0 - a1;"), "{stdout}");
}
