#!/usr/bin/env python3
"""Write the AVR-Dx processor specs (avr8dx_<series>.pspec) from Microchip's AVR-Dx device pack.

Usage: gen_avr_dx_pspec.py <Microchip.AVR-Dx_DFP.<version>.atpack> [<out-dir>]

The pack is Apache-2.0 (its LICENSE.txt). For each series (DA, DB, DD, DU) every data-space register
of every device is named <instance>_<register>, as avr-libc's io headers name them, and listed as a
<default_symbols> label in mem space. A series' devices share one map; an address two devices name
differently stops the run. Registers SLEIGH already names (RAMPD..RAMPZ at 0x38..0x3b, SREG at 0x3f)
are left out.
"""
import re
import sys
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

SLEIGH_NAMED = {0x38, 0x39, 0x3A, 0x3B, 0x3F}
SERIES = ("DA", "DB", "DD", "DU")


def device_registers(root):
    groups = {}
    for module in root.find("modules"):
        for group in module.findall("register-group"):
            groups[(module.get("name"), group.get("name"))] = group
    regs = {}

    def walk(module, name, base, prefix, depth):
        group = groups.get((module, name))
        if group is None or depth > 4:
            return
        for item in group:
            offset = base + int(item.get("offset", "0"), 0)
            if item.tag == "register":
                modes = item.get("modes")
                if modes and "SINGLE" not in modes.split() and "DEFAULT" not in modes.split():
                    continue
                regs.setdefault(offset, (prefix + "_" + item.get("name"), int(item.get("size", "1"))))
            elif item.tag == "register-group":
                walk(module, item.get("name-in-module"), offset, prefix, depth + 1)

    for module in root.find("devices").iter("module"):
        for instance in module.findall("instance"):
            for group in instance.findall("register-group"):
                if group.get("address-space") == "data":
                    walk(module.get("name"), group.get("name-in-module"),
                         int(group.get("offset"), 0), instance.get("name"), 0)
    return regs


def main():
    pack = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / "specs/Ghidra/Processors/Atmel/data/languages"
    with zipfile.ZipFile(pack) as z:
        version = re.search(r"<release version=\"([^\"]+)\"", z.read(next(n for n in z.namelist() if n.endswith(".pdsc"))).decode()).group(1)
        series = {s: {} for s in SERIES}
        devices = {s: [] for s in SERIES}
        for name in sorted(n for n in z.namelist() if n.startswith("atdf/") and n.endswith(".atdf")):
            dev = Path(name).stem
            m = re.match(r"AVR\d+(D[ABDU])\d+", dev)
            if not m:
                continue
            devices[m.group(1)].append(dev)
            regs = series[m.group(1)]
            for addr, entry in device_registers(ET.fromstring(z.read(name))).items():
                if regs.setdefault(addr, entry) != entry:
                    sys.exit(f"{dev}: 0x{addr:04x} is {entry[0]}, another {m.group(1)} device names it {regs[addr][0]}")
    for s in SERIES:
        lines = [
            '<?xml version="1.0" encoding="UTF-8"?>',
            "",
            f"<!-- Generated by tools/gen_avr_dx_pspec.py from Microchip AVR-Dx_DFP {version} (Apache-2.0):",
            f"     the data-space registers of the AVR{s} devices ({', '.join(devices[s])}). -->",
            "<processor_spec>",
            '  <programcounter register="PC"/>',
            '  <data_space space="mem"/>',
            '  <volatile outputop="write_volatile" inputop="read_volatile">',
            '    <range space="mem" first="0x00" last="0x37"/>',
            '    <range space="mem" first="0x40" last="0xfff"/>',
            "  </volatile>",
            "  <context_data>",
            '    <tracked_set space="code">',
            '      <set name="R1" val="0"/>',
            "    </tracked_set>",
            "  </context_data>",
            "  <default_symbols>",
        ]
        for addr in sorted(series[s]):
            if addr in SLEIGH_NAMED:
                continue
            name, size = series[s][addr]
            size_attr = f' size="{size}"' if size > 1 else ""
            lines.append(f'    <symbol name="{name}" address="mem:0x{addr:04x}"{size_attr}/>')
        lines += ["  </default_symbols>", "</processor_spec>", ""]
        (out / f"avr8dx_{s.lower()}.pspec").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
