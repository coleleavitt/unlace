//! The Nios II language decompiles a compare-and-branch routine built with nios2-elf-as.
use crate::common;
use common::{run_kuna, scratch_file};

#[test]
fn nios2_compare_branch_decompiles() {
    let bin = scratch_file("nios2_compare_branch_decompiles", "bin");
    std::fs::write(
        &bin,
        [
            0x0e, 0x02, 0x40, 0x21, 0x3a, 0xc8, 0x05, 0x29, 0x3a, 0x28, 0x00, 0xf8,
            0x3a, 0xc8, 0x45, 0x21, 0x3a, 0x28, 0x00, 0xf8, 0x04, 0xfe, 0xff, 0xde,
            0x15, 0x01, 0xc0, 0xdf, 0x15, 0x00, 0x00, 0xdc, 0x3a, 0x88, 0x21, 0x20,
            0x84, 0x02, 0x40, 0x01, 0x00, 0x00, 0x01, 0x00, 0x17, 0x02, 0xc0, 0x80,
            0x3a, 0x88, 0xc5, 0x10, 0x3a, 0x88, 0x05, 0x14, 0xcc, 0x3f, 0x80, 0x10,
            0x17, 0x01, 0xc0, 0xdf, 0x17, 0x00, 0x00, 0xdc, 0x04, 0x02, 0xc0, 0xde,
            0x3a, 0x28, 0x00, 0xf8,
        ],
    )
    .unwrap();
    let (stdout, stderr, code) = run_kuna(&[
        "decompile",
        bin.to_str().unwrap(),
        "0x1000",
        "--raw-image",
        "--target",
        "nios2:LE:32:R1",
        "--base",
        "0x1000",
    ]);
    assert_eq!(code, 0, "{stderr}");
    let lower = stdout.to_lowercase();
    assert!(!lower.contains("unimplemented"), "{stdout}");
    assert!(!lower.contains("bad instruction"), "{stdout}");
    assert!(stdout.contains("if (a0 < a1)"), "{stdout}");
    assert!(stdout.contains("return a1 - a0;"), "{stdout}");
    assert!(stdout.contains("return a0 - a1;"), "{stdout}");
}
