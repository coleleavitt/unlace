//! The Visium language decompiles a compare-and-branch routine (with delay slots) built with visium-elf-as.
use crate::common;
use common::{run_kuna, scratch_file};

#[test]
fn visium_compare_branch_decompiles() {
    let bin = scratch_file("visium_compare_branch_decompiles", "bin");
    std::fs::write(
        &bin,
        [
            0x06, 0x41, 0x00, 0x24, 0x48, 0x00, 0x00, 0x05, 0x00, 0x00, 0x00, 0x00,
            0x86, 0x42, 0x04, 0x14, 0x7f, 0x95, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00,
            0x86, 0x41, 0x04, 0x24, 0x7f, 0x95, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00,
            0x84, 0x57, 0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x03, 0xf7, 0x05, 0x54,
            0x83, 0xf7, 0x00, 0xb4, 0x87, 0x21, 0x2c, 0x04, 0x84, 0xa9, 0x00, 0x00,
            0x84, 0x89, 0x10, 0x00, 0x7f, 0x89, 0x54, 0x04, 0x04, 0xc2, 0x00, 0x0a,
            0x07, 0xeb, 0x0e, 0x24, 0x86, 0x01, 0x04, 0x34, 0x06, 0x01, 0x04, 0xb4,
            0x07, 0xf7, 0x56, 0x14, 0x87, 0xf7, 0x2e, 0x04, 0x7f, 0x95, 0x00, 0x04,
            0x04, 0x17, 0x00, 0x08,
        ],
    )
    .unwrap();
    let (stdout, stderr, code) = run_kuna(&[
        "decompile",
        bin.to_str().unwrap(),
        "0x1000",
        "--raw-image",
        "--target",
        "visium:BE:32:default",
        "--base",
        "0x1000",
    ]);
    assert_eq!(code, 0, "{stderr}");
    let lower = stdout.to_lowercase();
    assert!(!lower.contains("unimplemented"), "{stdout}");
    assert!(!lower.contains("bad instruction"), "{stdout}");
    assert!(stdout.contains("if (a0 < a1)"), "{stdout}");
    assert!(stdout.contains("return a1 - a0;"), "{stdout}");
    assert!(stdout.contains("return a0 - a1;"), "{stdout}");
}
