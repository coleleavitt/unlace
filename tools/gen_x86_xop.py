#!/usr/bin/env python3
"""Generate the AMD FMA4, XOP, TBM and LWP SLEIGH tables of the x86 languages from LLVM's TableGen records.

Usage:
  llvm-tblgen --dump-json -I <llvm>/include -I <llvm>/lib/Target/X86 \
      <llvm>/lib/Target/X86/X86.td -o x86.json
  tools/gen_x86_xop.py x86.json specs/Ghidra/Processors/x86/data/languages/amd_xop.sinc

Every record with a HasFMA4, HasXOP, HasTBM or HasLWP predicate is emitted, the disassembler-only
_REV register forms included; a register record and the memory record with the same operand layout
fold into one constructor over the XmmReg2_m*/YmmReg2_m*/rm* tables. XOP encodings are the
VEX-like 8F prefix of ia.sinc (maps 8, 9 and 0Ah as vexMMMMM 8..10). Semantics follow the AMD64
APM (volume 3 for TBM/LWP, volume 4 for FMA4/XOP):
- FMA4 computes with one rounding, which p-code cannot express: one user operation per mnemonic
  (as fma.sinc does for FMA3); the scalar forms clear bits 127:32 (127:64).
- VFRCZ*, VPPERM and VPERMIL2* are user operations; the scalar VFRCZ forms clear the upper bits.
- VPCMOV, VPCOM*, VPROT*, VPSHL*, VPSHA*, VPHADD*, VPHSUB*, VPMACS* and VPMADCS* are p-code. A
  shift or rotate count is the signed low byte of the count element (or imm8): positive counts go
  left, negative ones right, by the magnitude modulo the element width (the APM's "bit 6 of the
  count byte is ignored" for quadwords); saturating forms saturate the exact sum.
- TBM: the result of the APM's add/sub pseudo-instruction pair, CF from that add/sub, ZF/SF/PF from
  the result, OF 0; BEXTR with an immediate control as bmi1.sinc's BEXTR.
- LWP: user operations (LWPINS returns CF).
Every XOP and FMA4 instruction clears the destination's bits above the vector length.
"""
import json, re, sys, collections

PRED = ("HasFMA4", "HasXOP", "HasTBM", "HasLWP")
MAP = {"XOP8": "$(XOP_MAP8)", "XOP9": "$(XOP_MAP9)", "XOPA": "$(XOP_MAPA)", "TA": "$(VEX_0F3A)"}
PRE = {"PS": "$(VEX_PRE_NONE)", "PD": "$(VEX_PRE_66)"}
HEADER = ("# GENERATED by tools/gen_x86_xop.py from LLVM's X86 TableGen records (FMA4, XOP, TBM, LWP);\n"
          "# edit the generator, not this file. See specs/Ghidra/Processors/x86/README.md.\n")
CC = ["LT", "LE", "GT", "GE", "EQ", "NEQ", "FALSE", "TRUE"]


def bits(lst):
    return sum(b << i for i, b in enumerate(lst))


def load(path):
    J = json.load(open(path))
    out = []
    for n in J["!instanceof"]["X86Inst"]:
        r = J[n]
        if r.get("isPseudo") or r.get("isAsmParserOnly"):
            continue
        if r.get("isCodeGenOnly") and not r.get("ForceDisassemble"):
            continue
        ps = [p["def"] for p in r.get("Predicates", [])]
        tag = [p for p in ps if p in PRED]
        if not tag:
            continue
        asm = r["AsmString"]
        mn = re.sub(r"\{[lq]\}", "", asm.split()[0])
        out.append(dict(name=n, set=tag[0], mn=mn, form=r["Form"]["def"], map=r["OpMap"]["def"],
                        pre=r["OpPrefix"]["def"], opc=bits(r["Opcode"]), w=r["hasREX_W"], l=r["hasVEX_L"],
                        igl=r["ignoresVEX_L"], v4=r["hasVEX_4V"],
                        outs=[(a[1], a[0]["def"]) for a in r["OutOperandList"]["args"]],
                        ins=[(a[1], a[0]["def"]) for a in r["InOperandList"]["args"]]))
    out.sort(key=lambda r: r["name"])
    return out


def is_vec(t):
    return t.startswith(("VR128", "VR256", "FR32", "FR64"))


def is_mem(t):
    return t.endswith("mem")


def is_imm(t):
    return "imm" in t


def layout(r):
    """(role of each vector/GPR source in order: 'v' vvvv, 'rm', 'is4'), imm present."""
    f = r["form"]
    srcs = [(n, t) for n, t in r["ins"] if (is_vec(t) or is_mem(t) or t.startswith("GR")) and n not in ("src1_tied",)]
    imm = [t for n, t in r["ins"] if is_imm(t)]
    if r["set"] in ("HasTBM", "HasLWP"):
        return None, imm
    if f.endswith("Op4"):
        roles = ["v", "is4", "rm"]
    elif f.endswith("4VOp3"):
        roles = ["rm", "v"]
    elif r["v4"]:
        roles = ["v", "rm", "is4"]
    else:
        roles = ["rm"]
    return roles[:len(srcs)], imm


def vlen(r):
    if r["igl"]:
        return 128, True
    return (256 if r["l"] else 128), False


SCAL = {"ss": 4, "sd": 8}


def rm_table(r, bits_):
    m = re.search(r"(ss|sd)$", r["mn"])
    if m and r["set"] in ("HasFMA4", "HasXOP"):
        return "XmmReg2_m%d" % (8 * SCAL[m.group(1)])
    return "XmmReg2_m128" if bits_ == 128 else "YmmReg2_m256"


def operand_names(bits_):
    X = "Xmm" if bits_ == 128 else "Ymm"
    return {"dst": X + "Reg1", "v": "vexVVVV_%sReg" % X, "is4": "%s_imm8_7_4" % X}


# ---------------------------------------------------------------- semantics

def el(v, i, w):
    return "%s[%d,%d]" % (v, i * w, w)


def sem_vector(mn, a, b, c, nbytes):
    """Lines computing local r:nbytes from the source locals a, b, c; None for a user operation."""
    L = []
    m = re.match(r"vpcom(u?)([bwdq])$", mn)
    if mn == "vpcmov":
        return ["r = (a & c) | (b & ~c);"]
    m = re.match(r"vprot([bwdq])$", mn)
    if m:
        w = {"b": 8, "w": 16, "d": 32, "q": 64}[m.group(1)]
        if b is None:
            L.append("local n:1 = imm8 & %d;" % (w - 1))
        for i in range(128 // w):
            n = "n"
            if b is not None:
                n = "n%d" % i
                L.append("local %s:1 = %s & %d;" % (n, el("b", i, w).replace(",%d]" % w, ",8]"), w - 1))
            L.append("r[%d,%d] = (%s << zext(%s)) | (%s >> (%d - zext(%s)));" % (i * w, w, el("a", i, w), n, el("a", i, w), w, n))
        return L
    m = re.match(r"vpsh([la])([bwdq])$", mn)
    if m:
        w = {"b": 8, "w": 16, "d": 32, "q": 64}[m.group(2)]
        sh = ">>" if m.group(1) == "l" else "s>>"
        for i in range(128 // w):
            L.append("local n%d:1 = %s;" % (i, el("b", i, w).replace(",%d]" % w, ",8]")))
            L.append("local p%d:1 = n%d & %d;" % (i, i, w - 1))
            L.append("local q%d:1 = (0 - n%d) & %d;" % (i, i, w - 1))
            L.append("r[%d,%d] = (%s << zext(p%d)) * zext(n%d s>= 0) + (%s %s zext(q%d)) * zext(n%d s< 0);"
                     % (i * w, w, el("a", i, w), i, i, el("a", i, w), sh, i, i))
        return L
    m = re.match(r"vph(add|sub)(u?)([bwd])([bwdq])$", mn)
    if m:
        op, u, f, t = m.groups()
        fw, tw = ({"b": 8, "w": 16, "d": 32}[f], {"w": 16, "d": 32, "q": 64}[t])
        k = tw // fw
        ext = "zext" if u else "sext"
        for i in range(128 // tw):
            parts = ["%s(%s)" % (ext, el("a", i * k + j, fw)) for j in range(k)]
            if op == "add":
                expr = " + ".join("tmp:%d" % 0 if False else p for p in parts)
            else:
                expr = parts[0] + " - " + parts[1]
            L.append("local s%d:%d = %s;" % (i, tw // 8, expr))
            L.append("r[%d,%d] = s%d;" % (i * tw, tw, i))
        return L
    m = re.match(r"vp(macs|madcs)(s?)(ww|wd|dd|dql|dqh)$", mn)
    if m:
        kind, sat, t = m.groups()
        if kind == "madcs":                      # vpmadcswd / vpmadcsswd
            for i in range(4):
                L.append("local s%d:8 = sext(%s) * sext(%s) + sext(%s) * sext(%s) + sext(%s);" % (
                    i, el("a", 2 * i, 16), el("b", 2 * i, 16), el("a", 2 * i + 1, 16), el("b", 2 * i + 1, 16), el("c", i, 32)))
                L.append(store_sat("r", i, 32, "s%d" % i, 8, sat))
            return L
        if t == "ww":
            for i in range(8):
                L.append("local s%d:4 = sext(%s) * sext(%s) + sext(%s);" % (i, el("a", i, 16), el("b", i, 16), el("c", i, 16)))
                L.append(store_sat("r", i, 16, "s%d" % i, 4, sat))
        elif t == "wd":
            for i in range(4):
                L.append("local s%d:8 = sext(%s) * sext(%s) + sext(%s);" % (i, el("a", 2 * i + 1, 16), el("b", 2 * i + 1, 16), el("c", i, 32)))
                L.append(store_sat("r", i, 32, "s%d" % i, 8, sat))
        elif t == "dd":
            for i in range(4):
                L.append("local s%d:8 = sext(%s) * sext(%s) + sext(%s);" % (i, el("a", i, 32), el("b", i, 32), el("c", i, 32)))
                L.append(store_sat("r", i, 32, "s%d" % i, 8, sat))
        else:
            o = 0 if t == "dql" else 1
            for i in range(2):
                L.append("local s%d:16 = sext(%s) * sext(%s) + sext(%s);" % (i, el("a", 2 * i + o, 32), el("b", 2 * i + o, 32), el("c", i, 64)))
                L.append(store_sat("r", i, 64, "s%d" % i, 16, sat))
        return L
    return None


def store_sat(r, i, w, s, ssz, sat):
    if not sat:
        return "%s[%d,%d] = %s:%d;" % (r, i * w, w, s, w // 8)
    hi = (1 << (w - 1)) - 1
    lo = -(1 << (w - 1)) & ((1 << w) - 1)
    return ("%s[%d,%d] = (%s:%d) * zext((%s s<= sext(0x%x:%d)) && (%s s>= sext(0x%x:%d))) + 0x%x * zext(%s s> sext(0x%x:%d)) + 0x%x * zext(%s s< sext(0x%x:%d));"
            % (r, i * w, w, s, w // 8, s, hi, w // 8, s, lo, w // 8, hi, s, hi, w // 8, lo, s, lo, w // 8))


def vpcom_body(mn, cc):
    """The comparison of every element under the predicate the table cc exports (a constant, so the
    decompiler folds the selection away)."""
    m = re.match(r"vpcom(u?)([bwdq])$", mn)
    u, t = m.groups()
    w = {"b": 8, "w": 16, "d": 32, "q": 64}[t]
    s = "" if u else "s"
    L = []
    for i in range(128 // w):
        x, y = el("a", i, w), el("b", i, w)
        L.append("local lt%d:1 = %s %s< %s;" % (i, x, s, y))
        L.append("local gt%d:1 = %s %s< %s;" % (i, y, s, x))
        L.append("local eq%d:1 = %s == %s;" % (i, x, y))
        L.append(("r[%d,%d] = 0 - zext((%s == 0 && lt%d) || (%s == 1 && (lt%d || eq%d)) || (%s == 2 && gt%d) || "
                  "(%s == 3 && (gt%d || eq%d)) || (%s == 4 && eq%d) || (%s == 5 && !eq%d) || %s == 7);")
                 % (i * w, w, cc, i, cc, i, i, cc, i, cc, i, i, cc, i, cc, i, cc))
    return L


# ---------------------------------------------------------------- emission

def pattern_prefix(r, bits_, lig):
    p = ["$(VEX_NDS)", "$(VEX_LIG)" if lig else ("$(VEX_L256)" if bits_ == 256 else "$(VEX_L128)"), PRE[r["pre"]], MAP[r["map"]],
         "$(VEX_W1)" if r["w"] else "$(VEX_W0)"]
    return " & ".join(p)


def emit_vector(r, roles, imm, out, ops_declared):
    bits_, lig = vlen(r)
    nb = bits_ // 8
    names = operand_names(bits_)
    rmt = rm_table(r, bits_)
    tbl = dict(names, rm=rmt)
    mn = r["mn"]
    srcs = [tbl[x] for x in roles]
    has_v = "v" in roles
    pat = pattern_prefix(r, bits_, lig) + (" & " + names["v"] if has_v else " & vexVVVV=0") + "; byte=0x%02X; (%s & ZmmReg1) ... & %s" % (r["opc"], names["dst"], rmt)
    tail = ""
    if "is4" in roles:
        tail = "; " + names["is4"]
    elif imm:
        tail = "; imm8"
    scalar = rmt.startswith("XmmReg2_m") and rmt != "XmmReg2_m128"
    esz = int(rmt[9:]) // 8 if scalar else nb
    disp = [names["dst"]] + srcs
    if mn.startswith("vpcom"):
        tab = "xop" + mn
        body = ["local a:16 = %s;" % srcs[0], "local b:16 = %s;" % srcs[1], "local r:16 = 0;"] + vpcom_body(mn, tab) + ["ZmmReg1 = zext(r);"]
        out.append(":^%s %s^xopccop is %s; byte=0x%02X; (%s & ZmmReg1) ... & %s; %s & xopccop\n{\n    %s\n}\n" % (
            tab, ", ".join(disp), pattern_prefix(r, bits_, lig) + " & " + names["v"], r["opc"], names["dst"], rmt, tab, "\n    ".join(body)))
        return
    if mn in ("vpermil2ps", "vpermil2pd"):
        tail += " & imm8_3_0"
        disp.append("imm8_3_0")
    elif imm:
        disp.append("imm8")
    sem = None if scalar or mn.startswith(("vfm", "vfnm", "vfrcz", "vpperm", "vpermil2")) else sem_vector(mn, *(["a", "b" if len(srcs) > 1 or imm else None, "c"]), nb)
    if mn.startswith("vprot") and imm:
        sem = sem_vector(mn, "a", None, None, nb)
    body = []
    for v, s in zip("abc", srcs):
        body.append("local %s:%d = %s;" % (v, nb, s))
    if sem is not None:
        body.append("local r:%d = 0;" % nb)
        body += sem
        body.append("ZmmReg1 = zext(r);")
    else:
        op = re.sub(r"[^a-z0-9]", "", mn) + ("_fma4" if r["set"] == "HasFMA4" else "_xop")
        if op not in ops_declared:
            ops_declared.add(op)
            out.append("define pcodeop %s;" % op)
        args = ["a", "b", "c"][:len(srcs)]
        if mn.startswith("vpermil2"):
            args.append("imm8_3_0:1")
        if scalar:
            body = ["local %s:%d = %s:%d;" % (v, esz, s, esz) for v, s in zip("abc", srcs)]
            body.append("local r:%d = %s(%s);" % (esz, op, ", ".join(args)))
        else:
            body.append("local r:%d = %s(%s);" % (nb, op, ", ".join(args)))
        body.append("ZmmReg1 = zext(r);")
    out.append(":%s %s is %s%s\n{\n    %s\n}\n" % (mn.upper(), ", ".join(disp), pat, tail, "\n    ".join(body)))


TBM = {  # mnemonic: (opcode map, opcode, reg field, expression over s, add (1) or sub (-1))
    "blcfill": ("XOP9", 0x01, 1, "(s + 1) & s", 1), "blsfill": ("XOP9", 0x01, 2, "(s - 1) | s", -1),
    "blcs": ("XOP9", 0x01, 3, "(s + 1) | s", 1), "tzmsk": ("XOP9", 0x01, 4, "(s - 1) & ~s", -1),
    "blcic": ("XOP9", 0x01, 5, "(s + 1) & ~s", 1), "blsic": ("XOP9", 0x01, 6, "(s - 1) | ~s", -1),
    "t1mskc": ("XOP9", 0x01, 7, "(s + 1) | ~s", 1), "blcmsk": ("XOP9", 0x02, 1, "(s + 1) ^ s", 1),
    "blci": ("XOP9", 0x02, 6, "~(s + 1) | s", 1),
}


def emit_gpr(r, out, ops_declared, seen):
    mn = r["mn"]
    w64 = bool(r["w"])
    rs = "64" if w64 else "32"
    lm = "$(LONGMODE_ON) & " if w64 else ""
    wpat = "$(VEX_W1)" if w64 else "$(XOP_W32)"
    key = (mn, w64)
    if key in seen:
        return
    seen.add(key)
    if w64:
        out.append("@ifdef IA64")
        emit_gpr_body(r, mn, w64, rs, lm, wpat, out, ops_declared)
        out.append("@endif")
    else:
        emit_gpr_body(r, mn, w64, rs, lm, wpat, out, ops_declared)


def emit_gpr_body(r, mn, w64, rs, lm, wpat, out, ops_declared):
    if mn in TBM:
        mp, opc, reg, expr, add = TBM[mn]
        chk = "" if w64 else " & check_vexVVVV_r32_dest"
        out.append(":%s vexVVVV_r%s, rm%s is %s$(VEX_NDD) & $(VEX_LZ) & $(VEX_PRE_NONE) & %s & %s & vexVVVV_r%s%s; byte=0x%02X; reg_opcode=%d ... & rm%s\n{\n"
                   "    local s:%d = rm%s;\n    local d:%d = %s;\n    CF = %s;\n    vexVVVV_r%s = d;\n%s    resultflags(d);\n    OF = 0;\n}\n" % (
                       mn.upper(), rs, rs, lm, MAP[mp], wpat, rs, chk, opc, reg, rs, int(rs) // 8, rs, int(rs) // 8, expr,
                       "s == -1" if add > 0 else "s == 0", rs, "" if w64 else "    build check_vexVVVV_r32_dest;\n"))
        return
    if mn == "bextr":
        chk = "" if w64 else " & check_Reg%s_dest ..." % rs
        out.append(":BEXTR Reg%s, rm%s, imm32 is %s$(VEX_NONE) & $(VEX_LZ) & $(VEX_PRE_NONE) & $(XOP_MAPA) & %s & vexVVVV=0; byte=0x10; Reg%s ...%s & rm%s; imm32\n{\n"
                   "    local ctl:4 = imm32;\n    local start:1 = ctl[0,8];\n    local len:1 = ctl[8,8];\n    Reg%s = (rm%s >> start) & ((1 << len) - 1);\n%s"
                   "    ZF = (Reg%s == 0);\n    OF = 0;\n    CF = 0;\n}\n" % (rs, rs, lm, wpat, rs, chk, rs, rs, rs,
                                                                         "" if w64 else "    build check_Reg32_dest;\n", rs))
        return
    if mn in ("llwpcb", "slwpcb"):
        for o in (mn,):
            if o not in ops_declared:
                ops_declared.add(o)
                out.append("define pcodeop %s;" % o)
        reg = 0 if mn == "llwpcb" else 1
        body = "    llwpcb(Rmr%s);" % rs if mn == "llwpcb" else "    Rmr%s = slwpcb();" % rs
        out.append(":%s Rmr%s is %s$(VEX_NONE) & $(VEX_LZ) & $(VEX_PRE_NONE) & $(XOP_MAP9) & %s & vexVVVV=0; byte=0x12; mod=3 & reg_opcode=%d & Rmr%s\n{\n%s\n}\n" % (
            mn.upper(), rs, lm, wpat, reg, rs, body))
        return
    if mn in ("lwpins", "lwpval"):
        if mn not in ops_declared:
            ops_declared.add(mn)
            out.append("define pcodeop %s;" % mn)
        reg = 0 if mn == "lwpins" else 1
        call = "CF = lwpins(vexVVVV_r%s, rm32, imm32:4);" % rs if mn == "lwpins" else "lwpval(vexVVVV_r%s, rm32, imm32:4);" % rs
        out.append(":%s vexVVVV_r%s, rm32, imm32 is %s$(VEX_NDD) & $(VEX_LZ) & $(VEX_PRE_NONE) & $(XOP_MAPA) & %s & vexVVVV_r%s; byte=0x12; reg_opcode=%d ... & rm32; imm32\n{\n    %s\n}\n" % (
            mn.upper(), rs, lm, wpat, rs, reg, call))
        return
    raise SystemExit("no semantics for " + mn)


LOCAL = re.compile(r"\b(a|b|c|r|s|d|n|ctl|start|len|[npqs]\d+)\b(?![<>])")


def rename_locals(text):
    """Prefix the constructor-local names with x (ia.sinc already has symbols such as n1)."""
    out = []
    for blk in re.split(r"(\{\n.*?\n\})", text, flags=re.S):
        out.append(LOCAL.sub(lambda m: "x" + m.group(1), blk) if blk.startswith("{\n") else blk)
    return "".join(out)


def main():
    recs = load(sys.argv[1])
    out = [HEADER, "# a 32-bit TBM/LWP operand: XOP.W=0, or any W outside 64-bit mode", "@ifdef IA64",
           '@define XOP_W32 "(rexWprefix=0 | longMode=0)"', "@else", '@define XOP_W32 "rexWprefix"', "@endif", ""]
    # VPCOM* mnemonics by imm8[2:0], exporting the predicate (one constructor per form: telling
    # constructors apart by the byte after a variable-length ModRM operand is not possible)
    for t in ("b", "w", "d", "q", "ub", "uw", "ud", "uq"):
        for k, cc in enumerate(CC):
            u, e = ("u", t[1]) if len(t) == 2 else ("", t)
            out.append('xopvpcom%s: "VPCOM%s%s%s" is imm8=%d { export %d:1; }' % (t, cc, u.upper(), e.upper(), k, k))
            # imm8 above 7: LLVM prints the plain mnemonic and the immediate; the predicate is imm8[2:0]
            out.append('xopvpcom%s: "VPCOM%s" is imm8_0=%d & imm8_1=%d & imm8_2=%d { export %d:1; }' % (
                t, t.upper(), k & 1, (k >> 1) & 1, k >> 2, k))
    out.append('xopccop: "" is imm8_3_7=0 { }')
    out.append('xopccop: ", "^imm8 is imm8 { }')
    out.append("")
    ops = set()
    groups = collections.OrderedDict()
    seen_gpr = set()
    for r in recs:
        if r["set"] in ("HasTBM", "HasLWP"):
            continue
        roles, imm = layout(r)
        bits_, lig = vlen(r)
        key = (r["mn"], r["map"], r["opc"], r["w"], bits_, tuple(roles), bool(imm))
        groups.setdefault(key, (r, roles, imm))
    n = 0
    for key, (r, roles, imm) in groups.items():
        emit_vector(r, roles, imm, out, ops)
        n += 1
    for r in recs:
        if r["set"] in ("HasTBM", "HasLWP"):
            emit_gpr(r, out, ops, seen_gpr)
    open(sys.argv[2], "w").write(rename_locals("\n".join(out)))
    print("%d records, %d vector constructors (vpcom x8), %d TBM/LWP forms, %d user operations" % (len(recs), n, len(seen_gpr), len(ops)))


if __name__ == "__main__":
    main()
