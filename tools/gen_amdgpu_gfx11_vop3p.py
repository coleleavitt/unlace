#!/usr/bin/env python3
"""GFX11 VOP3P: packed 16-bit integer and float math, the dot products, fma_mix and WMMA.

Encoding (llvm-mc -mcpu=gfx1100 -show-encoding): word 0 bits 31-23 = 0x198, op 22-16, clamp 15,
op_sel_hi[2] 14, op_sel[0..2] 11-13, neg_hi 8-10, vdst 0-7; word 1 src2 18-26, src1 9-17,
src0 0-8, op_sel_hi[0..1] 27-28, neg_lo 29-31.  A packed source's low lane is its high half
when op_sel is set, and its high lane is its low half when op_sel_hi is clear.  Opcode
numbers from llvm-objdump over every VOP3P opcode; the p-code is written here.

usage: gen_amdgpu_gfx11_vop3p.py amdgcn_gfx11.slaspec amdgcn_gfx11_valu.sinc > amdgcn_gfx11_vop3p.sinc
       gen_amdgpu_gfx11_vop3p.py --gfx12 gfx12_wmma.txt amdgcn_gfx12.slaspec amdgcn_gfx12_valu.sinc > amdgcn_gfx12_vop3p.sinc
GFX12 moves the packed min/max to v_pk_min/max_num_f16 (27-28) and adds v_pk_minimum/maximum_f16
(29-30); its WMMA and SWMMAC opcodes and tile sizes come from 'amdgpu_gfx12_probe.py wmma'.
"""
import re
import sys

PK = {0: ('v_pk_mad_i16', 'a * b + c', 3), 1: ('v_pk_mul_lo_u16', 'a * b', 2), 2: ('v_pk_add_i16', 'a + b', 2),
      3: ('v_pk_sub_i16', 'a - b', 2), 4: ('v_pk_lshlrev_b16', 'b << (a & 15)', 2),
      5: ('v_pk_lshrrev_b16', 'b >> (a & 15)', 2), 6: ('v_pk_ashrrev_i16', 'b s>> (a & 15)', 2),
      7: ('v_pk_max_i16', 'sel:s>', 2), 8: ('v_pk_min_i16', 'sel:s<', 2), 9: ('v_pk_mad_u16', 'a * b + c', 3),
      10: ('v_pk_add_u16', 'a + b', 2), 11: ('v_pk_sub_u16', 'a - b', 2), 12: ('v_pk_max_u16', 'sel:>', 2),
      13: ('v_pk_min_u16', 'sel:<', 2), 14: ('v_pk_fma_f16', '(a f* b) f+ c', 3), 15: ('v_pk_add_f16', 'a f+ b', 2),
      16: ('v_pk_mul_f16', 'a f* b', 2), 17: ('v_pk_min_f16', 'sel:f<', 2), 18: ('v_pk_max_f16', 'sel:f>', 2)}
DOT = {19: ('v_dot2_f32_f16', 'dot2'), 22: ('v_dot4_i32_iu8', 'dot4'), 23: ('v_dot4_u32_u8', 'dot4'),
       24: ('v_dot8_i32_iu4', 'dot8'), 25: ('v_dot8_u32_u4', 'dot8'), 26: ('v_dot2_f32_bf16', 'dot2'),
       32: ('v_fma_mix_f32', 'fma_mix'), 33: ('v_fma_mixlo_f16', 'fma_mix'), 34: ('v_fma_mixhi_f16', 'fma_mix')}
# op: (mnemonic, src0/src1 VGPR count); the accumulator and result are 8 VGPRs in wave32
WMMA = {64: ('v_wmma_f32_16x16x16_f16', 8), 65: ('v_wmma_f32_16x16x16_bf16', 8),
        66: ('v_wmma_f16_16x16x16_f16', 8), 67: ('v_wmma_bf16_16x16x16_bf16', 8),
        68: ('v_wmma_i32_16x16x16_iu8', 4), 69: ('v_wmma_i32_16x16x16_iu4', 2)}
SRC = ['j0', 'j9', 'j18']


def lanes(i):
    """p-code shift amounts (constant at decode) for source i's low and high lane."""
    lo = '((v3opsel >> %d) & 1) * 16' % i
    hi = ('((j_omod >> %d) & 1) * 16' % i) if i < 2 else '((v3opsel >> 3) & 1) * 16'
    return lo, hi


def main():
    args = sys.argv[1:]
    wmma = {op: (mn, 8, n, n, 8, 0) for op, (mn, n) in WMMA.items()}
    if args[0] == '--gfx12':
        for k in (17, 18):
            del PK[k]
        PK.update({27: ('v_pk_min_num_f16', 'sel:f<', 2), 28: ('v_pk_max_num_f16', 'sel:f>', 2),
                   29: ('v_pk_minimum_f16', 'sel:f<', 2), 30: ('v_pk_maximum_f16', 'sel:f>', 2)})
        wmma = {}
        for line in open(args[1]):
            op, mn, d, a, b, c = line.split()
            # SWMMAC: the accumulator is D itself and the fourth operand is the sparsity index VGPR
            wmma[int(op)] = (mn, int(d), int(a), int(b), int(c), mn.startswith('v_swmmac'))
        args = args[2:]
    have = set(re.findall(r'define pcodeop (\w+);', ''.join(open(f).read() for f in args)))
    o = []
    w = o.append
    w('# Generated by tools/gen_amdgpu_gfx11_vop3p.py; edit the generator.')
    # 4- and 8-VGPR tuples at every start for the WMMA operands (the base spec has pairs)
    for n in (4, 8):
        for k in range(n):
            names = ['wv%d_%d' % (s, s + n - 1) for s in range(k, 256 - n + 1, n)]
            w('define register offset=0x%x size=%d [ %s ];' % (0x1000 + 4 * k, 4 * n, ' '.join(names)))
    w('define token wm0(32) wm_d = (0,7) wm_op = (16,22) wm_e9 = (23,31);')
    w('define token wm1(32) wm_a = (0,7) wm_av = (8,8) wm_b = (9,16) wm_bv = (17,17) wm_c = (18,25) wm_cv = (26,26);')
    ops_needed = {'dot2', 'dot4', 'dot8', 'fma_mix', 'wmma'} | ({'swmmac'} if any(v[5] for v in wmma.values()) else set())
    for nm in sorted(ops_needed - have):
        w('define pcodeop %s;' % nm)
    w('')
    for j in SRC:
        w('PK_%s: %s_vg is %s_v=1 & %s_vg { export %s_vg; }' % (j, j, j, j, j))
        w('PK_%s: S32_%s is %s_v=0 ... & S32_%s ... { export S32_%s; }' % (j, j, j, j, j))
    # tuple operands: one subtable per size and field, one constructor per starting VGPR
    sizes = sorted({x for v in wmma.values() for x in v[1:5]})
    for n in sizes:
        for f, fv in (('wm_a', 'wm_av'), ('wm_b', 'wm_bv'), ('wm_c', 'wm_cv'), ('wm_d', None)):
            for s in range(256 - n + 1):
                reg = {1: 'v%d' % s, 2: 'v%d_%d' % (s, s + 1)}.get(n, 'wv%d_%d' % (s, s + n - 1))
                cond = ('%s=1 & %s=%d' % (fv, f, s)) if fv else '%s=%d' % (f, s)
                disp = ('v%d' % s) if n == 1 else 'v[%d:%d]' % (s, s + n - 1)
                w('T%d_%s: "%s" is %s { export %s; }' % (n, f[3:], disp, cond, reg))
    w('')
    body = []
    for op, (mn, form, nsrc) in sorted(PK.items()):
        code = []
        for i in range(nsrc):
            lo, hi = lanes(i)
            x = 'abc'[i]
            code.append('s%s:4 = PK_%s; t%s:4 = s%s >> (%s); l%s:2 = t%s:2; t%s = s%s >> (%s); h%s:2 = t%s:2;'
                        % (x, SRC[i], x, x, lo, x, x, x, x, hi, x, x))
        if op >= 14:
            # float lanes: neg_lo (word 1) and neg_hi (word 0) flip the sign of each half
            for i in range(nsrc):
                x = 'abc'[i]
                code.append('l%s = l%s ^ (v3neg%d * 0x8000); h%s = h%s ^ (v3abs%d * 0x8000);' % (x, x, i, x, x, i))
        for p in 'lh':
            if form.startswith('sel:'):
                c = form[4:]
                code.append('%sr:2 = %sa; if (%sa %s %sb) goto <k%s>; %sr = %sb; <k%s>' % (p, p, p, c, p, p, p, p, p))
            else:
                code.append('%sr:2 = %s;' % (p, re.sub(r'\b([abc])\b', lambda m: p + m.group(1), form)))
        code.append('i0v8 = (zext(hr) << 16) | zext(lr);')
        srcs = ', '.join('PK_%s' % SRC[i] for i in range(nsrc))
        pat = ' & '.join('PK_%s ...' % SRC[i] for i in range(nsrc))
        m0 = ''.join(' & v3abs%d' % i for i in range(nsrc)) if op >= 14 else ''
        m1 = ''.join(' & v3neg%d ...' % i for i in range(nsrc)) if op >= 14 else ''
        body.append(':%s i0v8, %s is e9=0x198 & vop3op=%d & i0v8 & v3opsel%s ; %s & j_omod ...%s { %s }'
                    % (mn, srcs, op, m0, pat, m1, ' '.join(code)))
    for op, (mn, fn) in sorted(DOT.items()):
        body.append(':%s i0v8, PK_j0, PK_j9, PK_j18 is e9=0x198 & vop3op=%d & i0v8 ; PK_j0 ... & PK_j9 ... & PK_j18 ... '
                    '{ i0v8 = %s(PK_j0, PK_j9, PK_j18); }' % (mn, op, fn))
    for op, (mn, d, a, b, c, sparse) in sorted(wmma.items()):
        ops = 'T%d_d, T%d_a, T%d_b, T%d_c' % (d, a, b, c)
        pat = 'wm_e9=0x198 & wm_op=%d & T%d_d ; T%d_a & T%d_b & T%d_c' % (op, d, a, b, c)
        if sparse:
            sem = 'T%d_d = swmmac(T%d_a, T%d_b, T%d_d, T%d_c);' % (d, a, b, d, c)
        else:
            sem = 'T%d_d = wmma(T%d_a, T%d_b, T%d_c);' % (d, a, b, c)
        body.append(':%s %s is %s { %s }' % (mn, ops, pat, sem))
    w('\n'.join(body))
    print('\n'.join(o))


main()
