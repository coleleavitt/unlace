//! Port of `decompiler/cpp/unlace_phases.{cc,hh}` — the unlace stage registry.
//!
//! This is the normative stage model made physical: pure static data + lookups
//! (no pipeline linkage, no output effect). It encodes
//!
//!   - the stages themselves ([`UnlacePhase`]): the P0 knowledge plane + S1..S9,
//!     with Band B (S3..S6) membership, plus the `Infra` registry-only
//!     pseudo-stage for orchestration units;
//!   - the four static tables transcribed from `unlace_stages.cc`:
//!     [`GROUP_TABLE`] (action/rule groups), [`SUBPHASE_TABLE`] (named
//!     decision points), [`SURFACE_TABLE`] (console/option surfaces), and
//!     [`SETTABLE_TABLE`] (LLM/agent-settable assertions);
//!   - the lookup API (`unlace_num_groups`/`unlace_group_by_index`/`lookup_group`
//!     and siblings — the idiomatic equivalents of the C++ `unlaceNumGroups` /
//!     `unlaceGroupByIndex` / `unlaceLookupGroup` family).
//!
//! Per ADR 0006 the four tables and the typed [`OptionValues`] struct are
//! **generated by `build.rs` from `phases.toml`** (the single source of truth):
//! the generated code is `include!`d below. The catalog JSON emitter
//! ([`emit_settable_json`]) is hand-written to be byte-compatible with
//! `unlace_console.cc unlaceEmitSettableJson` (ADR 0006); `tests/catalog_bytecompat.rs`
//! string-matches it against the C++ binary's captured output.

use core::fmt;
use std::borrow::Cow;

/// (unlace) The stages of the unlace stage model (`docs/phases.md`).
///
/// `Infra` is the registry-only pseudo-stage for orchestration units
/// (ActionStart/Stop, the cleanup pool's termination policy) that own no model
/// artifact — the C++ `kstage_infra = -1`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum UnlacePhase {
    /// Orchestration / termination policy (no artifact) — C++ `kstage_infra`.
    Infra,
    /// Knowledge & Configuration Plane (orthogonal) — C++ `kstage_p0`.
    P0,
    /// Image & Code Partition — C++ `kstage_s1`.
    P1,
    /// Flow & Op-Graph Recovery — C++ `kstage_s2`.
    P2,
    /// Definition Web (Band B) — C++ `kstage_s3`.
    P3,
    /// Call & Prototype Model (Band B) — C++ `kstage_s4`.
    P4,
    /// Value & Type Facts (Band B) — C++ `kstage_s5`.
    P5,
    /// Variable & Storage Model (Band B) — C++ `kstage_s6`.
    P6,
    /// Region Hierarchy — C++ `kstage_s7`.
    P7,
    /// Structured AST & Goto Quality — C++ `kstage_s8`.
    P8,
    /// Surface Rendering & Refinement — C++ `kstage_s9`.
    P9,
}

impl UnlacePhase {
    /// The numeric value of the stage matching the C++ `enum UnlacePhase` (infra
    /// is -1, P0 is 0, S1..S9 are 1..9).
    pub fn index(self) -> i32 {
        match self {
            UnlacePhase::Infra => -1,
            UnlacePhase::P0 => 0,
            UnlacePhase::P1 => 1,
            UnlacePhase::P2 => 2,
            UnlacePhase::P3 => 3,
            UnlacePhase::P4 => 4,
            UnlacePhase::P5 => 5,
            UnlacePhase::P6 => 6,
            UnlacePhase::P7 => 7,
            UnlacePhase::P8 => 8,
            UnlacePhase::P9 => 9,
        }
    }

    /// "P0".."P9" (or "--" for infra) — C++ `unlaceStageCode`.
    pub fn code(self) -> &'static str {
        PHASE_CODES[self.code_index()]
    }

    /// Long stage name — C++ `unlaceStageName`.
    pub fn name(self) -> &'static str {
        PHASE_NAMES[self.code_index()]
    }

    /// The artifact the stage owns — C++ `unlaceStageArtifact`.
    pub fn artifact(self) -> &'static str {
        PHASE_ARTIFACTS[self.code_index()]
    }

    /// true for S3..S6 — C++ `unlaceStageInBandB`.
    pub fn in_band_b(self) -> bool {
        // The enum ordering of P3..P6 mirrors the numeric one (infra=-1 sorts below P0).
        let i = self.index();
        (UnlacePhase::P3.index()..=UnlacePhase::P6.index()).contains(&i)
    }

    /// Index into the `STAGE_*` arrays: 0..=9 for P0..S9, 10 for infra.
    fn code_index(self) -> usize {
        match self {
            UnlacePhase::Infra => 10,
            other => other.index() as usize,
        }
    }

    /// Parse "P3"/"p3" (or the legacy "S3"/"s3") into the phase — C++ `unlaceStageFromCode`.
    ///
    /// Returns `None` on a malformed code (the C++ returns `false` and leaves
    /// `res` unset).
    pub fn from_code(code: &str) -> Option<UnlacePhase> {
        if code.len() != 2 {
            return None;
        }
        let bytes = code.as_bytes();
        let c0 = bytes[0];
        let c1 = bytes[1];
        if (c0 == b'p' || c0 == b'P') && c1 == b'0' {
            return Some(UnlacePhase::P0);
        }
        // "P1".."P9" primary; the pre-rename "S1".."S9" spellings stay
        // accepted as input aliases (kassert scripts, older tooling).
        if (c0 == b'p' || c0 == b'P' || c0 == b's' || c0 == b'S') && (b'1'..=b'9').contains(&c1) {
            return Some(match c1 - b'0' {
                1 => UnlacePhase::P1,
                2 => UnlacePhase::P2,
                3 => UnlacePhase::P3,
                4 => UnlacePhase::P4,
                5 => UnlacePhase::P5,
                6 => UnlacePhase::P6,
                7 => UnlacePhase::P7,
                8 => UnlacePhase::P8,
                9 => UnlacePhase::P9,
                _ => unreachable!("c1 guaranteed in 1..=9"),
            });
        }
        None
    }
}

/// (unlace) Assertion strength (`docs/history/stage-model.md` section 2) — C++ `UnlaceStrength`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum UnlaceStrength {
    /// No assertion exists (fully LATENT decision) — C++ `kstrength_none`.
    None,
    /// Biases inference — C++ `kstrength_hint`.
    Hint,
    /// Blocks inference unconditionally — C++ `kstrength_hard`.
    Hard,
}

impl UnlaceStrength {
    /// "HARD"/"HINT"/"NONE" — the catalog rendering of a strength.
    pub fn catalog_code(self) -> &'static str {
        match self {
            UnlaceStrength::Hard => "HARD",
            UnlaceStrength::Hint => "HINT",
            UnlaceStrength::None => "NONE",
        }
    }
}

