#!/usr/bin/env python3
"""GFX9 SDWA and DPP forms of the VOP1, VOP2 and VOPC constructors (GFX9 and, spliced in, CDNA).

Layouts from llvm-mc -mcpu=gfx900 -show-encoding: src0 = 0xf9 selects SDWA and 0xfa DPP, and a
second dword follows.
  SDWA: src0 0-7, dst_sel 8-10 (BYTE_0-3, WORD_0/1, DWORD), dst_unused 11-12 (PAD, SEXT,
    PRESERVE), clamp 13, omod 14-15 (VOPC: sdst 8-14, sd 15), src0_sel 16-18, sext 19, neg 20,
    abs 21, s0 23 (src0 is an SGPR), src1_sel 24-26, sext 27, neg 28, abs 29, s1 31.
  DPP: src0 0-7, dpp_ctrl 8-16, bound_ctrl 19, src0 neg/abs 20/21, src1 neg/abs 22/23,
    bank_mask 24-27, row_mask 28-31.
Each e32 constructor with 32-bit operands is cloned: SDWA reads each source's selected byte or
word (zero- or sign-extended, then neg/abs) and writes the result through dst_sel/dst_unused (a
VOPC writes VCC or the SGPR pair); DPP reads src0 through the dpp_mov user-op (the lane exchange
the one-lane model cannot express) with the DPP neg/abs modifiers.  VOPC has no DPP form on GFX9.

usage: gen_amdgpu_gfx9_dpp.py amdgcn_gfx9.slaspec [include ...] > amdgcn_gfx9_dpp.sinc
"""
import re
import sys

SEL = ['BYTE_0', 'BYTE_1', 'BYTE_2', 'BYTE_3', 'WORD_0', 'WORD_1', 'DWORD']
UNUSED = ['UNUSED_PAD', 'UNUSED_SEXT', 'UNUSED_PRESERVE']
SKIP = re.compile(r'\b(V64F?_i0|i9_vp|i17_vp|i17_lo7|i0_vg|litv|VN32_i0)\b')


def groups(lines):
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.startswith(':'):
            i += 1
            continue
        g = [line]
        depth = line.count('{') - line.count('}')
        i += 1
        while i < len(lines) and depth > 0:
            g.append(lines[i])
            depth += lines[i].count('{') - lines[i].count('}')
            i += 1
        yield '\n'.join(g)


def selcode(var, sel, sext):
    """p-code turning the 32-bit var into its selected field, extended to 32 bits."""
    if sel == 6:
        return ''
    bits, sh = (8, 8 * sel) if sel < 4 else (16, 16 * (sel - 4))
    b = bits // 8
    return '%s = %s >> %d; h%d:%d = %s:%d; %s = %s(h%d);' % (var, var, sh, b, b, var, b, var,
                                                          'sext' if sext else 'zext', b)


def main():
    text = ''.join(open(f).read() for f in sys.argv[1:])
    s4 = re.search(r'define register offset=0x0+ size=4 \[([^\]]*)\]', text).group(1).split()
    s8 = re.search(r'define register offset=0x0+ size=8 \[([^\]]*)\]', text).group(1).split()
    o = []
    w = o.append
    w('# Generated by tools/gen_amdgpu_gfx9_dpp.py; edit the generator.')
    w('define register offset=0x4200 size=4 [ sdwa_d ];')
    w('define token sdwa(32) sw_src0 = (0,7) sw_src0s = (0,7) sw_dsel = (8,10) sw_dun = (11,12) sw_clamp = (13,13)'
      ' sw_omod = (14,15) sw_sdst = (8,14) sw_sd = (15,15) sw_s0sel = (16,18) sw_s0sext = (19,19) sw_s0neg = (20,20)'
      ' sw_s0abs = (21,21) sw_s0 = (23,23) sw_s1sel = (24,26) sw_s1sext = (27,27) sw_s1neg = (28,28)'
      ' sw_s1abs = (29,29) sw_s1 = (31,31);')
    w('define token dpp(32) dp_src0 = (0,7) dp_ctrl = (8,16) dp_bound = (19,19) dp_s0neg = (20,20) dp_s0abs = (21,21)'
      ' dp_s1neg = (22,22) dp_s1abs = (23,23) dp_bank = (24,27) dp_row = (28,31);')
    w('attach variables [ sw_src0 dp_src0 ] [ %s ];' % ' '.join('v%d' % i for i in range(256)))
    w('attach variables [ sw_src0s ] [ %s ];' % ' '.join(s4 + ['_'] * (256 - len(s4))))
    if 'define pcodeop dpp_mov;' not in text:
        w('define pcodeop dpp_mov;')
    # source 0: register (VGPR, or SGPR with s0), then select/extend and neg/abs
    for k in (0, 1):
        f = 'sw_s%d' % k
        reg, regs = ('sw_src0', 'sw_src0s') if k == 0 else ('i9_vg', None)
        anch = '' if k == 0 else 'i9_vg ; '
        for float16 in (0, 1):
            nb = 0x8000 if float16 else 0x80000000
            t = 'SW%d%s' % (k, 'h' if float16 else '')
            for sel in range(7):
                for sx in (0, 1):
                    for neg in (0, 1):
                        for ab in (0, 1):
                            for sreg in ((0, 1) if k == 0 else (0, 1)):
                                if k == 1 and sreg:
                                    continue
                                r = (regs if sreg else reg)
                                if k == 1:
                                    rdisp = 'i9_vg'
                                    pat = 'i9_vg ; %ssel=%d & %ssext=%d & %sneg=%d & %sabs=%d & %s=0' % (f, sel, f, sx, f, neg, f, ab, f)
                                else:
                                    rdisp = r
                                    pat = '%s & %ssel=%d & %ssext=%d & %sneg=%d & %sabs=%d & %s=%d' % (
                                        r, f, sel, f, sx, f, neg, f, ab, f, sreg)
                                disp = rdisp
                                if sx:
                                    disp = '"sext("^%s^")"' % disp
                                if ab:
                                    disp = '"|"^%s^"|"' % disp
                                if neg:
                                    disp = '"-"^%s' % disp
                                code = 't:4 = %s; %s' % (r, selcode('t', sel, sx))
                                if ab:
                                    code += ' t = t & 0x%x;' % (0xffffffff ^ nb)
                                if neg:
                                    code += ' t = t ^ 0x%x;' % nb
                                w('%s: %s is %s { %s export t; }' % (t, disp, pat, code))
    # integer operations: neg/abs do not apply (LLVM does not print them)
    for sel in range(7):
        for sx in (0, 1):
            for sreg in (0, 1):
                r = 'sw_src0s' if sreg else 'sw_src0'
                disp = '"sext("^%s^")"' % r if sx else r
                w('SW0i: %s is %s & sw_s0sel=%d & sw_s0sext=%d & sw_s0=%d { t:4 = %s; %s export t; }' % (
                    disp, r, sel, sx, sreg, r, selcode('t', sel, sx)))
            disp = '"sext("^i9_vg^")"' if sx else 'i9_vg'
            w('SW1i: %s is i9_vg ; sw_s1sel=%d & sw_s1sext=%d & sw_s1=0 { t:4 = i9_vg; %s export t; }' % (
                disp, sel, sx, selcode('t', sel, sx)))
    w('DP0i: dp_src0 is dp_src0 & dp_ctrl { c:2 = dp_ctrl; t:4 = dpp_mov(dp_src0, c); export t; }')
    w('DP1i: i9_vg is i9_vg ; dp_s1neg { export i9_vg; }')
    # SGPR src1 (s1) and the anchored src1 for the root
    for sel in range(7):
        w('SS0: " src0_sel:%s" is sw_s0sel=%d { }' % (SEL[sel], sel))
        w('SS1: " src1_sel:%s" is sw_s1sel=%d { }' % (SEL[sel], sel))
    for d in range(7):
        for u in range(3):
            w('SDS: " dst_sel:%s dst_unused:%s" is sw_dsel=%d & sw_dun=%d { }' % (SEL[d], UNUSED[u], d, u))
            if d == 6:
                code = 'i17_vg = sdwa_d;'
            else:
                bits, sh = (8, 8 * d) if d < 4 else (16, 16 * (d - 4))
                mask = ((1 << bits) - 1) << sh
                v = 'v:4 = (sdwa_d << %d) & 0x%x;' % (sh, mask)
                if u == 0:
                    code = v + ' i17_vg = v;'
                elif u == 1:
                    code = v + ' i17_vg = v s>> 0; s:4 = sdwa_d << %d; s = s s>> %d; i17_vg = (s << %d) | (v & 0x%x);' % (
                        32 - bits, 32 - bits, sh, ((1 << (sh + bits)) - 1))
                    code = v + ' s:4 = sdwa_d << %d; s = s s>> %d; s = s << %d; i17_vg = s | (v & 0x%x);' % (
                        32 - bits, 32 - bits, sh, (1 << sh) - 1 if sh else 0)
                else:
                    code = v + ' i17_vg = (i17_vg & 0x%x) | v;' % (0xffffffff ^ mask)
            w('SWD: is i17_vg ; sw_dsel=%d & sw_dun=%d { %s }' % (d, u, code))
    w('SMOD: is sw_clamp=0 & sw_omod=0 { }')
    for c in (0, 1):
        for om, s in enumerate(['', ' mul:2', ' mul:4', ' div:2']):
            if c or om:
                w('SMOD: "%s%s" is sw_clamp=%d & sw_omod=%d { }' % (' clamp' if c else '', s, c, om))
    w('SWC: "vcc" is sw_sd=0 { export vcc; }')
    for s in range(0, 106, 2):
        w('SWC: "%s" is sw_sd=1 & sw_sdst=%d { export %s; }' % ('s[%d:%d]' % (s, s + 1), s, s8[s // 2]))
    # DPP
    def ctrl(c):
        if c < 0x100:
            return 'quad_perm:[%d,%d,%d,%d]' % (c & 3, (c >> 2) & 3, (c >> 4) & 3, (c >> 6) & 3)
        for base, nm in ((0x100, 'row_shl'), (0x110, 'row_shr'), (0x120, 'row_ror')):
            if base < c <= base + 15:
                return '%s:%d' % (nm, c - base)
        return {0x130: 'wave_shl:1', 0x134: 'wave_rol:1', 0x138: 'wave_shr:1', 0x13c: 'wave_ror:1',
                0x140: 'row_mirror', 0x141: 'row_half_mirror', 0x142: 'row_bcast:15', 0x143: 'row_bcast:31'}.get(c)
    for c in range(0x144):
        n = ctrl(c)
        if n:
            w('DPC: " %s" is dp_ctrl=%d { }' % (n, c))
    w('DPB: is dp_bound=0 { }')
    w('DPB: " bound_ctrl:1" is dp_bound=1 { }')
    for float16 in (0, 1):
        nb = 0x8000 if float16 else 0x80000000
        h = 'h' if float16 else ''
        for neg in (0, 1):
            for ab in (0, 1):
                d0 = 'dp_src0'
                d1 = 'i9_vg'
                if ab:
                    d0, d1 = '"|"^%s^"|"' % d0, '"|"^%s^"|"' % d1
                if neg:
                    d0, d1 = '"-"^%s' % d0, '"-"^%s' % d1
                mod = (' t = t & 0x%x;' % (0xffffffff ^ nb) if ab else '') + (' t = t ^ 0x%x;' % nb if neg else '')
                w('DP0%s: %s is dp_src0 & dp_ctrl & dp_s0neg=%d & dp_s0abs=%d { c:2 = dp_ctrl; t:4 = dpp_mov(dp_src0, c); %s export t; }'
                  % (h, d0, neg, ab, mod))
                w('DP1%s: %s is i9_vg ; dp_s1neg=%d & dp_s1abs=%d { t:4 = i9_vg;%s export t; }' % (h, d1, neg, ab, mod))
    print('\n'.join(o + [''] + clones(text)))


def clones(text):
    """The SDWA and DPP copies of the 32-bit VOP1, VOP2 and VOPC constructors in text."""
    body = []
    for c in groups(text.split('\n')):
        m = re.match(r':(\S+) (.*?) is (e1=0|e7=0x3e|e7=0x3f) (.*?)\{(.*)\}\s*$', c, re.S)
        if not m or SKIP.search(c) or 'V32_i0' not in c:
            continue
        mn, disp, enc, pat, sem = m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)
        fo = re.search(r'\b(vop1op|vop2op|vopcop)=(\d+)', pat)
        if not fo:
            continue
        vopc = enc == 'e7=0x3e'
        base = re.sub(r'_e32$', '', mn)
        f16 = bool(re.search(r'_[fiub]16\b|_f16_|_[iu]16_', base))
        hsfx = 'h' if f16 else ''
        if not re.search(r'_f(16|32|64)', base) and base != 'v_cndmask_b32':
            hsfx = 'i'     # integer: no neg/abs
        h1 = 'i' if base.startswith('v_ldexp') else hsfx    # ldexp's exponent is an integer
        fields = [x for x in ('i17_vg', 'i9_vg') if re.search(r'\b%s\b' % x, pat)]
        word0 = '%s & %s=%s & %s & i0_v=0' % (enc, fo.group(1), fo.group(2), ' & '.join(fields) if fields else 'i0_x')
        has1 = 'i9_vg' in disp
        # SDWA
        d = disp.replace('V32_i0', 'SW0' + hsfx).replace('i9_vg', 'SW1' + h1)
        sm = sem.replace('V32_i0', 'SW0' + hsfx)
        sm = re.sub(r'\bi9_vg\b', 'SW1' + h1, sm)
        if vopc:
            d = d.replace('"vcc"', 'SWC')
            sm = re.sub(r'\bvcc\s*=(?!=)', 'SWC =', sm)
            suffix = '^SS0' + ('^SS1' if has1 else '')
            w1 = 'SW0%s & SWC & SS0%s' % (hsfx, ' & SS1' if has1 else '')
            extra = ''
        else:
            sm = re.sub(r'\bi17_vg\s*=(?!=)', 'sdwa_d =', sm) + ' build SWD;'
            suffix = '^SMOD^SDS^SS0' + ('^SS1' if has1 else '')
            w1 = 'SW0%s & SMOD & SDS & SS0%s' % (hsfx, ' & SS1' if has1 else '')
            extra = ' & SWD'
        if has1:
            extra += ' & SW1' + h1
        body.append(':%s_sdwa %s%s is (%s & i0_x=249 ; %s)%s { %s }' % (base, d, suffix, word0, w1, extra, sm.strip()))
        if vopc:
            continue
        # DPP
        d = disp.replace('V32_i0', 'DP0' + hsfx).replace('i9_vg', 'DP1' + h1)
        sm = sem.replace('V32_i0', 'DP0' + hsfx)
        sm = re.sub(r'\bi9_vg\b', 'DP1' + h1, sm)
        extra = (' & DP1' + h1) if has1 else ''
        body.append(':%s_dpp %s^DPC^" row_mask:"^dp_row^" bank_mask:"^dp_bank^DPB is (%s & i0_x=250 ; DP0%s & DPC & dp_row & dp_bank & DPB)%s { %s }'
                    % (base, d, word0, hsfx, extra, sm.strip()))
    return body


if __name__ == '__main__':
    main()
