//! The Epiphany language decompiles 16- and 32-bit instructions built with epiphany-elf-as.
use crate::common;
use common::{run_kuna, scratch_file};

#[test]
fn epiphany_mixed_width_decompiles() {
    let bin = scratch_file("epiphany_mixed_width_decompiles", "bin");
    std::fs::write(
        &bin,
        [
            0xba, 0x40, 0x70, 0x04, 0x3a, 0x04, 0x4f, 0x19, 0x02, 0x04, 0xba, 0x00,
            0x4f, 0x19, 0x02, 0x04, 0x5c, 0xd5, 0x00, 0x27, 0xdc, 0x14, 0x00, 0x84,
            0xef, 0x00, 0x02, 0x80, 0x43, 0x21, 0xf0, 0xf1, 0x4c, 0x61, 0x00, 0x10,
            0x9a, 0x01, 0x1f, 0x00, 0x0a, 0x02, 0x8b, 0x86, 0x22, 0x41, 0x0b, 0x8f,
            0x62, 0x55, 0x1f, 0x02, 0x0a, 0x01, 0xcc, 0x14, 0x00, 0x84, 0x4c, 0xd5,
            0x00, 0x24, 0x1b, 0xb4, 0x01, 0x24, 0x4f, 0x19, 0x02, 0x04,
        ],
    )
    .unwrap();
    let (stdout, stderr, code) = run_kuna(&[
        "decompile",
        bin.to_str().unwrap(),
        "0x1010",
        "--raw-image",
        "--target",
        "epiphany:LE:32:default",
        "--base",
        "0x1000",
    ]);
    assert_eq!(code, 0, "{stderr}");
    let lower = stdout.to_lowercase();
    assert!(!lower.contains("unimplemented"), "{stdout}");
    assert!(!lower.contains("bad instruction"), "{stdout}");
    assert!(stdout.contains("sub_1000(a0,10)"), "{stdout}");
    assert!(stdout.contains("((int *)a0)[2]"), "{stdout}");
    assert!(stdout.contains("0x56781234"), "{stdout}");
}
