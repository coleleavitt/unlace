#!/usr/bin/env python3
"""Generate the AVX-512 {sae}/{rc} register-form constructors of the x86 languages.

Usage:
  llvm-tblgen --dump-json -I <llvm>/include -I <llvm>/lib/Target/X86 <llvm>/lib/Target/X86/X86.td -o x86.json
  tools/gen_x86_avx512_round.py x86.json specs/Ghidra/Processors/x86/data/languages

For every EVEX register-form record with EVEX.b (LLVM's rrb/rrib records: {sae} or embedded
rounding {rn-sae}/{rd-sae}/{ru-sae}/{rz-sae}) outside AVX10.2 and APX, the matching 512-bit or
scalar register constructor of avx512.sinc / avx512_manual.sinc is copied with evexRcOn=1 (set by
the EVEX.b pre-parse in ia.sinc, which also forces L'L to 512 bits and keeps the rounding mode in
evexRcMode), its register-or-memory operand narrowed to the register, and the rounding operand
printed where LLVM prints it. The copies go to avx512_round.sinc. Records with no matching base
constructor are listed on stderr.
"""
import json, re, sys, collections

MAP = {"TB": "$(VEX_0F)", "T8": "$(VEX_0F38)", "TA": "$(VEX_0F3A)", "T_MAP5": "$(VEX_MAP5)", "T_MAP6": "$(VEX_MAP6)"}
PRE = {"PS": "$(VEX_PRE_NONE)", "PD": "$(VEX_PRE_66)", "XS": "$(VEX_PRE_F3)", "XD": "$(VEX_PRE_F2)"}
SKIP = ("HasEGPR", "HasNDD", "HasNF", "HasCCMP", "HasCF", "HasZU")
HEADER = ("# GENERATED by tools/gen_x86_avx512_round.py from avx512.sinc, avx512_manual.sinc, avx10_2.sinc and LLVM's X86\n"
          "# TableGen records; edit the generator, not this file.\n")


def bits(l):
    return sum(b << i for i, b in enumerate(l))


def llvm_records(path):
    J = json.load(open(path))
    out = collections.OrderedDict()
    for n in sorted(J["!instanceof"]["X86Inst"]):
        r = J[n]
        if r.get("isPseudo") or r.get("isCodeGenOnly") or r.get("isAsmParserOnly"):
            continue
        if r["OpEnc"]["def"] != "EncEVEX" or not r["hasEVEX_B"] or "Mem" in r["Form"]["def"] or r["OpMap"]["def"] == "T_MAP4":
            continue
        ps = [p["def"] for p in r.get("Predicates", [])]
        if any(p.startswith("HasAVX10") or p in SKIP for p in ps):
            continue
        if r["hasEVEX_K"] or r["hasEVEX_Z"]:
            continue
        asm = r["AsmString"]
        mn = re.sub(r"\$\{cc\}|\{[xyz]\}$", "", asm.split()[0]).upper()
        intel = asm.split("|", 1)[1].rsplit("}", 1)[0] if "|" in asm else ""
        scalar = not re.search(r"Z(128|256)?(rr|rm|r_|m)", n) or not re.search(r"Z(r|rr)", n)
        key = (mn, MAP.get(r["OpMap"]["def"]), PRE.get(r["OpPrefix"]["def"]), r["hasREX_W"], r["IgnoresW"],
               "%02x" % bits(r["Opcode"]))
        toks = [t.strip() for t in intel.split(",")]
        pos = next((i for i, t in enumerate(toks) if t in ("{sae}", "$rc")), len(toks))
        out.setdefault(key, (n, bool(r["hasEVEX_RC"]), pos, len(toks)))
    return out


def ctors(text):
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        if lines[i].startswith(":"):
            j = i
            while j < len(lines) and lines[j].rstrip() != "}":
                j += 1
            yield "\n".join(lines[i:j + 1])
            i = j + 1
        else:
            i += 1


def split_top(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [x.strip() for x in out]


COMBINED = re.compile(r"\b([XYZ])mmReg2_m\w+")
GPRRM = re.compile(r"\brm(32|64)\b")


def round_copy(c, rc, pos, ntok):
    head, rest = re.split(r"\s+is\s+", c, maxsplit=1)
    brace = rest.find("{")
    pat, body = rest[:brace], rest[brace:]
    pat = re.sub(r"\n\[[^\]]*\][^\n]*", "", pat).strip()
    if not COMBINED.search(pat) and not GPRRM.search(pat) and "mod=3" not in pat.replace(" ", ""):
        return None
    m = re.match(r"(:\^?\S+)(.*)", head)
    mn, ops = m.group(1), m.group(2).strip()
    operands = [GPRRM.sub(r"Rmr\1", COMBINED.sub(lambda mm: mm.group(1) + "mmReg2", o)) for o in (split_top(ops) if ops else [])]
    rop = "avx512Rc" if rc else '"{sae}"'
    k = min(pos, len(operands))
    operands.insert(k, rop)
    ctx, sep, tail = pat.partition(";")
    ctx = ctx.rstrip() + " & evexRcOn=1" + (" & avx512Rc" if rc else "")
    parts = tail.split(";")
    # parts[0] is " byte=0xNN" (the opcode); parts[1] the ModRM part; any later part is an immediate
    for idx in range(1, len(parts)):
        p = parts[idx]
        if COMBINED.search(p) or GPRRM.search(p) or "Reg1" in p or "Reg2" in p or "KReg" in p:
            p = GPRRM.sub(r"Rmr\1", COMBINED.sub(lambda mm: mm.group(1) + "mmReg2", p)).replace(" ... &", " &").replace("...", "")
            if not re.search(r"\bmod\s*=\s*(3|0x3|0b11)\b", p):
                p = " mod=3 & " + p.strip()
            parts[idx] = p
            break
    pat = ctx + sep + ";".join(parts)
    body = GPRRM.sub(r"Rmr\1", COMBINED.sub(lambda mm: mm.group(1) + "mmReg2", body))
    return "%s %s is %s\n%s" % (mn, ", ".join(operands), pat, body)


def main():
    recs = llvm_records(sys.argv[1])
    lang = sys.argv[2]
    found = {}
    out = [HEADER, "@ifndef IA16", ""]
    # avx10_2.sinc: LLVM tags a few AVX10.2 {sae} records (VMINMAXP[DHS]Zrrib) HasAVX512 only
    for name in ("avx512.sinc", "avx512_manual.sinc", "avx10_2.sinc"):
        text = open("%s/%s" % (lang, name)).read()
        for c in ctors(text):
            first = c.split("\n")[0]
            if "$(EVEX_NONE)" not in c or "evexB=" in first or not re.search(r"\$\((EVEX_L512|VEX_LIG|EVEX_LLIG)\)", first):
                continue
            mn = re.match(r":\^?(\S+?)(_mon)?[\s^]", first)
            if not mn:
                continue
            mnem = mn.group(1).upper()
            pre = (re.search(r"\$\(VEX_PRE_\w+\)", first) or [None])[0]
            mp = (re.search(r"\$\(VEX_(0F|0F38|0F3A|MAP5|MAP6)\)", first) or [None])[0]
            w = "1" if "$(VEX_W1)" in first else ("0" if "$(VEX_W0)" in first else "x")
            op = re.search(r";\s*byte=0x([0-9A-Fa-f]{2})", first)
            if not (pre and mp and op):
                continue
            for (rm, rmap, rpre, rw, rig, rop), (rname, rc, pos, ntok) in recs.items():
                if rm != mnem or rmap != mp or rpre != pre or rop != op.group(1).lower():
                    continue
                if w != "x" and not rig and str(rw) != w:
                    continue
                if (rm, rmap, rpre, rw, rop) in found:
                    continue
                cp = round_copy(c, rc, pos, ntok)
                if cp:
                    found[(rm, rmap, rpre, rw, rop)] = rname
                    if re.search(r"\b(Reg64|Rmr64|LONGMODE_ON)\b", cp):
                        cp = "@ifdef IA64\n%s\n@endif" % cp
                    out.append("# %s (%s)\n%s\n" % (rname, name, cp))
    out += ["@endif", ""]
    open("%s/avx512_round.sinc" % lang, "w").write("\n".join(out))
    missing = [v[0] for k, v in recs.items() if (k[0], k[1], k[2], k[3], k[5]) not in found]
    print("%d EVEX.b register records, %d constructors, %d without a base constructor" % (len(recs), len(found), len(missing)), file=sys.stderr)
    for m in missing:
        print("  missing", m, file=sys.stderr)


if __name__ == "__main__":
    main()
