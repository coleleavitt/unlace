#!/usr/bin/env python3
"""Generate v60.slaspec (NEC V60/V70) from the tables below.

The V60 operand encoding (two addressing-mode fields per instruction, each
selected by an 'm' bit that sits in an earlier byte, with operand-size
dependent immediates, index scaling and auto-increment steps) gives a few
hundred near-identical constructors; this script writes them.
Run: python3 gen_v60.py > data/languages/v60.slaspec
"""

SIZES = (1, 2, 4, 8)
REGS = ["R%d" % i for i in range(29)] + ["AP", "FP", "SP"]
CREG = {1: "c_rb", 2: "c_rh", 4: "c_reg", 8: "c_rd"}
AREG = {1: "a_rb", 2: "a_rh", 4: "a_r", 8: "a_rd"}
COND = {
    0: "OV", 1: "!OV", 2: "CY", 3: "!CY", 4: "Z", 5: "!Z",
    6: "(CY || Z)", 7: "!(CY || Z)", 8: "S", 9: "!S", 10: "1:1",
    12: "(S != OV)", 13: "(S == OV)", 14: "((S != OV) || Z)",
    15: "!((S != OV) || Z)",
}
BNAMES = {0: "bv", 1: "bnv", 2: "bl", 3: "bnl", 4: "be", 5: "bne", 6: "bnh",
          7: "bh", 8: "bn", 9: "bp", 10: "br", 12: "blt", 13: "bge",
          14: "ble", 15: "bgt"}
out = []
w = out.append


def header():
    w("# NEC V60 / V70 (uPD70616 / uPD70632). Generated by gen_v60.py; edit that, not this.")
    w("define endian=little;")
    w("define alignment=1;")
    w("define space ram type=ram_space size=4 default;")
    w("define space io type=ram_space size=4;")
    w("define space register type=register_space size=4;")
    w("define register offset=0 size=4 [ %s ];" % " ".join(REGS))
    w("define register offset=0 size=2 [ %s ];" % " ".join("%sh _" % r for r in REGS))
    w("define register offset=0 size=1 [ %s ];" % " ".join("%sb _ _ _" % r for r in REGS))
    w("define register offset=0 size=8 [ %s ];" % " ".join("%sd" % REGS[i] for i in range(0, 32, 2)))
    w("define register offset=4 size=8 [ %s ];" % " ".join("%sd" % REGS[i] for i in range(1, 32, 2)))
    w("define register offset=0x100 size=4 [ PC PSW ];")
    w("define register offset=0x110 size=1 [ Z S OV CY ];")
    w("define register offset=0x120 size=4 [ ISP L0SP L1SP L2SP L3SP SBR TR SYCW TKCW PIR PSW2 ];")
    w("define register offset=0x200 size=4 contextreg;")
    w("define context contextreg m1=(0,0) noflow m2=(1,1) noflow;")
    w("")
    w("define token opbyte(8) op=(0,7) op_lo1=(0,0) op_hi7=(1,7);")
    w("define token codebyte(8) c_f2=(7,7) c_m=(6,6) c_d=(5,5) c_sub=(0,4) c_hi3=(5,7)"
      " c_reg=(0,4) c_rb=(0,4) c_rh=(0,4) c_rd=(0,4);")
    w("define token ammod(8) a_mode=(5,7) a_sub=(0,4) a_q=(0,3) a_r=(0,4) a_rb=(0,4) a_rh=(0,4) a_rd=(0,4);")
    w("define token amx(8) x_mode=(5,7) x_sub=(0,4) x_r=(0,4);")
    w("define token lenbyte(8) l_isreg=(7,7) l_imm=(0,6) l_reg=(0,4);")
    w("define token d8a(8) d8=(0,7) signed;")
    w("define token d8b(8) e8=(0,7) signed;")
    w("define token d16a(16) d16=(0,15) signed;")
    w("define token d16b(16) e16=(0,15) signed;")
    w("define token d32a(32) d32=(0,31) signed u32=(0,31);")
    w("define token d32b(32) e32=(0,31) signed;")
    w("define token i8t(8) imm8=(0,7);")
    w("define token i16t(16) imm16=(0,15);")
    w("define token i32t(32) imm32=(0,31);")
    w("")
    w("attach variables [ c_reg a_r x_r l_reg ] [ %s ];" % " ".join(REGS))
    w("attach variables [ c_rh a_rh ] [ %s ];" % " ".join(r + "h" for r in REGS))
    w("attach variables [ c_rb a_rb ] [ %s ];" % " ".join(r + "b" for r in REGS))
    w("attach variables [ c_rd a_rd ] [ %s ];" % " ".join(r + "d" for r in REGS))
    w("")
    for n in ("halt", "brk", "brkTrap", "trapfl", "clrtlba", "clrtlb", "softwareTrap",
              "ldtask", "sttask", "stpr", "ldpr", "getra", "getpte", "getate", "updpte",
              "update", "chlvl", "checkAccessRead", "checkAccessWrite", "checkAccessExec",
              "compareAndExchangeInterlocked", "bitReverse", "rotateThroughCarry",
              "rotateThroughCarryOut", "stringCompare", "stringMove", "stringSearch",
              "stringSkip", "decimalAdd", "decimalSub", "decimalSubReverse",
              "packedToZoned", "zonedToPacked", "bitStringSearch", "bitStringOp",
              "bitFieldCompare", "bitFieldExtract", "bitFieldInsert", "scaleFloat"):
        w("define pcodeop %s;" % n)
    w("")
    w("macro resflags(r) { Z = (r == 0); S = (r s< 0); }")
    w("macro packpsw() { PSW = (PSW & 0xfffffff0) | zext(Z) | (zext(S) << 1) | (zext(OV) << 2) | (zext(CY) << 3); }")
    w("macro unpackpsw() { Z = (PSW & 1) != 0; S = (PSW & 2) != 0; OV = (PSW & 4) != 0; CY = (PSW & 8) != 0; }")
    w("")


def mode_rows(slot, kind, z):
    """Yield (display, pattern, actions, pcode) for one addressing-mode table.

    kind 'ea': export the effective address (4 bytes); 'ct': constant code
    targets only; 'ba': a bit address (8 bytes, byte address * 8 + bit offset).
    """
    M = "m%d" % slot
    rows = []

    def ea(disp_body):
        return disp_body

    def fin(base_expr, off=None, deref=False, idx=None):
        """pcode computing ea from base (+off) (deref) (+idx scaled)."""
        lines = []
        if kind == "ba":
            if deref:
                lines.append("local pa:4 = %s%s; local p:4 = *:4 pa;" % (base_expr, "" if off is None else " + " + off))
                lines.append("local b:8 = zext(p) * 8;")
            else:
                be = base_expr if base_expr in ("rel", "u32") else "zext(%s)" % base_expr
                lines.append("local b:8 = %s * 8%s;" % (be, "" if off is None else " + " + off))
            if idx:
                lines.append("b = b + sext(%s);" % idx)
            lines.append("export b;")
        else:
            if deref:
                lines.append("local pa:4 = %s%s; local p:4 = *:4 pa;" % (base_expr, "" if off is None else " + " + off))
                e = "p"
            else:
                e = base_expr + ("" if off is None else " + " + off)
            if idx:
                e = "%s + %s%s" % (e, idx, "" if z == 1 else " * %d" % z)
            lines.append("local ea:4 = %s;" % e)
            lines.append("export ea;")
        return " ".join(lines)

    D = [("d8", "d8a"), ("d16", "d16a"), ("d32", "d32a")]
    E = [("e8", "d8b"), ("e16", "d16b"), ("e32", "d32b")]
    if kind == "ct":
        for i, (d, _) in enumerate(D):
            rows.append(('rel^"[PC]"', "a_mode=7 & a_sub=%d; %s" % (16 + i, d),
                         "[ rel = inst_start + %s; ]" % d, "export *:4 rel;"))
        rows.append(("u32", "a_mode=7 & a_sub=19; u32", "", "export *:4 u32;"))
        return rows
    # m = 0
    for i, (d, _) in enumerate(D):
        if kind == "ba":
            rows.append(('%s^"["^a_r^"]"' % d, "a_mode=%d & a_r & %s=0; %s" % (i, M, d), "",
                         fin("a_r", "sext(%s:4)" % d if False else d)))
        else:
            rows.append(('%s^"["^a_r^"]"' % d, "a_mode=%d & a_r & %s=0; %s" % (i, M, d), "", fin("a_r", d)))
    rows.append(('"["^a_r^"]"', "a_mode=3 & a_r & %s=0" % M, "", fin("a_r")))
    for i, (d, _) in enumerate(D):
        rows.append(('"["^%s^"["^a_r^"]]"' % d, "a_mode=%d & a_r & %s=0; %s" % (4 + i, M, d), "",
                     fin("a_r", d, deref=True)))
    for i, (d, _) in enumerate(D):
        rows.append(('rel^"[PC]"', "a_mode=7 & a_sub=%d & %s=0; %s" % (16 + i, M, d),
                     "[ rel = inst_start + %s; ]" % d,
                     ("local b:8 = rel * 8; export b;" if kind == "ba" else "export *[const]:4 rel;")))
    rows.append(("u32", "a_mode=7 & a_sub=19 & %s=0; u32" % M, "",
                 ("local b:8 = u32 * 8; export b;" if kind == "ba" else "export *[const]:4 u32;")))
    for i, (d, _) in enumerate(D):
        rows.append(('"["^rel^"[PC]]"', "a_mode=7 & a_sub=%d & %s=0; %s" % (24 + i, M, d),
                     "[ rel = inst_start + %s; ]" % d, fin("rel", deref=True)))
    rows.append(('"["^u32^"]"', "a_mode=7 & a_sub=27 & %s=0; u32" % M, "", fin("u32", deref=True)))
    for i in range(3):
        d, e = D[i][0], E[i][0]
        if kind == "ba":
            body = "local pa:4 = rel; local p:4 = *:4 pa; local b:8 = zext(p) * 8 + %s; export b;" % e
        else:
            body = "local pa:4 = rel; local p:4 = *:4 pa; local ea:4 = p + %s; export ea;" % e
        rows.append(('%s^"["^rel^"[PC]]"' % e, "a_mode=7 & a_sub=%d & %s=0; %s; %s" % (28 + i, M, d, e),
                     "[ rel = inst_start + %s; ]" % d, body))
    # m = 1
    for i in range(3):
        d, e = D[i][0], E[i][0]
        if kind == "ba":
            body = "local p:4 = *:4 (a_r + %s); local b:8 = zext(p) * 8 + %s; export b;" % (d, e)
        else:
            body = "local p:4 = *:4 (a_r + %s); local ea:4 = p + %s; export ea;" % (d, e)
        rows.append(('%s^"["^%s^"["^a_r^"]]"' % (e, d), "a_mode=%d & a_r & %s=1; %s; %s" % (i, M, d, e), "", body))
    step = 1 if kind == "ba" else z
    if kind == "ba":
        rows.append(('"["^a_r^"+]"', "a_mode=4 & a_r & %s=1" % M, "", "local b:8 = zext(a_r) * 8; export b;"))
        rows.append(('"[-"^a_r^"]"', "a_mode=5 & a_r & %s=1" % M, "", "local b:8 = zext(a_r) * 8; export b;"))
    else:
        rows.append(('"["^a_r^"+]"', "a_mode=4 & a_r & %s=1" % M, "",
                     "local ea:4 = a_r; a_r = a_r + %d; export ea;" % step))
        rows.append(('"[-"^a_r^"]"', "a_mode=5 & a_r & %s=1" % M, "",
                     "a_r = a_r - %d; local ea:4 = a_r; export ea;" % step))
    # indexed group: a_r is the index register, x_r the base
    for i, (d, _) in enumerate(D):
        rows.append(('%s^"["^x_r^"]("^a_r^")"' % d, "a_mode=6 & a_r & %s=1; x_mode=%d & x_r; %s" % (M, i, d), "",
                     fin("x_r", d, idx="a_r")))
    rows.append(('"["^x_r^"]("^a_r^")"', "a_mode=6 & a_r & %s=1; x_mode=3 & x_r" % M, "", fin("x_r", idx="a_r")))
    for i, (d, _) in enumerate(D):
        rows.append(('"["^%s^"["^x_r^"]]("^a_r^")"' % d, "a_mode=6 & a_r & %s=1; x_mode=%d & x_r; %s" % (M, 4 + i, d),
                     "", fin("x_r", d, deref=True, idx="a_r")))
    for i, (d, _) in enumerate(D):
        rows.append(('rel^"[PC]("^a_r^")"', "a_mode=6 & a_r & %s=1; x_mode=7 & x_sub=%d; %s" % (M, 16 + i, d),
                     "[ rel = inst_start + %s; ]" % d, fin("rel", idx="a_r")))
    rows.append(('u32^"("^a_r^")"', "a_mode=6 & a_r & %s=1; x_mode=7 & x_sub=19; u32" % M, "",
                 fin("u32", idx="a_r")))
    for i, (d, _) in enumerate(D):
        rows.append(('"["^rel^"[PC]]("^a_r^")"', "a_mode=6 & a_r & %s=1; x_mode=7 & x_sub=%d; %s" % (M, 24 + i, d),
                     "[ rel = inst_start + %s; ]" % d, fin("rel", deref=True, idx="a_r")))
    rows.append(('"["^u32^"]("^a_r^")"', "a_mode=6 & a_r & %s=1; x_mode=7 & x_sub=27; u32" % M, "",
                 fin("u32", deref=True, idx="a_r")))
    return rows


def immediates(t, M, z, ez):
    """Quick (0-15) and inline immediates of operand size z, exported as ez bytes."""
    w('%s: "#"^a_q is a_mode=7 & a_sub<16 & a_q & %s=0 { local t:%d = a_q; export t; }' % (t, M, ez))
    if z != 8:
        imm = {1: "imm8", 2: "imm16", 4: "imm32"}[z]
        w('%s: "#"^%s is a_mode=7 & a_sub=20 & %s=0; %s { local t:%d = %s; export t; }' % (t, imm, M, imm, ez, imm))


def tables():
    for slot in (1, 2):
        M = "m%d" % slot
        for z in SIZES:
            t = "EA%d_%d" % (slot, z)
            for disp, pat, act, body in mode_rows(slot, "ea", z):
                w("%s: %s is %s %s { %s }" % (t, disp, pat, act, body))
            v = "AM%d_%d" % (slot, z)
            w("%s: %s is %s { export *:%d %s; }" % (v, t, t, z, t))
            w("%s: %s is a_mode=3 & %s & %s=1 { export %s; }" % (v, AREG[z], AREG[z], M, AREG[z]))
            immediates(v, M, z, z)
            x = "XA%d_%d" % (slot, z)
            w("%s: %s is %s { export %s; }" % (x, t, t, t))
            w("%s: a_r is a_mode=3 & a_r & %s=1 { export a_r; }" % (x, M))
            immediates(x, M, z, 4)
            w("")
        t = "BA%d" % slot
        for disp, pat, act, body in mode_rows(slot, "ba", 1):
            w("%s: %s is %s %s { %s }" % (t, disp, pat, act, body))
        for b, z in (("BS%d" % slot, 1), ("BF%d" % slot, 4)):
            w("%s: %s is %s { export %s; }" % (b, t, t, t))
            w("%s: a_r is a_mode=3 & a_r & %s=1 { local b:8 = zext(a_r); export b; }" % (b, M))
            immediates(b, M, z, 8)
        w("")
    for disp, pat, act, body in mode_rows(1, "ct", 4):
        w("CT1: %s is %s %s { %s }" % (disp, pat, act, body))
    w("")
    w("REL8: rel is d8 [ rel = inst_start + d8; ] { export *:4 rel; }")
    w("REL16: rel is d16 [ rel = inst_start + d16; ] { export *:4 rel; }")
    for t in ("LENA", "LENB"):
        w("%s: l_reg is l_isreg=1 & l_reg { export l_reg; }" % t)
        w('%s: "#"^l_imm is l_isreg=0 & l_imm { export *[const]:4 l_imm; }' % t)
    w("")


# ---- semantics: f(S, D, s1, s2) -> pcode; S is operand 1 (source), D operand 2 ----
def bits(z):
    return z * 8


def s_add(S, D, a, b):
    return ("local x:%d = %s; local y:%d = %s; local r:%d = y + x; CY = carry(y, x); OV = scarry(y, x); "
            "%s = r; resflags(r);" % (a, S, b, D, b, D))


def s_addc(S, D, a, b):
    return ("local x:%d = %s; local y:%d = %s; local c:%d = zext(CY); local t:%d = y + x; local r:%d = t + c; "
            "CY = carry(y, x) || carry(t, c); OV = ((~(y ^ x)) & (y ^ r)) s< 0; %s = r; resflags(r);"
            % (a, S, b, D, b, b, b, D))


def s_sub(S, D, a, b, store=True):
    return ("local x:%d = %s; local y:%d = %s; local r:%d = y - x; CY = y < x; OV = sborrow(y, x); "
            "%sresflags(r);" % (a, S, b, D, b, ("%s = r; " % D) if store else ""))


def s_subc(S, D, a, b):
    return ("local x:%d = %s; local y:%d = %s; local c:%d = zext(CY); local t:%d = y - x; local r:%d = t - c; "
            "CY = (y < x) || (t < c); OV = ((y ^ x) & (y ^ r)) s< 0; %s = r; resflags(r);"
            % (a, S, b, D, b, b, b, D))


def s_logic(opc):
    def f(S, D, a, b):
        return "local r:%d = %s %s %s; OV = 0; %s = r; resflags(r);" % (b, D, opc, S, D)
    return f


def s_mul(signed):
    def f(S, D, a, b):
        ext = "sext" if signed else "zext"
        cmp = "%s(r) != p" % ext
        return ("local x:%d = %s; local y:%d = %s; local p:%d = %s(y) * %s(x); local r:%d = p:%d; "
                "OV = %s; %s = r; resflags(r);" % (a, S, b, D, 2 * b, ext, ext, b, b, cmp, D))
    return f


def s_div(signed, rem):
    def f(S, D, a, b):
        opc = {(True, False): "s/", (False, False): "/", (True, True): "s%", (False, True): "%"}[(signed, rem)]
        ov = ("OV = (y == 0x%x) && (x == -1);" % (1 << (bits(b) - 1))) if (signed and not rem) else "OV = 0;"
        return ("local x:%d = %s; local y:%d = %s; %s local r:%d = y %s x; %s = r; resflags(r);"
                % (a, S, b, D, ov, b, opc, D))
    return f


def s_shl(S, D, a, b):
    n = bits(b)
    return ("local c:1 = %s; local y:%d = %s; local r:%d = y; OV = 0; CY = 0; "
            "if (c == 0) goto <done>; if (c s< 0) goto <right>; "
            "r = y << c; CY = ((y >> (%d - c)) & 1) != 0; goto <done>; "
            "<right> local k:1 = -c; r = y >> k; CY = ((y >> (k - 1)) & 1) != 0; "
            "<done> %s = r; resflags(r);" % (S, b, D, b, n, D))


def s_sha(S, D, a, b):
    n = bits(b)
    return ("local c:1 = %s; local y:%d = %s; local r:%d = y; OV = 0; CY = 0; "
            "if (c == 0) goto <done>; if (c s< 0) goto <right>; "
            "r = y << c; CY = ((y >> (%d - c)) & 1) != 0; OV = (r s>> c) != y; goto <done>; "
            "<right> local k:1 = -c; r = y s>> k; CY = ((y s>> (k - 1)) & 1) != 0; "
            "<done> %s = r; resflags(r);" % (S, b, D, b, n, D))


def s_rot(S, D, a, b):
    n = bits(b)
    return ("local c:1 = %s; local y:%d = %s; local r:%d = y; CY = 0; "
            "if (c == 0) goto <done>; if (c s< 0) goto <right>; "
            "r = (y << c) | (y >> (%d - c)); CY = (r & 1) != 0; goto <done>; "
            "<right> local k:1 = -c; r = (y >> k) | (y << (%d - k)); CY = r s< 0; "
            "<done> OV = 0; %s = r; resflags(r);" % (S, b, D, b, n, n, D))


def s_rotc(S, D, a, b):
    return ("local c:1 = %s; local y:%d = %s; local r:%d = rotateThroughCarry(y, c, CY); "
            "CY = rotateThroughCarryOut(y, c, CY); OV = 0; %s = r; resflags(r);" % (S, b, D, b, D))


def s_bit(opc):
    def f(S, D, a, b):
        upd = {"set": "%s = y | m;", "clr": "%s = y & ~m;", "not": "%s = y ^ m;", "test": ""}[opc]
        return ("local n:4 = %s & 31; local y:4 = %s; local m:4 = 1 << n; CY = (y & m) != 0; Z = !CY; %s"
                % (S, D, upd % D if upd else ""))
    return f


def s_mov(S, D, a, b):
    return "%s = %s;" % (D, S)


def s_movs(S, D, a, b):
    return "%s = sext(%s);" % (D, S)


def s_movz(S, D, a, b):
    return "%s = zext(%s);" % (D, S)


def s_movt(S, D, a, b):
    return "local x:%d = %s; local r:%d = x:%d; OV = sext(r) != x; %s = r;" % (a, S, b, b, D)


def s_not(S, D, a, b):
    return "local r:%d = ~%s; OV = 0; %s = r; resflags(r);" % (b, S, D)


def s_neg(S, D, a, b):
    return ("local x:%d = %s; local r:%d = -x; CY = x != 0; OV = sborrow(0:%d, x); %s = r; resflags(r);"
            % (a, S, b, b, D))


def s_rvbit(S, D, a, b):
    return "%s = bitReverse(%s);" % (D, S)


def s_rvbyt(S, D, a, b):
    return ("local x:4 = %s; %s = (x << 24) | ((x & 0xff00) << 8) | ((x >> 8) & 0xff00) | (x >> 24);" % (S, D))


def s_xch(S, D, a, b):
    return "local t:%d = %s; %s = %s; %s = t;" % (b, D, D, S, S)


def s_setf(S, D, a, b):
    lines = ["local c:1 = %s & 15; local v:1 = 0;" % S]
    for k in range(16):
        e = COND.get(k, "0:1")
        lines.append("if (c != %d) goto <n%d>; v = %s; goto <done>; <n%d>" % (k, k, e, k))
    lines.append("<done> %s = zext(v);" % D if b > 1 else "<done> %s = v;" % D)
    return " ".join(lines)


def s_cmp(S, D, a, b):
    return s_sub(S, D, a, b, store=False)


def s_in(S, D, a, b):
    return "%s = *[io]:%d %s;" % (D, b, S)


def s_out(S, D, a, b):
    return "*[io]:%d %s = %s;" % (a, D, S)


def s_movea(S, D, a, b):
    return "%s = %s;" % (D, S)


def s_updpsw(mask):
    def f(S, D, a, b):
        return ("packpsw(); local v:4 = %s & 0x%x; local m:4 = %s & 0x%x; PSW = (PSW & ~m) | (v & m); unpackpsw();"
                % (S, mask, D, mask))
    return f


def s_mulx(signed):
    def f(S, D, a, b):
        ext = "sext" if signed else "zext"
        return ("local x:4 = %s; local y:8 = %s; local lo:4 = y:4; local r:8 = %s(lo) * %s(x); %s = r; "
                "Z = r == 0; S = r s< 0;" % (S, D, ext, ext, D))
    return f


def s_divx(signed):
    def f(S, D, a, b):
        ext = "sext" if signed else "zext"
        dv, rm = ("s/", "s%") if signed else ("/", "%")
        return ("local x:4 = %s; local y:8 = %s; local q:8 = y %s %s(x); local m:8 = y %s %s(x); "
                "%s = (m << 32) | zext(q:4); Z = q:4 == 0; S = q:4 s< 0;" % (S, D, dv, ext, rm, ext, D))
    return f


def s_user(name, write):
    def f(S, D, a, b):
        if write:
            return "%s = %s(%s);" % (D, name, S)
        return "%s(%s, %s);" % (name, S, D)
    return f


def s_caxi(S, D, a, b):
    return "%s = compareAndExchangeInterlocked(%s, %s);" % (S, S, D)


def s_call(S, D, a, b):
    return ("local ap:4 = %s; SP = SP - 4; *:4 SP = AP; AP = ap; SP = SP - 4; *:4 SP = inst_next; call %s;"
            % (D, S))


def s_callind(S, D, a, b):
    return ("local t:4 = %s; local ap:4 = %s; SP = SP - 4; *:4 SP = AP; AP = ap; SP = SP - 4; *:4 SP = inst_next; "
            "call [t];" % (S, D))


def s_ldpr(S, D, a, b):
    return "ldpr(%s, %s);" % (S, D)


