#!/usr/bin/env python3
"""Generate the AVX10.2 SLEIGH tables of the x86-64 language from LLVM's TableGen records.

Usage:
  llvm-tblgen --dump-json -I <llvm>/include -I <llvm>/lib/Target/X86 \
      <llvm>/lib/Target/X86/X86.td -o x86.json
  tools/gen_x86_avx10.py x86.json specs/Ghidra/Processors/x86/data/languages/avx10_2.sinc [probe.txt]

Every non-pseudo EVEX record with a HasAVX10_2* predicate is emitted. The records
of one instruction form (plain, merge-masked, zero-masked, broadcast, {sae} and
{rc} variants) fold into one constructor for the register form, one for the
memory form and one for the {sae}/{rc} register form, in the style of avx512.sinc:
masking through the Xmm/Ymm/ZmmOpMask* tables, Disp8*N from LLVM's CD8_Scale (the
16-bit broadcast rows FV16/HV16 are in ia.sinc),
and one user operation per mnemonic (avx10_<mnemonic>) whose inputs are the read
operands (the old destination first for accumulating forms). VMOVRS* are loads,
VMOVD/VMOVW zero-extending moves, and the VCOMX/VUCOMX/VCOMISBF16 compares set
EFLAGS (VCOMX: OF SF ZF PF CF = 11011 unordered, 00000 greater, 10001 less,
11100 equal; VCOMISBF16: ZF PF CF as COMISS).
"""
import json, re, sys, collections

MAP = {"TB": "$(VEX_0F)", "T8": "$(VEX_0F38)", "TA": "$(VEX_0F3A)", "T_MAP5": "$(VEX_MAP5)", "T_MAP6": "$(VEX_MAP6)"}
PRE = {"PS": "$(VEX_PRE_NONE)", "PD": "$(VEX_PRE_66)", "XS": "$(VEX_PRE_F3)", "XD": "$(VEX_PRE_F2)"}
VBITS = {"VR128X": 128, "VR256X": 256, "VR512": 512, "FR16X": 128, "FR32X": 128, "FR64X": 128}
VNAME = {128: "Xmm", 256: "Ymm", 512: "Zmm"}
MEMSZ = {"f16mem": 16, "i16mem": 16, "f32mem": 32, "ssmem": 32, "i32mem": 32, "f64mem": 64, "sdmem": 64,
         "i64mem": 64, "f128mem": 128, "i128mem": 128, "f256mem": 256, "i256mem": 256, "f512mem": 512,
         "i512mem": 512}
KREG = ("VK1", "VK2", "VK4", "VK8", "VK16", "VK32", "VK64")
SCALAR = {"sh": 16, "ss": 32, "sd": 64, "bf16": 16}
CMP_PRED = ["EQ", "LT", "LE", "UNORD", "NEQ", "NLT", "NLE", "ORD", "EQ_UQ", "NGE", "NGT", "FALSE", "NEQ_OQ", "GE", "GT",
            "TRUE", "EQ_OS", "LT_OQ", "LE_OQ", "UNORD_S", "NEQ_US", "NLT_UQ", "NLE_UQ", "ORD_S", "EQ_US", "NGE_UQ",
            "NGT_UQ", "FALSE_OS", "NEQ_OS", "GE_OQ", "GT_OQ", "TRUE_US"]
HEADER = ("# GENERATED by tools/gen_x86_avx10.py from LLVM's X86 TableGen records (AVX10.2);\n"
          "# edit the generator, not this file. See specs/Ghidra/Processors/x86/README.md.\n")


def bits(lst):
    return sum(b << i for i, b in enumerate(lst))


def load(path):
    J = json.load(open(path))
    out = []
    for n in J["!instanceof"]["X86Inst"]:
        r = J[n]
        if r.get("isPseudo") or r.get("isCodeGenOnly") or r.get("isAsmParserOnly"):
            continue
        ps = [p["def"] for p in r.get("Predicates", [])]
        if not any(p.startswith("HasAVX10_2") for p in ps) or r["OpEnc"]["def"] != "EncEVEX":
            continue
        asm = r["AsmString"]
        mn = re.sub(r"\{[xyz]\}$", "", asm.split()[0])
        intel = asm.split("|", 1)[1].rsplit("}", 1)[0] if "|" in asm else asm.split(None, 1)[1]
        form = r["Form"]["def"]
        out.append(dict(
            name=n, mn=mn, intel=intel.strip(), form=form, map=r["OpMap"]["def"], pre=r["OpPrefix"]["def"],
            opc=bits(r["Opcode"]), w=r["hasREX_W"], igw=r["IgnoresW"], l=r["hasVEX_L"], l2=r["hasEVEX_L2"],
            igl=r["ignoresVEX_L"], v4=r["hasVEX_4V"], k=r["hasEVEX_K"], z=r["hasEVEX_Z"], b=r["hasEVEX_B"],
            rc=r["hasEVEX_RC"], u=r["hasEVEX_U"], cd8=bits(r["CD8_Scale"]), vl=vlen(n, r),
            outs=[(a[1], a[0]["def"]) for a in r["OutOperandList"]["args"]],
            ins=[(a[1], a[0]["def"]) for a in r["InOperandList"]["args"]],
            cons=r.get("Constraints", "") or "", mem="Mem" in form))
    out.sort(key=lambda r: r["name"])
    return out


def vlen(name, r):
    """Vector length index from the record name (Z128, Z256, Z); {rc} records leave L'L to the rounding mode."""
    m = re.search(r"Z(128|256)?(?=[a-z_]|$)", name)
    if m:
        return {"128": 0, "256": 1, None: 2}[m.group(1)]
    return 2 if r["hasEVEX_L2"] else (1 if r["hasVEX_L"] else 0)


def bkey(r):
    return (r["mn"], r["map"], r["pre"], r["opc"], r["w"])


def tied(r):
    m = re.search(r"\$(\w+)\s*=\s*\$dst", r["cons"])
    return m.group(1) if m and m.group(1) != "src0" else None


def roles(r):
    """Encoding role (reg, vvvv, rm, imm) of each named operand of a plain record."""
    t = tied(r)
    ins = [(n, c) for n, c in r["ins"] if not c.endswith("WM") and n not in ("src0", t) and c != "AVX512RC"]
    role = {}
    if r["outs"]:
        role[r["outs"][0][0]] = "reg"
        rest = ins
    else:
        role[ins[0][0]] = "reg"
        rest = ins[1:]
    for n, c in rest:
        if "imm" in c:
            role[n] = "imm"
    regs = [(n, c) for n, c in rest if "imm" not in c]
    order = ["rm", "vvvv"] if r["form"].endswith("4VOp3") else (["vvvv", "rm"] if r["v4"] else ["rm"])
    if len(regs) != len(order):
        raise ValueError("%s: operands %s for roles %s" % (r["name"], regs, order))
    for (n, c), ro in zip(regs, order):
        role[n] = ro
    return role


def disp8(n, l, bcst, w, scalar=False):
    """(evexD8Type, evexTType) giving the compressed displacement N at vector length index l."""
    if scalar and not bcst:
        return 1, {1: 1, 2: 2, 4: 4, 8: 5, 16: 12}[n]
    full, half = 16 << l, 8 << l
    if bcst:
        if n == full:
            return (1, 14) if bcst == 2 else (0, 0)
        if n == half:
            return (1, 15) if bcst == 2 else (0, 1)
        raise ValueError("broadcast with N=%d" % n)
    if n == full:
        return 1, 0
    for nn, t in ((half, 9), (4 << l, 10), (2 << l, 11)):
        if n == nn:
            return 1, t
    return 1, {1: 1, 2: 2, 4: 4, 8: 5, 16: 12}[n]


def bcst_check(group, plain_w):
    """Broadcast element size (bytes) of a memory group; W must agree for the FV/HV table rows."""
    for g in group:
        if g["b"] and g["mem"]:
            if g["cd8"] in (4, 8) and g["cd8"] != (8 if plain_w else 4):
                raise ValueError("%s: broadcast %d with W=%d" % (g["name"], g["cd8"], plain_w))
            return g["cd8"]
    return None


class Gen:
    def __init__(self):
        self.ops = collections.OrderedDict()
        self.memtabs = collections.OrderedDict()
        self.ctors = []
        self.probe = []
        self.bkeys = {}

    def op(self, name):
        self.ops[name] = True
        return name

    def memtab(self, sz, bcst):
        if not bcst:
            return "m%d" % sz
        name = "avx10_m%d_b%d" % (sz, bcst * 8)
        self.memtabs[name] = ("%s: m%d is evexB=0 & m%d { export m%d; }\n%s: m%dbcst%d is evexB=1 & m%dbcst%d { export m%dbcst%d; }"
                              % (name, sz, sz, sz, name, bcst * 8, sz, bcst * 8, sz, bcst * 8, sz))
        return name

    def group(self, group):
        plain = [r for r in group if not r["k"] and not r["b"]] or [r for r in group if not r["k"]]
        r = plain[0]
        role = roles(r)
        masked = any(g["k"] for g in group)
        maskc = next((c for g in group for n, c in g["ins"] if c.endswith("WM")), None)
        breg = [g for g in group if g["b"] and not g["mem"]]
        lidx = 2 if r["l2"] else (1 if r["l"] else 0)
        if r["vl"] == 2 and lidx == 0:
            r = dict(r, igl=1)
        mem = r["mem"]
        bcst = bcst_check(group, r["w"]) if mem else None
        self.emit(r, role, masked, maskc, lidx, mem, bcst, None, bool(breg))
        if breg:
            b = breg[0]
            self.emit(r, role, masked, maskc, lidx, False, None, "rc" if b["rc"] else "sae", False, b["u"], b["intel"])

    def emit(self, r, role, masked, maskc, lidx, mem, bcst, bvar, has_bvar, ubit=0, bintel=None):
        mn = r["mn"]
        names = dict(r["outs"] + r["ins"])
        dstn = r["outs"][0][0] if r["outs"] else None
        dstc = names.get(dstn)
        t = tied(r)
        ctx = ["$(EVEX_NONE)"]
        if r["igl"] or bvar:
            ctx.append("$(VEX_LIG)")
        else:
            ctx.append({0: "$(VEX_L128)", 1: "$(VEX_L256)", 2: "$(EVEX_L512)"}[lidx])
        ctx += [PRE[r["pre"]], MAP[r["map"]], "$(VEX_WIG)" if r["igw"] else ("$(VEX_W1)" if r["w"] else "$(VEX_W0)")]
        if bvar:
            ctx.append("evexB=1")
            ctx.append("rexX4=%d" % (1 if ubit else 0))
        elif has_bvar or (not mem and self.bkeys.get(bkey(r))):
            ctx.append("evexB=0")
        regpart, text, reads = [], {}, []
        scal = {}
        dst, dbits, mtab = None, None, None
        if dstc in VBITS:
            dbits = VBITS[dstc]
            dst = "%sReg1" % VNAME[dbits]
            regpart.append(dst)
            if dbits != 512:
                regpart.append("ZmmReg1")
        elif dstc in KREG:
            dst = "KReg_reg"
            regpart.append(dst)
        elif dstc in ("GR32", "GR64"):
            dst = "Reg32" if dstc == "GR32" else "Reg64"
            regpart.append(dst)
            if dstc == "GR32":
                regpart.append("check_Reg32_dest")
        elif dstc == "TILE":
            dst = "amxTreg"
            regpart.append(dst)
        elif dstc is not None:
            raise ValueError("%s: destination %s" % (r["name"], dstc))
        if dstn:
            text[dstn] = dst
            if masked and dbits:
                if maskc == "VK1WM":
                    eb = next((v for s, v in SCALAR.items() if mn.endswith(s)), 32)
                else:
                    eb = dbits // int(re.match(r"VK(\d+)WM", maskc).group(1))
                mtab = "%sOpMask%d" % (VNAME[dbits], eb)
                ctx.append(mtab)
                text[dstn] = "%s^%s" % (dst, mtab)
            elif masked and dst == "KReg_reg":
                ctx.append("AVXOpMask")
                text[dstn] = "KReg_reg^AVXOpMask"
        if t and dst:
            reads.append(dst)
        kmask = masked and dst == "KReg_reg"
        rmtab = None
        for n, c in r["ins"]:
            ro = role.get(n)
            if ro is None:
                continue
            if ro == "imm":
                text[n] = "imm8"
                reads.append("imm8:1")
                continue
            if c in VBITS:
                V = VNAME[VBITS[c]]
                tab = {"vvvv": "evexV5_%sReg" % V, "reg": "%sReg1" % V, "rm": "%sReg2" % V}[ro]
                if mem and ro == "rm":
                    raise ValueError("%s: register %s in a memory form" % (r["name"], n))
                scal[n] = tab
            elif c in MEMSZ:
                tab = self.memtab(MEMSZ[c], bcst)
                scal[n] = tab
            elif c == "TILE":
                tab = {"rm": "amxTrm", "reg": "amxTreg", "vvvv": "amxTvvvv"}[ro]
            elif c in ("GR32", "GR64"):
                tab = {"vvvv": "apxNDD", "reg": "Reg", "rm": "Rmr"}[ro] + c[2:]
            elif c in KREG:
                tab = {"rm": "KReg_rm", "reg": "KReg_reg"}[ro]
            else:
                raise ValueError("%s: operand %s %s" % (r["name"], n, c))
            if ro == "vvvv":
                ctx.append(tab)
            elif ro == "reg":
                regpart.append(tab)
            else:
                rmtab = tab
            text[n] = tab
            reads.append(tab)
        # Intel operand order
        shown = []
        intel = bintel if bvar else r["intel"]
        for tok in [x.strip() for x in intel.split(",")] if intel else []:
            m = re.match(r"\$\{?(\w+)\}?", tok)
            if tok == "{sae}":
                shown.append('"{sae}"')
            elif m and m.group(1) == "rc":
                shown.append("avx10Rc")
            elif m and m.group(1) in text:
                shown.append(text[m.group(1)])
        if kmask:
            reads.append("AVXOpMask")
        opcode = "byte=0x%02x" % r["opc"]
        uniq = []
        for x in regpart:
            if x not in uniq:
                uniq.append(x)
        if mem:
            modrm = "(mod != 3 & %s) ... & %s" % (" & ".join(uniq), rmtab)
        else:
            modrm = "mod=3 & " + " & ".join(uniq + ([rmtab] if rmtab else []))
        if "imm8" in text.values():
            modrm += "; imm8"
        if bvar == "rc":
            modrm += " & avx10Rc"
        pat = " & ".join(dict.fromkeys(ctx)) + "; " + opcode + "; " + modrm
        cop = ""
        if mem:
            n8 = r["cd8"]
            d8, tt = disp8(n8, lidx, bcst, r["w"], r["igl"])
            cop = "\n[ evexD8Type = %d; evexTType = %d; ]" % (d8, tt)
        body = self.body(r, mn, dst, dbits, mtab, reads, scal, role, names)
        mnem = mn.upper()
        if mn == "vcmpbf16":
            shown = [s for s in shown if s != "imm8"]
            mnem = "^avx10CmpBf16"
            pat += " & avx10CmpBf16"
        ops = ", ".join(shown)
        head = ":%s %s" % (mnem, ops) if ops else ":%s" % mnem
        self.ctors.append("# %s\n%s is %s%s\n{\n%s\n}\n" % (r["name"], head, pat, cop, body))

    def body(self, r, mn, dst, dbits, mtab, reads, scal, role, names):
        if mn.startswith(("vcomx", "vucomx", "vcomisbf16")):
            a, b = [n for n, ro in sorted(role.items(), key=lambda x: {"reg": 0, "vvvv": 1, "rm": 2}.get(x[1], 3))
                    if ro in ("reg", "rm")]
            ta, tb = scal[a], scal[b]
            sz = next(v for s, v in SCALAR.items() if mn.endswith(s))
            va = "%s[0,%d]" % (ta, sz)
            vb = tb if tb.startswith("m") else "%s[0,%d]" % (tb, sz)
            lines = ["\tlocal a:%d = %s;" % (sz // 8, va), "\tlocal b:%d = %s;" % (sz // 8, vb)]
            if sz in (32, 64):
                lines.append("\tlocal un:1 = nan(a) || nan(b); local lt:1 = a f< b; local eq:1 = a f== b;")
            else:
                op = self.op("avx10_" + mn + "_cmp")
                lines.append("\tlocal c:1 = %s(a, b); local un:1 = c[0,1]; local lt:1 = c[1,1]; local eq:1 = c[2,1];" % op)
            if mn.startswith("vcomisbf16"):
                lines.append("\tZF = un || eq; PF = un; CF = un || lt; OF = 0; SF = 0; AF = 0;")
            else:
                lines.append("\tOF = un || lt || eq; SF = OF; ZF = eq; PF = un; CF = un || lt; AF = 0;")
            return "\n".join(lines)
        if mn.startswith("vmovrs"):
            val = reads[-1]
        elif mn in ("vmovd", "vmovw"):
            n = 32 if mn == "vmovd" else 16
            src = reads[-1]
            val = "zext(%s[0,%d])" % (src, n) if not src.startswith("m") else "zext(%s)" % src
            return "\tZmmReg1 = %s;" % val
        else:
            val = "%s(%s)" % (self.op("avx10_" + mn), ", ".join(reads))
        if dbits:
            V = VNAME[dbits]
            if mtab:
                lines = ["\t%sResult = %s;" % (V, val), "\t%sMask = %s;" % (V, dst), "\tbuild %s;" % mtab]
                lines.append("\tZmmReg1 = %s;" % ("ZmmResult" if dbits == 512 else "zext(%sResult)" % V))
                return "\n".join(lines)
            if dbits == 512:
                return "\tZmmReg1 = %s;" % val
            return "\tlocal res:%d = %s;\n\tZmmReg1 = zext(res);" % (dbits // 8, val)
        if dst == "KReg_reg":
            return "\tKReg_reg = %s;" % val
        if dst in ("Reg32", "Reg64"):
            return "\t%s = %s;%s" % (dst, val, " build check_Reg32_dest;" if dst == "Reg32" else "")
        return "\t%s;" % val


def vex_vnni(path, gen):
    """The VEX AVX-VNNI-INT8/INT16 forms, which AVX10.2 promotes to EVEX and compilers still emit."""
    J = json.load(open(path))
    done = set()
    for n in sorted(J["!instanceof"]["X86Inst"]):
        r = J[n]
        ps = [p["def"] for p in r.get("Predicates", [])]
        if r.get("isCodeGenOnly") or r["OpEnc"]["def"] != "EncVEX" or not set(ps) & {"HasAVXVNNIINT8", "HasAVXVNNIINT16"}:
            continue
        mn = r["AsmString"].split()[0]
        l = r["hasVEX_L"]
        k = (mn, l)
        if k in done:
            continue
        done.add(k)
        V, m, b = ("Ymm", "m256", 32) if l else ("Xmm", "m128", 16)
        op = gen.op("avx10_" + mn)
        gen.ctors.append(
            "# %s\n:%s %sReg1, vexVVVV_%sReg, %sReg2_%s is $(VEX_NDS) & $(VEX_L%d) & %s & $(VEX_0F38) & $(VEX_W0) & vexVVVV_%sReg; "
            "byte=0x%02x; (%sReg1 & ZmmReg1) ... & %sReg2_%s\n{\n\tlocal res:%d = %s(%sReg1, vexVVVV_%sReg, %sReg2_%s);\n\tZmmReg1 = zext(res);\n}\n"
            % (n, mn.upper(), V, V, V, m, 256 if l else 128, PRE[r["OpPrefix"]["def"]], V, bits(r["Opcode"]), V, V, m, b, op, V, V, V, m))


def main():
    recs = load(sys.argv[1])
    groups = collections.OrderedDict()
    for r in recs:
        k = (r["mn"], r["map"], r["pre"], r["opc"], r["w"], r["vl"], r["igl"], r["mem"], r["form"].replace("Mem", "Reg"))
        groups.setdefault(k, []).append(r)
    g = Gen()
    for r in recs:
        if r["b"] and not r["mem"]:
            g.bkeys[bkey(r)] = True
    for grp in groups.values():
        g.group(grp)
    vex_vnni(sys.argv[1], g)
    out = [HEADER, "@ifdef IA64", ""]
    out += ["define pcodeop %s;" % o for o in g.ops]
    out += [""] + ['avx10CmpBf16: "VCMP%sBF16" is imm8=%d { }' % (p, i) for i, p in enumerate(CMP_PRED)] + [
            'avx10CmpBf16: "VCMPBF16" is imm8 { }', "",
            'avx10Rc: "{rn-sae}" is evexL=0 { }', 'avx10Rc: "{rd-sae}" is evexL=1 { }',
            'avx10Rc: "{ru-sae}" is evexL=2 { }', 'avx10Rc: "{rz-sae}" is evexL=3 { }', ""]
    out += list(g.memtabs.values()) + [""]
    out += g.ctors
    out += ["@endif", ""]
    open(sys.argv[2], "w").write("\n".join(out))
    print("%d records, %d constructors, %d user operations" % (len(recs), len(g.ctors), len(g.ops)), file=sys.stderr)


if __name__ == "__main__":
    main()
