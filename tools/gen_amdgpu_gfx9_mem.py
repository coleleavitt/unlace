#!/usr/bin/env python3
"""GFX9 MIMG, MTBUF and VINTRP (and the VOP3 v_interp forms), with their CDNA use.

Layouts from llvm-mc -mcpu=gfx900 -show-encoding:
  MIMG (bits 31-26 = 111100): dmask 8-11, unorm 12, glc 13, da 14, a16 15, tfe 16, lwe 17, op 18-24,
    slc 25; word 1 vaddr 0-7, vdata 8-15, srsrc 16-20 (x4), ssamp 21-25 (x4), d16 31.  The
    encoding does not carry the address size; the address range shown is the one llvm-objdump
    prints for the opcode ('amdgpu_cdna_probe.py mimg9').  The data count is the dmask's bit
    count (4 for gather4), halved and rounded up with d16, plus one with tfe; MD sets it in the
    context field mi_vdn (declared in the GFX9 spec, with mi_tf holding tfe until d16 is known), which picks the data
    tuple.
  MTBUF (111010): offset 0-11, offen 12, idxen 13, glc 14, op 15-18, dfmt 19-22, nfmt 23-25; word
    1 vaddr 0-7, vdata 8-15, srsrc 16-20 (x4), slc 22, tfe 23, soffset 24-31.  The address is the
    resource base (low 48 bits) plus soffset, offset, the offen VGPR and the idxen VGPR times the
    stride; the format spellings are llvm-objdump's ('amdgpu_cdna_probe.py mtbuf9').
  VINTRP (110101): vsrc 0-7, attr_chan 8-9, attr 10-15, op 16-17 (p1, p2, mov), vdst 18-25; the
    VOP3 forms carry attr/chan (and high) in src0.
Image operations and the interpolations are user-ops; typed loads and stores move the dwords.

With --cdna (amdgcn_cdna_mem.sinc, which the CDNA specs use instead): the bit GFX9 uses for tfe
(MIMG word 0 bit 16, MTBUF word 1 bit 23) is acc, which makes the data operand AGPRs.

usage: gen_amdgpu_gfx9_mem.py [--cdna] mimg9.txt mtbuf9.txt amdgcn_gfx9.slaspec [include ...] > amdgcn_gfx9_mem.sinc
"""
import re
import sys


CDNA = len(sys.argv) > 1 and sys.argv[1] == '--cdna'
if CDNA:
    del sys.argv[1]


def areg(s, n):
    return 'a%d' % s if n == 1 else 'at%d_%d' % (s, s + n - 1)


def vreg(s, n):
    return {1: 'v%d' % s, 2: 'v%d_%d' % (s, s + 1)}.get(n, 'vt%d_%d' % (s, s + n - 1))


def rng(s, n):
    return 'v%d' % s if n == 1 else 'v[%d:%d]' % (s, s + n - 1)


def main():
    mimg = [l.split() for l in open(sys.argv[1]) if l.strip() and not l.startswith('#')]
    mt = [l.split(None, 3) for l in open(sys.argv[2]) if l.strip()]
    text = ''.join(open(f).read() for f in sys.argv[3:])
    have = set(re.findall(r'define pcodeop (\w+);', text))
    s4 = re.search(r'define register offset=0x0+ size=4 \[([^\]]*)\]', text).group(1).split()
    o, body = [], []
    w = o.append
    b = body.append
    ops = set()
    w('# Generated by tools/gen_amdgpu_gfx9_mem.py; edit the generator.')
    for n in (3, 4, 5):
        for k in range(n):
            w('define register offset=0x%x size=%d [ %s ];' % (0x1000 + 4 * k, 4 * n,
                                                               ' '.join(vreg(s, n) for s in range(k, 256 - n + 1, n))))
    if CDNA:
        for n in (3, 4, 5):
            for k in range(n):
                w('define register offset=0x%x size=%d [ %s ];' % (0x6000 + 4 * k, 4 * n,
                                                                   ' '.join(areg(s, n) for s in range(k, 256 - n + 1, n))))
    w('define register offset=0x4300 size=32 [ mimg9_data ];')
    w('define token mg0(32) mg_dmask = (8,11) mg_unorm = (12,12) mg_glc = (13,13) mg_da = (14,14) mg_a16 = (15,15)'
      ' mg_tfe = (16,16) mg_lwe = (17,17) mg_op = (18,24) mg_slc = (25,25) mg_e6 = (26,31);')
    w('define token mg1(32) mg_vaddr = (0,7) mg_vdata = (8,15) mg_rsrc = (16,20) mg_ssamp = (21,25) mg_d16 = (31,31);')
    w('define token mt0(32) mt_off = (0,11) mt_offen = (12,12) mt_idxen = (13,13) mt_glc = (14,14) mt_op = (15,18)'
      ' mt_dfmt = (19,22) mt_nfmt = (23,25) mt_e6 = (26,31);')
    w('define token mt1(32) mt_vaddr = (0,7) mt_vdata = (8,15) mt_rsrc = (16,20) mt_slc = (22,22) mt_tfe = (23,23)'
      ' mt_soff = (24,31) mt_soffr = (24,31) mt_soffh = (31,31);')
    w('define token vin(32) vi_vsrc = (0,7) vi_par = (0,7) vi_chan = (8,9) vi_attr = (10,15) vi_op = (16,17) vi_vdst = (18,25)'
      ' vi_e6 = (26,31);')
    w('define token vi30(32) vo_vdst = (0,7) vo_clamp = (15,15) vo_op = (16,25) vo_e6 = (26,31);')
    w('define token vi31(32) vo_attr = (0,5) vo_chan = (6,7) vo_high = (8,8) vo_s0hi = (9,9) vo_src1 = (9,16)'
      ' vo_par = (9,16) vo_s1v = (17,17) vo_src2 = (18,25) vo_s2v = (26,26);')
    w('attach variables [ mt_vdata vi_vsrc vi_vdst vo_vdst vo_src1 vo_src2 ] [ %s ];' % ' '.join('v%d' % i for i in range(256)))
    w('attach variables [ mt_soffr ] [ %s ];' % ' '.join(s4 + ['_'] * (256 - len(s4))))
    w('MTS: mt_soffr is mt_soffr & mt_soffh=0 { export mt_soffr; }')
    for v in range(128, 209):
        c = v - 128 if v <= 192 else 192 - v
        w('MTS: "%d" is mt_soff=%d { t:4 = 0x%x; export t; }' % (c, v, c & 0xffffffff))
    tabs = {}

    def table(name, field, n, exp=None, agpr=False):
        t = '%s%d' % (name, n)
        if t not in tabs:
            tabs[t] = ['%s: "%s" is %s=%d { export %s; }' % (
                t, ('a' + rng(s, n)[1:]) if agpr else rng(s, n), field, s,
                exp(s) if exp else (areg if agpr else vreg)(s, n)) for s in range(256 - n + 1)]
        return t
    # ---- MIMG
    for dm in range(16):
        for fixed in (0, 1):
            c = 4 if fixed else max(1, bin(dm).count('1'))
            for tfe in (0, 1):
                w('M9%s: is mg_dmask=%d & mg_tfe=%d [ mi_vdn = %d; mi_tf = %d; ] { }' % ('F' if fixed else 'D', dm, tfe, c, tfe))
    tf = '' if CDNA else ' + mi_tf'      # on CDNA the bit is acc and adds no dword
    w('M9H: is mg_d16=0 [ mi_vdn = mi_vdn%s; ] { }' % tf)
    w('M9H: is mg_d16=1 [ mi_vdn = (mi_vdn + 1) / 2%s; ] { }' % tf)
    for n in range(1, 6):
        for s in range(256 - n + 1):
            for acc in ((0, 1) if CDNA else (None,)):
                c = '' if acc is None else ' & mi_tf=%d' % acc
                r = areg(s, n) if acc else vreg(s, n)
                d = ('a' + rng(s, n)[1:]) if acc else rng(s, n)
                w('M9V: "%s" is mi_vdn=%d%s & mg_vdata=%d { }' % (d, n, c, s))
                w('M9W: is mi_vdn=%d%s & mg_vdata=%d { %s = mimg9_data:%d; }' % (n, c, s, r, 4 * n))
                w('M9X: is mi_vdn=%d%s & mg_vdata=%d { mimg9_data = zext(%s); }' % (n, c, s, r))
    for s in range(0, 128, 4):
        if s + 8 <= len(s4):
            w('M9R: "s[%d:%d]" is mg_rsrc=%d { export %s; }' % (s, s + 7, s // 4, s4[s]))
        if s + 4 <= len(s4):
            w('M9S: "s[%d:%d]" is mg_ssamp=%d { export %s; }' % (s, s + 3, s // 4, s4[s]))
    fl = [('unorm', 'mg_unorm'), ('glc', 'mg_glc'), ('slc', 'mg_slc'), ('a16', 'mg_a16')] + (
        [] if CDNA else [('tfe', 'mg_tfe')]) + [('lwe', 'mg_lwe'), ('da', 'mg_da')]
    for v in range(1 << len(fl)):
        on = [f for i, (f, _) in enumerate(fl) if (v >> i) & 1]
        w('M9G: %sis %s { }' % ('"%s" ' % ''.join(' ' + f for f in on) if on else '',
                                ' & '.join('%s=%d' % (x, (v >> i) & 1) for i, (_, x) in enumerate(fl))))
    w('M9E: is mg_d16=0 { }')
    w('M9E: " d16" is mg_d16=1 { }')
    for op, mn, samp, n in mimg:
        op, samp, n = int(op), int(samp), int(n)
        fixed = mn.startswith('image_gather4')
        cnt = 'M9F' if fixed else 'M9D'
        store = mn.startswith('image_store')
        atomic = mn.startswith('image_atomic')
        if mn not in have:
            ops.add(mn)
        a = table('M9A', 'mg_vaddr', n, lambda s: 'v%d' % s)
        io = 'M9X' if store else ('M9W & M9X' if atomic else 'M9W')
        srcs = [a, 'M9R'] + (['M9S'] if samp else [])
        disp = '%s %s^M9H^M9V, %s^" dmask:"^mg_dmask^M9G^M9E' % (mn, cnt, ', '.join(srcs))
        pat = ('(mg_e6=0x3c & mg_op=%d & mg_dmask & %s & M9G ; M9H & M9V & %s & %s & M9R%s & M9E)'
               % (op, cnt, io, a, ' & M9S' if samp else ''))
        args = 'M9R, ' + ('M9S, ' if samp else '') + a
        if store:
            sem = 'build M9X; %s(%s, mimg9_data);' % (mn, args)
        elif atomic:
            sem = 'build M9X; mimg9_data = %s(%s, mimg9_data); build M9W;' % (mn, args)
        else:
            sem = 'mimg9_data = %s(%s); build M9W;' % (mn, args)
        b(':%s is %s { %s }' % (disp, pat, sem))
    # ---- MTBUF
    fmts = {}
    for row in mt:
        if row[0] == 'fmt':
            d, n, s = row[1], row[2], row[3].strip()
            fmts[(int(d), int(n))] = s
    for (d, n), s in sorted(fmts.items()):
        w('MTF: %sis mt_dfmt=%d & mt_nfmt=%d { }' % ('" %s" ' % s if s != '-' else '', d, n))
    w('MTO: is mt_off=0 { }')
    w('MTO: " offset:"^mt_off is mt_off { }')
    for v in range(4 if CDNA else 8):
        on = [f for i, f in enumerate(('glc', 'slc', 'tfe')) if (v >> i) & 1]
        w('MTG: %sis mt_glc=%d ; mt_slc=%d%s { }' % ('"%s" ' % ''.join(' ' + f for f in on) if on else '',
                                                    v & 1, (v >> 1) & 1, '' if CDNA else ' & mt_tfe=%d' % (v >> 2)))
    rs = ['MTR: "s[%d:%d]" is mt_rsrc=%d { r:8 = zext(%s) | (zext(%s) << 32); export r; }' % (s, s + 3, s // 4, s4[s], s4[s + 1])
          for s in range(0, 104, 4)]
    o.extend(rs)
    v1 = table('MTV', 'mt_vaddr', 1)
    v2 = table('MTV', 'mt_vaddr', 2)
    w('MTA: "off, "^MTR^", "^MTS is mt_offen=0 & mt_idxen=0 & mt_off ; MTR & MTS '
      '{ a:8 = (MTR & 0xffffffffffff) + zext(MTS) + mt_off; export a; }')
    w('MTA: %s^", "^MTR^", "^MTS is mt_offen=1 & mt_idxen=0 & mt_off ; %s & MTR & MTS '
      '{ a:8 = (MTR & 0xffffffffffff) + zext(MTS) + zext(%s) + mt_off; export a; }' % (v1, v1, v1))
    w('MTA: %s^", "^MTR^", "^MTS is mt_offen=0 & mt_idxen=1 & mt_off ; %s & MTR & MTS '
      '{ st:8 = (MTR >> 48) & 0x3fff; a:8 = (MTR & 0xffffffffffff) + zext(MTS) + zext(%s) * st + mt_off; export a; }'
      % (v1, v1, v1))
    w('MTA: %s^", "^MTR^", "^MTS is mt_offen=1 & mt_idxen=1 & mt_off ; %s & MTR & MTS '
      '{ st:8 = (MTR >> 48) & 0x3fff; i:4 = %s:4; v:4 = %s(4); a:8 = (MTR & 0xffffffffffff) + zext(MTS) + zext(i) * st + zext(v) + mt_off; export a; }'
      % (v2, v2, v2, v2))
    w('MTI: is mt_offen=0 & mt_idxen=0 { }')
    w('MTI: " offen" is mt_offen=1 & mt_idxen=0 { }')
    w('MTI: " idxen" is mt_offen=0 & mt_idxen=1 { }')
    w('MTI: " idxen offen" is mt_offen=1 & mt_idxen=1 { }')
    for row in mt:
        if row[0] != 'op':
            continue
        op, mn = int(row[1]), row[2]
        m = re.match(r'tbuffer_(load|store)_format_(d16_)?(x|xy|xyz|xyzw)$', mn)
        if not m:
            continue
        n = len(m.group(3))
        if m.group(2):
            n = (n + 1) // 2
        for acc in ((0, 1) if CDNA else (None,)):
            d = table('MTDA' if acc else 'MTD', 'mt_vdata', n, agpr=bool(acc))
            if m.group(1) == 'load':
                sem = '%s = *:%d MTA;' % (d, 4 * n)
            else:
                sem = '*:%d MTA = %s;' % (4 * n, d)
            c = '' if acc is None else 'mt_tfe=%d & ' % acc
            b(':%s %s, MTA^MTF^MTI^MTO^MTG is (mt_e6=0x3a & mt_op=%d & MTF & MTI & MTO ; %s%s) & MTA & MTG { %s }'
              % (mn, d, op, c, d, sem))
    # ---- VINTRP and the VOP3 interpolations
    chan = 'xyzw'
    for c in range(4):
        for a in range(64):
            w('VIA: "attr%d.%s" is vi_attr=%d & vi_chan=%d { }' % (a, chan[c], a, c))
            w('VOA: "attr%d.%s" is vo_attr=%d & vo_chan=%d { }' % (a, chan[c], a, c))
    w('VOH: is vo_high=0 { }')
    w('VOH: " high" is vo_high=1 { }')
    for p, nm in enumerate(('p10', 'p20', 'p0')):
        w('VIP: "%s" is vi_par=%d { }' % (nm, p))
    for nm in ('interp_p1', 'interp_p2', 'interp_mov', 'interp_p1ll', 'interp_p1lv', 'interp_p2_legacy', 'interp_p2_f16'):
        if nm not in have:
            ops.add(nm)
    b(':v_interp_p1_f32_e32 vi_vdst, vi_vsrc, VIA is vi_e6=0x35 & vi_op=0 & vi_vdst & vi_vsrc & vi_attr & vi_chan & VIA '
      '{ a:1 = vi_attr; c:1 = vi_chan; vi_vdst = interp_p1(vi_vsrc, a, c); }')
    b(':v_interp_p2_f32_e32 vi_vdst, vi_vsrc, VIA is vi_e6=0x35 & vi_op=1 & vi_vdst & vi_vsrc & vi_attr & vi_chan & VIA '
      '{ a:1 = vi_attr; c:1 = vi_chan; vi_vdst = interp_p2(vi_vdst, vi_vsrc, a, c); }')
    b(':v_interp_mov_f32_e32 vi_vdst, VIP, VIA is vi_e6=0x35 & vi_op=2 & vi_vdst & vi_par & vi_attr & vi_chan & VIP & VIA '
      '{ a:1 = vi_attr; c:1 = vi_chan; p:1 = vi_par; vi_vdst = interp_mov(p, a, c); }')
    e64 = {624: ('v_interp_p1_f32_e64', 'interp_p1', 1), 625: ('v_interp_p2_f32_e64', 'interp_p2', 1),
           626: ('v_interp_mov_f32_e64', 'interp_mov', 0), 628: ('v_interp_p1ll_f16', 'interp_p1ll', 1),
           629: ('v_interp_p1lv_f16', 'interp_p1lv', 2), 630: ('v_interp_p2_legacy_f16', 'interp_p2_legacy', 2),
           631: ('v_interp_p2_f16', 'interp_p2_f16', 2)}
    for op, (mn, fn, nsrc) in sorted(e64.items()):
        if (':%s ' % mn) in text:
            continue
        if nsrc == 0:
            b(':%s vo_vdst, VOMP, VOA is (vo_e6=0x34 & vo_op=%d & vo_vdst ; vo_par & vo_attr & vo_chan & VOMP & VOA) '
              '{ a:1 = vo_attr; c:1 = vo_chan; p:1 = vo_par; vo_vdst = %s(p, a, c); }' % (mn, op, fn))
            continue
        srcs = 'vo_vdst, vo_src1, VOA' + (', vo_src2' if nsrc == 2 else '')
        args = ('vo_vdst, ' if fn.startswith('interp_p2') else '') + 'vo_src1, a, c' + (', vo_src2' if nsrc == 2 else '')
        b(':%s %s^VOH is (vo_e6=0x34 & vo_op=%d & vo_vdst ; vo_s1v=1 & vo_src1 & vo_attr & vo_chan & VOA & VOH%s) '
          '{ a:1 = vo_attr; c:1 = vo_chan; vo_vdst = %s(%s); }' % (
              mn, srcs, op, ' & vo_s2v=1 & vo_src2' if nsrc == 2 else '', fn, args))
    for p, nm in enumerate(('p10', 'p20', 'p0')):
        w('VOMP: "%s" is vo_par=%d { }' % (nm, p))
    for nm in sorted(ops - have):
        w('define pcodeop %s;' % nm)
    defs = [l for l in o if l.startswith(('define', 'attach', '#'))]
    first = [l for l in o if l.startswith(('MTS:', 'MTR:'))]   # MTA uses them
    rest = [l for l in o if l not in defs and l not in first]
    defs = defs + first
    t = [r for k in sorted(tabs) for r in tabs[k]]
    print('\n'.join(defs + t + rest + [''] + body))


main()
