use super::*;

/// The helpers as lld-link laid them out from `clang --target=thumbv7-windows-msvc`, with the
/// cookie at 0x402000 (`movw r12,#0x2000; movt r12,#0x40`), behind a two-byte `nop`.
const CODE: [u8; 52] = [
    0x00, 0xbf, 0x81, 0xb0, 0x42, 0xf2, 0x00, 0x0c, 0xc0, 0xf2, 0x40, 0x0c, 0xdc, 0xf8, 0x00, 0xc0,
    0xad, 0xeb, 0x0c, 0x0c, 0xcd, 0xf8, 0x00, 0xc0, 0x70, 0x47, 0x42, 0xf2, 0x00, 0x0c, 0xc0, 0xf2,
    0x40, 0x0c, 0x00, 0x9b, 0xdc, 0xf8, 0x00, 0xc0, 0xad, 0xeb, 0x03, 0x03, 0x63, 0x45, 0x01, 0xd1,
    0x01, 0xb0, 0x70, 0x47,
];

#[test]
fn both_helpers_match_whatever_the_cookie_address() {
    assert_eq!(
        scan_bytes(&CODE, 0x401026),
        [
            (0x401028, "__security_push_cookie"),
            (0x401040, "__security_pop_cookie"),
        ]
    );
}

#[test]
fn a_changed_instruction_or_an_odd_offset_does_not() {
    let mut other = CODE;
    other[20] = 0xce; // str.w r12,[sp] -> another register base
    assert_eq!(
        scan_bytes(&other, 0x401026),
        [(0x401040, "__security_pop_cookie")]
    );
    assert!(scan_bytes(&CODE[1..], 0x401027).is_empty());
}
