def operand(kind, z, slot):
    if kind == "e":
        return "XA%d_%d" % (slot, z)
    return "AM%d_%d" % (slot, z)


def emit_f12():
    for opc, mn, s1, k1, s2, k2, sem, forms in F12:
        # F1, AM is operand 1, register operand 2
        a1 = operand(k1, s1, 1)
        r2 = "c_reg" if k2 == "e" else CREG[s2]
        f2c = "c_f2=0 & " if "2" in forms else ""
        w(":%s %s, %s is op=0x%02x; %sc_d=1 & c_m & %s; %s [ m1 = c_m; ] { %s }"
          % (mn, a1, r2, opc, f2c, r2, a1, sem(a1, r2, s1, s2)))
        # F1, register operand 1, AM operand 2
        a2 = operand(k2, s2, 1)
        r1 = "c_reg" if k1 == "e" else CREG[s1]
        w(":%s %s, %s is op=0x%02x; %sc_d=0 & c_m & %s; %s [ m1 = c_m; ] { %s }"
          % (mn, r1, a2, opc, f2c, r1, a2, sem(r1, a2, s1, s2)))
        if "2" in forms:
            b1 = operand(k1, s1, 1)
            b2 = operand(k2, s2, 2)
            w(":%s %s, %s is op=0x%02x; c_f2=1 & c_m & c_d; %s; %s [ m1 = c_m; m2 = c_d; ] { %s }"
              % (mn, b1, b2, opc, b1, b2, sem(b1, b2, s1, s2)))
    # call: constant targets get a direct call
    w(":call CT1, XA2_4 is op=0x49; c_f2=1 & c_m=0 & c_d; CT1; XA2_4 [ m2 = c_d; ] { %s }"
      % s_call("CT1", "XA2_4", 1, 4))
    w(":call XA1_1, XA2_4 is op=0x49; c_f2=1 & c_m & c_d; XA1_1; XA2_4 [ m1 = c_m; m2 = c_d; ] { %s }"
      % s_callind("XA1_1", "XA2_4", 1, 4))
    w(":call XA1_1, c_reg is op=0x49; c_f2=0 & c_d=1 & c_m & c_reg; XA1_1 [ m1 = c_m; ] { %s }"
      % s_callind("XA1_1", "c_reg", 1, 4))
    w(":call c_reg, XA1_4 is op=0x49; c_f2=0 & c_d=0 & c_m & c_reg; XA1_4 [ m1 = c_m; ] { %s }"
      % s_callind("c_reg", "XA1_4", 4, 4))
    w("")


def f3(opc, mn, z, kind, body):
    t = ("XA1_%d" if kind == "e" else "AM1_%d") % z
    w(":%s %s is op_hi7=0x%02x & op_lo1; %s [ m1 = op_lo1; ] { %s }" % (mn, t, opc >> 1, t, body.replace("$", t)))


def pushm_body():
    lines = ["local mask:4 = $;",
             "if ((mask & 0x80000000) == 0) goto <s31>; packpsw(); SP = SP - 4; *:4 SP = PSW; <s31>"]
    for i in range(30, -1, -1):
        lines.append("if ((mask & 0x%x) == 0) goto <s%d>; SP = SP - 4; *:4 SP = %s; <s%d>" % (1 << i, i, REGS[i], i))
    return " ".join(lines)


def popm_body():
    lines = ["local mask:4 = $;"]
    for i in range(31):
        lines.append("if ((mask & 0x%x) == 0) goto <s%d>; %s = *:4 SP; SP = SP + 4; <s%d>" % (1 << i, i, REGS[i], i))
    lines.append("if ((mask & 0x80000000) == 0) goto <s31>; packpsw(); "
                 "PSW = (PSW & 0xffff0000) | zext(*:2 SP); SP = SP + 4; unpackpsw(); <s31>")
    return " ".join(lines)


