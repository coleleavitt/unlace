def fld(t, lo, hi, signed=False):
    n = f"{t}_y{'s' if signed else ''}{lo}_{hi}"
    fields[n] = (t, f"{n}=({lo},{hi})" + (" signed" if signed else ""))
    return n


def reg(t, lo, kind):
    n = f"{t}_y{kind}{lo}"
    fields[n] = (t, f"{n}=({lo},{lo + 3})")
    attach.setdefault(kind, set()).add(n)
    return n


def span(vb):
    lo, hi = min(vb.values()), max(vb.values())
    assert sorted(vb.values()) == list(range(lo, hi + 1))
    return lo, hi


def addr(t, vbs, kind):
    """(subtable, length field) for an address operand."""
    b = vbs.get(kind[0])
    blo, _ = span(b)
    dlo, dhi = span(vbs["D"])
    br = reg(t, blo, "r")
    bz = fld(t, blo, blo + 3)
    twenty = dhi - dlo == 19
    if twenty:
        dl = fld(t, dlo + 8, dlo + 19)
        dh = fld(t, dlo, dlo + 7, True)
        dpat, act, disp = f"{dl} & {dh}", f" [ disp = ({dh} << 12) | {dl}; ]", "disp"
    else:
        d = fld(t, dlo, dhi)
        dpat, act, disp = d, "", d
    name = f"A{t}_{blo}_{dlo}"
    extra = None
    lines = []
    if "X" in vbs:
        xlo, _ = span(vbs["X"])
        xr, xz = reg(t, xlo, "r"), fld(t, xlo, xlo + 3)
        name += f"_x{xlo}"
        lines += [f"{name}: {disp}({xr},{br}) is {xr} & {br} & {dpat}{act} {{ local ea:8 = {xr} + {br} + {disp}; export ea; }}",
                  f"{name}: {disp}({xr}) is {xr} & {bz}=0 & {dpat}{act} {{ local ea:8 = {xr} + {disp}; export ea; }}",
                  f"{name}: {disp}({br}) is {xz}=0 & {br} & {dpat}{act} {{ local ea:8 = {br} + {disp}; export ea; }}",
                  f"{name}: {disp} is {xz}=0 & {bz}=0 & {dpat}{act} {{ export *[const]:8 {disp}; }}"]
    elif "L" in vbs:
        llo, lhi = span(vbs["L"])
        lf = fld(t, llo, lhi)
        name += f"_l{llo}"
        a2 = act[:-2] + " ln = " + lf + " + 1; ]" if act else f" [ ln = {lf} + 1; ]"
        lines += [f"{name}: {disp}(ln,{br}) is {br} & {lf} & {dpat}{a2} {{ local ea:8 = {br} + {disp}; export ea; }}",
                  f"{name}: {disp}(ln) is {bz}=0 & {lf} & {dpat}{a2} {{ export *[const]:8 {disp}; }}"]
        extra = lf
    elif "R" in vbs:
        rlo, _ = span(vbs["R"])
        rr = reg(t, rlo, "r")
        name += f"_r{rlo}"
        lines += [f"{name}: {disp}({rr},{br}) is {rr} & {br} & {dpat}{act} {{ local ea:8 = {br} + {disp}; export ea; }}",
                  f"{name}: {disp}({rr}) is {rr} & {bz}=0 & {dpat}{act} {{ export *[const]:8 {disp}; }}"]
        extra = rr
    else:
        lines += [f"{name}: {disp}({br}) is {br} & {dpat}{act} {{ local ea:8 = {br} + {disp}; export ea; }}",
                  f"{name}: {disp} is {bz}=0 & {dpat}{act} {{ export *[const]:8 {disp}; }}"]
    subs[name] = "\n".join(lines) + "\n"
    return name, extra


KIND = {"GRH32": "rh", "AR32": "a", "CR64": "c", "GR64": "r", "ADDR64": "r", "GR32": "rl", "FP64": "f", "FP32": "fs", "FP128": "f", "GR128": "r"}


def operands(ins):
    t = TOK[len(ins["bits"])]
    varbits = {}
    for pos, b in enumerate(ins["bits"]):
        if isinstance(b, list):
            varbits.setdefault(b[0], {})[b[1]] = pos
    tied = {m.group(1): m.group(2) for m in re.finditer(r"\$(\w+) = \$(\w+)", ins["constraints"])}
    tied.update({m.group(2): m.group(1) for m in re.finditer(r"\$(\w+) = \$(\w+)", ins["constraints"])})
    sym, pat, kinds = {}, [], {}
    for ty, v in ins["outs"] + ins["ins"]:
        if isinstance(v, list):
            vbs = {}
            for name in v:
                vbs[name[0]] = varbits[name]
            s, extra = addr(t, vbs, "B")
            key = "".join(x[0] for x in v) + v[0][-1]
            sym[tuple(v)] = (s, extra, ty)
            pat.append(s)
            if extra:
                pat.append(extra)
            kinds[tuple(v)] = ty
            continue
        if v in sym:
            continue
        if v not in varbits:
            if v in tied and tied[v] in sym:
                sym[v] = sym[tied[v]]
            continue
        lo, hi = span(varbits[v])
        if ty in KIND:
            n = reg(t, lo, KIND[ty])
            pair = None
            if ty == "FP128":
                pair = reg(t, lo, "fq")
            elif ty == "GR128":
                pair = reg(t, lo, "rp")
            sym[v] = (n, pair, ty)
            pat.append(n)
            if pair:
                pat.append(pair)
        elif ty.startswith("brtarget"):
            f = fld(t, lo, hi, True)
            n = f"REL_{f}"
            subs[n] = f"{n}: reloc is {f} [ reloc = inst_start + 2 * {f}; ] {{ export *[const]:8 reloc; }}\n"
            sym[v] = (n, None, "rel")
            pat.append(n)
        elif ty.startswith("imm"):
            n = fld(t, lo, hi, "sx" in ty)
            sym[v] = (n, None, "imm")
            pat.append(n)
        else:
            raise KeyError(ty)
        kinds[v] = ty
        if v in tied:
            sym[tied[v]] = sym[v]
    fixed = [p for p, b in enumerate(ins["bits"]) if isinstance(b, int)]
    runs, start = [], None
    for p in fixed + [None]:
        if start is not None and (p is None or p != prev + 1):
            runs.append((start, prev)); start = None
        if p is not None:
            if start is None:
                start = p
            prev = p
    for lo, hi in runs:
        val = sum(ins["bits"][p] << (p - lo) for p in range(lo, hi + 1))
        pat.insert(0, f"{fld(t, lo, hi)}={val}")
    return t, sym, pat, tied


def disp_of(ins, sym):
    s = ins["asm"].replace("{\t| }", " ").replace("{, |,}", ",")

    def sub(m):
        v = m.group(1)
        for k, x in sym.items():
            if isinstance(k, tuple) and v in ("XBD" + k[0][-1], "BD" + k[0][-1], "BDL" + k[0][-1], "BDR" + k[0][-1], "RBD" + k[0][-1]):
                return x[0]
        if v in sym:
            return sym[v][0]
        return v
    return re.sub(r"\$(\w+)", sub, s)


def hfp_sign(mn, w, d, s):
    """LOAD POSITIVE/NEGATIVE/COMPLEMENT/AND TEST (HFP): the sign bit only; CC 0 for a zero
    fraction, else 1 (negative) or 2 (positive)."""
    top = 1 << (8 * w - 1)
    frac = (1 << (8 * w - 8)) - 1
    op = {"lp": f"x & 0x{top - 1:x}", "ln": f"x | 0x{top:x}", "lc": f"x ^ 0x{top:x}", "lt": "x"}[mn[:2]]
    return (f"local x:{w} = {s}; local res:{w} = {op}; local z:1 = (res & 0x{frac:x}) == 0; "
            f"CC0 = z; CC1 = !z && (res s< 0); CC2 = !z && (res s>= 0); CC3 = 0; ccAux(); {d} = res;")


def sem(ins, mn, sym):
    def S(v):
        return sym[v][0]
    ops = [v for _, v in ins["outs"] + ins["ins"]]
    mem = [sym[k] for k in sym if isinstance(k, tuple)]
    if re.fullmatch(r"l[pnct][de]r", mn):
        w = 8 if mn[2] == "d" else 4
        return hfp_sign(mn, w, S("R1"), S("R2"))
    if mn in ("mdebr", "mdeb"):
        y = S("R2") if mn == "mdebr" else None
        pre = "" if y else f"local m:4 = *:4 {mem[0][0]}; "
        return pre + f"local l:8 = {S('R1src')}; local h:4 = l(4); local a:8 = float2float(h); local b:8 = float2float({y or 'm'}); {S('R1')} = a f* b;"
    if mn in ("madb", "msdb", "maeb", "mseb"):
        w = 8 if mn[2] == "d" else 4
        o = "f+" if mn[1] == "a" else "f-"
        return f"local m:{w} = *:{w} {mem[0][0]}; {S('R1')} = ({S('R3')} f* m) {o} {S('R1')};"
    if mn == "mxdb":
        hi, lo = sym["R1"][0], sym["R1"][1]
        return (f"local m:8 = *:8 {mem[0][0]}; local x:16 = float2float({hi}); local y:16 = float2float(m); "
                f"local res:16 = x f* y; {hi} = res(8); {lo} = res:8;")
    if mn == "lzrg":
        return f"local v:8 = *:8 {mem[0][0]}; {S('R1')} = v & 0xffffffffffffff00;"
    if mn == "lzrf":
        return f"local v:4 = *:4 {mem[0][0]}; {S('R1')} = v & 0xffffff00;"
    if mn == "llzrgf":
        return f"local v:4 = *:4 {mem[0][0]}; {S('R1')} = zext(v & 0xffffff00);"
    if mn in ("lpd", "lpdg"):
        w = 4 if mn == "lpd" else 8
        ev, od = sym["R3"][0], sym["R3"][1]
        lo = "" if w == 8 else "l"
        return (f"local a:{w} = *:{w} {mem[0][0]}; local b:{w} = *:{w} {mem[1][0]}; "
                f"{ev}{'' if w == 8 else ''} = {'a' if w == 8 else 'zext(a) | (' + ev + ' & 0xffffffff00000000)'}; "
                f"{od} = {'b' if w == 8 else 'zext(b) | (' + od + ' & 0xffffffff00000000)'}; "
                "CC0 = 1; CC1 = 0; CC2 = 0; CC3 = 0; ccAux();")
    if mn in ("lpsw", "lpswe", "lpswey"):
        # the new PSW's instruction address: bits 33-63 of an ESA/390 PSW, 64-127 of a z PSW
        a = mem[0][0]
        pcodeops.add("hd_" + mn)
        nxt = f"local na:4 = *:4 ({a} + 4); local tg:8 = zext(na & 0x7fffffff);" if mn == "lpsw" else f"local tg:8 = *:8 ({a} + 8);"
        return f"{nxt} hd_{mn}({a}); return [tg];"
    if mn == "lfpc":
        return f"fpc = *:4 {mem[0][0]};"
    if mn == "stfpc":
        return f"*:4 {mem[0][0]} = fpc;"
    if mn in ("srnm", "srnmb", "srnmt"):
        a = mem[0][0]
        m, sh = {"srnm": (3, 0), "srnmb": (7, 0), "srnmt": (7, 4)}[mn]
        return f"local v:4 = {a}:4; fpc = (fpc & ~0x{m << sh:x}) | ((v & {m}) << {sh});"
    if mn == "ts":
        a = mem[0][0]
        return f"local v:1 = *:1 {a}; *:1 {a} = 0xff; CC0 = (v & 0x80) == 0; CC1 = (v & 0x80) != 0; CC2 = 0; CC3 = 0; ccAux();"
    return None


def userop(ins, mn, sym, tied):
    op = "hd_" + mn
    args = []
    for ty, v in ins["ins"]:
        key = tuple(v) if isinstance(v, list) else v
        if key not in sym:
            continue
        s, extra, k = sym[key]
        if isinstance(v, list):
            args.append(s)
            if extra:
                args.append(extra if k != "bdladdr12onlylen4" and k != "bdladdr12onlylen8" else f"len_{s}")
        elif k == "imm":
            args.append(f"imm_{s}")
        else:
            args.append(s)
            if extra:
                args.append(extra)
    args += [IMPL[u] for u in ins.get("uses", []) if u in IMPL]
    pre = []
    for a in list(args):
        if a.startswith("imm_"):
            pre.append(f"local {a}:8 = {a[4:]};")
        if a.startswith("len_"):
            f = [sym[k][1] for k in sym if isinstance(k, tuple) and sym[k][0] == a[4:]][0]
            pre.append(f"local {a}:8 = {f}; {a} = {a} + 1;")
    body = list(dict.fromkeys(pre))
    outs = []
    for ty, v in ins["outs"]:
        s, extra, k = sym[v]
        w = 4 if ty in ("GR32", "FP32", "AR32", "GRH32") else 8
        outs.append((s, w))
        if extra:
            outs.append((extra, w))
    for d in ins["defs"]:
        if d in IMPL:
            outs.append((IMPL[d], 4 if d[-1] == "L" or d == "FPC" else 8))
    for i, (o, w) in enumerate(outs):
        nm = op if i == 0 else f"{op}_{i}"
        pcodeops.add(nm)
        body.append(f"local o{i}:{w} = {nm}({', '.join(args)});")
    if not outs:
        pcodeops.add(op)
        body.append(f"{op}({', '.join(args)});")
    if "CC" in ins["defs"]:
        pcodeops.add(op + "_cc")
        body.append(f"local cc:1 = {op}_cc({', '.join(args)});")
    body += [f"{o} = o{i};" for i, (o, w) in enumerate(outs)]
    if "CC" in ins["defs"]:
        body.append("ccFrom(cc);")
    return " ".join(body)


def branch_mode(ins, mn, sym, t):
    """BRANCH AND SET MODE / BRANCH AND SAVE AND SET MODE in the 64-bit addressing mode: bit 63
    of R2 selects the mode and is not part of the address."""
    r1, r2 = sym["R1"][0], sym["R2"][0]
    z1, z2 = r1.replace("_yr", "_y") , r2.replace("_yr", "_y")
    z1 = fld(t, int(r1.split("_yr")[1]), int(r1.split("_yr")[1]) + 3)
    z2 = fld(t, int(r2.split("_yr")[1]), int(r2.split("_yr")[1]) + 3)
    base = [p for p in operands(ins)[2] if "=" in p]
    head = " & ".join(base)
    out = []
    if mn == "bsm":
        set1 = f"{r1} = {r1} | 1;"
        out.append((f"bsm 0,{r2}", f"{head} & {z1}=0 & {r2}", f"local tg:8 = {r2} & ~1; goto [tg];"))
        out.append((f"bsm {r1},{r2}", f"{head} & {r1} & {r2}", f"local tg:8 = {r2} & ~1; {set1} goto [tg];"))
        out.append((f"bsm {r1},0", f"{head} & {r1} & {z2}=0", set1))
        out.append(("bsm 0,0", f"{head} & {z1}=0 & {z2}=0", ""))
    else:
        out.append((f"bassm {r1},{r2}", f"{head} & {r1} & {r2}", f"local tg:8 = {r2} & ~1; {r1} = inst_next | 1; call [tg];"))
        out.append((f"bassm {r1},0", f"{head} & {r1} & {z2}=0", f"{r1} = inst_next | 1;"))
    return out

CONDSFX = {1: "o", 2: "h", 3: "nle", 4: "l", 5: "nhe", 6: "lh", 7: "ne", 8: "e", 9: "nlh", 10: "he",
           11: "nl", 12: "le", 13: "nh", 14: "no"}
TRAPSFX = {2: "h", 4: "l", 6: "lh", 8: "e", 10: "he", 12: "le"}


def cc_mask(m):
    terms = [f for bit, f in ((8, "CC0"), (4, "CC1"), (2, "CC2"), (1, "CC3")) if m & bit]
    return "1" if m == 15 else "0" if not terms else " || ".join(terms)


def trap_mask(m, x, y, signed):
    lt, gt = ("s<", "s>") if signed else ("<", ">")
    terms = [e for bit, e in ((8, f"{x} == {y}"), (4, f"{x} {lt} {y}"), (2, f"{x} {gt} {y}")) if m & bit]
    return " || ".join(f"({e})" for e in terms) if terms else "0"


def masked(ins, sym, t):
    """One constructor per mask of a condition-mask record, with exact p-code."""
    name = ins["name"]
    mv = [v for ty, v in ins["ins"] if ty == "imm32zx4" and v.startswith("M")][0]
    mf = sym[mv][0]
    base = [p for p in operands(ins)[2] if p != mf]
    mem = [sym[k][0] for k in sym if isinstance(k, tuple)]
    mref = "$" + mv

    def S(v):
        return sym[v][0]
    out = []
    for m in MASKED[name]:
        names = sorted(ins["ext"].get(str(m), []))
        base_mn = mnemonic(ins["asm"])
        want = (TRAPSFX if "T" in name[1:5] and name.startswith("C") else CONDSFX).get(m)
        mn = next((x for x in names if x == base_mn + (want or "")), names[0] if names else None)
        s = ins["asm"].replace("{\t| }", " ").replace("{, |,}", ",")
        if mn:
            s = mn + re.sub(r"^\S+", "", s).replace("," + mref, "").replace(mref + ",", "")
        s = s.replace(mref, str(m))
        for k, x in sym.items():
            if isinstance(k, tuple):
                for pre in ("XBD", "BDL", "BDR", "RBD", "BD"):
                    s = s.replace("$" + pre + k[0][-1], x[0])
        s = re.sub(r"\$(\w+)", lambda q: sym[q.group(1)][0] if q.group(1) in sym else q.group(1), s)
        c = cc_mask(m)
        fam = re.sub(r"Asm$", "", name)
        if fam == "BIC":
            b = ""
        elif fam in ("LOC", "LOCG", "LOCFH"):
            w = 8 if fam == "LOCG" else 4
            b = f"if (!({c})) goto inst_next; {S('R1')} = *:{w} {mem[0]};"
        elif fam in ("STOC", "STOCG", "STOCFH"):
            w = 8 if fam == "STOCG" else 4
            b = f"if (!({c})) goto inst_next; *:{w} {mem[0]} = {S('R1')};"
        elif fam in ("LOCR", "LOCGR", "LOCFHR"):
            b = f"if (!({c})) goto inst_next; {S('R1')} = {S('R2')};"
        elif fam in ("LOCHI", "LOCGHI", "LOCHHI"):
            w = 8 if fam == "LOCGHI" else 4
            b = f"if (!({c})) goto inst_next; local v:{w} = {S('I2')}; {S('R1')} = v;"
        elif fam in ("SELR", "SELGR", "SELFHR"):
            b = f"local res:{8 if fam == 'SELGR' else 4} = {S('R3')}; if (!({c})) goto <done>; res = {S('R2')}; <done> {S('R1')} = res;"
        else:
            sg = fam in ("CIT", "CGIT", "CRT", "CGRT")
            w = 8 if fam in ("CGIT", "CLGIT", "CGRT", "CLGRT", "CLGT") else 4
            if fam in ("CLT", "CLGT"):
                y = f"*:{w} {mem[0]}"
            elif fam.endswith("RT"):
                y = S("R2")
            else:
                y = S("I2")
            b = f"local x:{w} = {S('R1')}; local y:{w} = {y}; if (!({trap_mask(m, 'x', 'y', sg)})) goto inst_next; trap();"
        b = re.sub(r"if \(!\(1\)\) goto inst_next; ", "", b)
        b = re.sub(r"if \(!\(1\)\) goto <done>; ", "", b)
        b = re.sub(r"if \(!\(0\)\) goto <done>; res = [^;]*; ", "", b)
        if "goto <done>" not in b:
            b = b.replace("<done> ", "")
        if "if (!(0)) goto inst_next;" in b:
            b = ""
        out.append((s, " & ".join(base + [f"{mf}={m}"]), b))
    return out


