//! (unlace `com`) COM class and interface ids, and the interfaces they name.
//!
//! On a PE image the pass:
//! - names every 16-byte value in a data or code section that equals a known class id
//!   or interface id (`CLSID_ShellLink`, `IID_IShellLinkW`, ...) and types it
//!   `GUID`;
//! - builds, for each interface id it found, the interface struct (`IShellLinkW`,
//!   whose only member is `IShellLinkWVtbl *lpVtbl`) and its table of typed
//!   method pointers, the base interfaces' methods first, and hands the engine
//!   the map from the id's address to the struct (`ComInterfaces`), which types
//!   the out-parameter of `CoCreateInstance`, `QueryInterface` and the other
//!   requests by the id they pass (`unlace_decomp::comtyping`);
//! - declares the prototypes of the imported `ole32` requests, so the
//!   out-parameter of each call is an argument even where the call site alone
//!   would not show it.
//!
//! With `comcfg` naming a file in the format of IDA's `clsid.cfg`
//! (`guid {00000000-0000-0000-C000-000000000046} IUnknown`), the ids it holds
//! that the built-in table lacks are named too ([`parse_clsid_cfg`]).
//!
//! The tables are generated by `scripts/gen_com_tables.py` from the Win32
//! bindings of the `windows` crate (microsoft/windows-rs, MIT OR Apache-2.0):
//! `interfaces.txt` holds each interface's base and the methods it adds, one
//! letter per return and parameter type (`?` marks a method with a by-value
//! aggregate, whose slot stays an untyped code pointer), `guids.txt` the
//! interface and class ids. The pass runs at the commit point
//! (`crate::passes::run_com`), only when the option is on, so a run with it
//! off builds no type.

use crate::pass::{AnalysisCtx, AnalysisOutput, AnalysisPass, Phase, TypedDataFact};
use object::{Object, ObjectSection, SectionKind};
use std::cell::RefCell;
use std::collections::BTreeMap;
use std::rc::Rc;
use std::sync::OnceLock;
use unlace_decomp::dtype::{Datatype, TypeFactory, TypeField, type_metatype};
use unlace_decomp::fspec::PrototypePieces;

/// The option and pass id.
pub const ID: &str = "com";

const MAX_DEPTH: usize = 16;

/// The COM pass.
pub struct ComPass;

/// One interface of the table: its base and the methods it adds, each with
/// its type letters (return first).
pub struct Interface {
    pub base: Option<&'static str>,
    pub methods: Vec<(&'static str, &'static str)>,
}

/// Interface name to its entry.
pub fn interfaces() -> &'static BTreeMap<&'static str, Interface> {
    static TABLE: OnceLock<BTreeMap<&'static str, Interface>> = OnceLock::new();
    TABLE.get_or_init(|| parse_interfaces(include_str!("interfaces.txt")))
}

fn parse_interfaces(text: &'static str) -> BTreeMap<&'static str, Interface> {
    let mut table = BTreeMap::new();
    let mut current: Option<&'static str> = None;
    for line in text.lines().filter(|l| !l.starts_with('#')) {
        if let Some(head) = line.strip_prefix("= ") {
            let mut words = head.split(' ');
            let Some(name) = words.next() else { continue };
            let base = words.next().filter(|b| *b != "-");
            table.insert(
                name,
                Interface {
                    base,
                    methods: Vec::new(),
                },
            );
            current = Some(name);
        } else if let (Some(name), Some((method, kinds))) = (current, line.split_once(' '))
            && let Some(entry) = table.get_mut(name) {
                entry.methods.push((method, kinds));
            }
    }
    table
}

/// GUID bytes (in memory order) to the name of the id.
pub fn guid_names() -> &'static BTreeMap<[u8; 16], &'static str> {
    static DB: OnceLock<BTreeMap<[u8; 16], &'static str>> = OnceLock::new();
    DB.get_or_init(|| {
        include_str!("guids.txt")
            .lines()
            .filter(|l| !l.starts_with('#'))
            .filter_map(|l| {
                let (hex, name) = l.split_once(' ')?;
                let mut raw = [0u8; 16];
                for (i, b) in raw.iter_mut().enumerate() {
                    *b = u8::from_str_radix(hex.get(2 * i..2 * i + 2)?, 16).ok()?;
                }
                Some((raw, name))
            })
            .filter(|(raw, _)| raw.iter().any(|&b| b != 0))
            .collect()
    })
}

/// The methods of `name` in table order, its bases' first.
pub fn methods_of(name: &str) -> Option<Vec<(&'static str, &'static str)>> {
    let table = interfaces();
    let mut chain = Vec::new();
    let mut at = table.get_key_value(name)?;
    loop {
        chain.push(at.1);
        if chain.len() > MAX_DEPTH {
            return None;
        }
        match at.1.base {
            Some(base) => at = table.get_key_value(base)?,
            None => break,
        }
    }
    Some(
        chain
            .iter()
            .rev()
            .flat_map(|i| i.methods.iter().copied())
            .collect(),
    )
}

/// The imported requests the pass declares: name and type letters (return
