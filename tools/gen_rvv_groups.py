#!/usr/bin/env python3
"""Register groups for the RISC-V vector spec, chosen from vtype tracked as SLEIGH context.

riscv.rvv.sinc lifts every vector instruction to a user operation over its registers. An
operand is a group of registers whose size depends on vtype: LMUL for most operands, 2*LMUL for
widening results and narrowing sources, EEW/SEW*LMUL for load and store data and indices, nf
groups for segments. This script

- adds context fields vlmulc, vsewc and vknown to riscv.reg.sinc; vsetvli and vsetivli set them
  from their immediate for the instructions that follow (globalset at inst_next), and vsetvl
  clears vknown;
- generates riscv.rvvgroups.sinc: token fields, overlapping registers for every run of 2..8
  consecutive vector registers, and fixed-size operand subtables (a SLEIGH table exports one
  size) that also check the alignment and that the group fits;
- after each constructor of riscv.rvv.sinc adds one constructor per distinct group shape, under
  a vknown=1 pattern over the vtypes that give it; a segment access without a known vtype still
  writes its nf registers. The old destination becomes an input of every user operation writing
  a vector register (tail- and mask-undisturbed elements and vl = 0 keep it), and vset* lift
  writing vl and vtype.

It is idempotent: the constructors it added are dropped and regenerated.

    python3 tools/gen_rvv_groups.py specs/Ghidra/Processors/RISCV/data/languages
"""
import re
import sys
from pathlib import Path

FAMILIES = {"D": ("v0711", 7), "S2": ("v2024", 20), "S1": ("v1519", 15)}
OPERAND_FAMILY = {"vd": "D", "vs3": "D", "vs2": "S2", "vs1": "S1"}
LMULS = {0: 0, 1: 1, 2: 2, 3: 3, 5: -3, 6: -2, 7: -1}
CONTEXT_FIELDS = """  vknown=(7,7)   # 1 when the fields below hold the vtype the last vsetvli/vsetivli set
  gk=(8,9)       # log2 of the registers in an LMUL group (0 for LMUL <= 1)
  wk=(10,11)     # the same for 2*LMUL (widening results, narrowing sources)
  e8k=(12,13)    # the same for EEW/SEW*LMUL at EEW 8 (load/store data, indices)
  e16k=(14,15)
  e32k=(16,17)
  e64k=(18,19)
"""
FIELD_OF = {"g": "gk", "w": "wk", "e8": "e8k", "e16": "e16k", "e32": "e32k", "e64": "e64k"}
BEGIN, END = "# BEGIN generated by tools/gen_rvv_groups.py", "# END generated by tools/gen_rvv_groups.py"


def group_sizes(fam):
    """Segments make groups of any size at vd; sources are LMUL-sized."""
    return range(2, 9) if fam == "D" else (2, 4, 8)


def gname(b, k):
    return "v%dm%d" % (b, k) if k in (2, 4, 8) and b % k == 0 else "v%d_%d" % (b, b + k - 1)


def emul(kind, sew, l):
    """log2 EMUL of an operand class at SEW = 8 << sew and log2 LMUL l."""
    if kind == "g":
        return l
    if kind == "w":
        return l + 1
    if kind[0] == "e":
        return {8: 0, 16: 1, 32: 2, 64: 3}[int(kind[1:])] - sew + l
    if kind[0] == "f":
        return l - {2: 1, 4: 2, 8: 3}[int(kind[1:])]
    raise ValueError(kind)


def classify(mn):
    """{operand: (nf, kind)} for the vector operands that are register groups."""
    m = re.match(r"^vl(?:seg(\d))?e(\d+)(?:ff)?\.v$", mn) or re.match(r"^vs(?:seg(\d))?e(\d+)\.v$", mn) \
        or re.match(r"^v[ls]s(?:seg(\d))?e(\d+)\.v$", mn)
    if m:
        nf = int(m.group(1) or 1)
        return {"vd": (nf, "e" + m.group(2)), "vs3": (nf, "e" + m.group(2))}
    m = re.match(r"^v[ls][uo]x(?:seg(\d))?ei(\d+)\.v$", mn)
    if m:
        nf = int(m.group(1) or 1)
        return {"vd": (nf, "g"), "vs3": (nf, "g"), "vs2": (1, "e" + m.group(2))}
    if re.match(r"^v[ls]m\.v$|^vm\w+\.mm$|^vm(sbf|sif|sof)\.m$|^vcpop\.m$|^vfirst\.m$|^vf?mv\.([xf]\.s|s\.[xf])$", mn):
        return {}
    if re.match(r"^vf?w?red\w*\.vs$", mn):
        return {"vs2": (1, "g")}
    if mn == "viota.m":
        return {"vd": (1, "g")}
    if mn == "vcompress.vm":
        return {"vd": (1, "g"), "vs2": (1, "g")}
    if re.match(r"^vms(eq|ne|ltu?|leu?|gtu?|geu?)\.|^vmf(eq|ne|lt|le|gt|ge)\.|^vm(adc|sbc)\.", mn):
        return {"vs2": (1, "g"), "vs1": (1, "g")}
    if re.match(r"^vf?w", mn):
        return {"vd": (1, "w"), "vs2": (1, "w" if re.search(r"\.w[vxf]$", mn) else "g"), "vs1": (1, "g")}
    if re.match(r"^vn(srl|sra|clipu?)\.w|^vfncvt", mn):
        return {"vd": (1, "g"), "vs2": (1, "w"), "vs1": (1, "g")}
    m = re.match(r"^v[sz]ext\.vf(\d)$", mn)
    if m:
        return {"vd": (1, "g"), "vs2": (1, "f" + m.group(1))}
    if mn == "vrgatherei16.vv":
        return {"vd": (1, "g"), "vs2": (1, "g"), "vs1": (1, "e16")}
    if re.match(r"^v(aes\w+|sm4r)\.vs$", mn):
        return {"vd": (1, "g")}
    return {"vd": (1, "g"), "vs2": (1, "g"), "vs1": (1, "g")}


def sizes(cls, sew, l):
    """{operand: (registers, alignment)} at one vtype, or None when the encoding is reserved there."""
    out = {}
    for op, (nf, kind) in cls.items():
        e = emul(kind, sew, l)
        if e > 3:
            return None
        a = 1 << max(e, 0)
        if nf * a > 8:
            return None
        out[op] = (nf * a, a)
    return out


def fixed_name(op, k, a):
    return "%s_k%da%d" % (op, k, a)


def fixed_table(name, fam, k, a):
    """A group of k registers at an a-aligned base. A group as large as its alignment always fits;
    a segment group (k > a) whose base leaves no room for k registers is reserved and reaches past
    v31 into unused register space, so it still decodes (a range check in the pattern would split
    the decision tree and make the .sla several times larger)."""
    base, _ = FAMILIES[fam]
    cons = [base, "vg%d_%s" % (k, fam)]
    if a > 1:
        cons.append("vlo%d_%s=0" % (a, fam))
    return "%s: %s is %s { export vg%d_%s; }" % (name, base, " & ".join(cons), k, fam)


def field_code(kind, sew, l):
    """(context field, code) giving an operand class's group at a vtype: code = log2 EMUL, 0 when
    EMUL <= 1 or the vtype makes the encoding reserved (EMUL > 8)."""
    if kind[0] == "f":
        return "gk", l if 0 < l <= 3 else 0
    e = emul(kind, sew, l)
    return FIELD_OF[kind], e if 0 < e <= 3 else 0


def context_terms(combos):
    """A pattern over vsewc/vlmulc matching exactly the (sew, raw lmul) combos."""
    by_l = {}
    for sew, raw in combos:
        by_l.setdefault(raw, set()).add(sew)
    terms = []
    for raw in sorted(by_l):
        if by_l[raw] == {0, 1, 2, 3}:
            terms.append("vlmulc=%d" % raw)
        else:
            terms += ["(vsewc=%d & vlmulc=%d)" % (s, raw) for s in sorted(by_l[raw])]
    return terms[0] if len(terms) == 1 else "(" + " | ".join(terms) + ")"


def vtctx_table():
    """The vtype context a vsetvli/vsetivli immediate sets for the instructions after it."""
    out = []
    for raw in range(8):
        for sew in range(8):
            if raw == 4 or sew > 3:
                acts = ["vknown = 0", "globalset(inst_next, vknown)"]
            else:
                l = LMULS[raw]
                codes = {"gk": max(0, l), "wk": l + 1 if 0 < l + 1 <= 3 else 0}
                for eew in (8, 16, 32, 64):
                    e = emul("e%d" % eew, sew, l)
                    codes["e%dk" % eew] = e if 0 < e <= 3 else 0
                acts = ["vknown = 1"] + ["%s = %d" % kv for kv in codes.items()]
                acts += ["globalset(inst_next, %s)" % f for f in ["vknown"] + list(codes)]
            out.append("vtctx: is op2022=%d & op2325=%d [ %s; ] { }" % (raw, sew, "; ".join(acts)))
    return out + [""]


def groups_sinc(tables):
    lines = [BEGIN, "# Operand subtables exporting a group of vector registers.", ""]
    for fam in FAMILIES:
        for k in group_sizes(fam):
            lst = [gname(b, k) for b in range(32)]
            lines.append("attach variables [ vg%d_%s ] [ %s ];" % (k, fam, " ".join(lst)))
    lines.append("")
    for n in (2, 4, 8):
        lines.append("vdm%d:  v0711 is v0711 & vg%d_D & vlo%d_D=0 { export vg%d_D; }" % (n, n, n, n))
        lines.append("vs2m%d: v2024 is v2024 & vg%d_S2 & vlo%d_S2=0 { export vg%d_S2; }" % (n, n, n, n))
    lines.append("")
    lines += vtctx_table()
    lines.append("vl_csr: vlr is epsilon [ vlr = $(CSR_REG_START) + 0xc20; ] { export *[csreg]:$(XLEN) vlr; }")
    lines.append("vtype_csr: vtr is epsilon [ vtr = $(CSR_REG_START) + 0xc21; ] { export *[csreg]:$(XLEN) vtr; }")
    lines.append("")
    for name in sorted(tables):
        lines.append(fixed_table(name, *tables[name]))
    lines.append(END)
    return "\n".join(lines) + "\n"


def register_block():
    out = [BEGIN, "# every run of 2..8 consecutive vector registers (VLEN = 32 bytes per register); a run"
           "\n# past v31 (a reserved segment encoding) reaches into unused space after it"]
    for k in range(2, 9):
        for b in range(0, 32):
            out.append("define register offset=0x%x size=%d [ %s ];" % (0x4000 + 32 * b, 32 * k, gname(b, k)))
    out.append(END)
    return "\n".join(out) + "\n"


def token_block():
    out = ["  " + BEGIN]
    for fam, (base, lo) in FAMILIES.items():
        for k in group_sizes(fam):
            out.append("  vg%d_%s=(%d,%d)" % (k, fam, lo, lo + 4))
        for a, w in ((2, 0), (4, 1), (8, 2)):
            out.append("  vlo%d_%s=(%d,%d)" % (a, fam, lo, lo + w))
    out.append("  " + END)
    return "\n".join(out) + "\n"


def replace_block(text, block, anchor, indent=""):
    pat = re.compile(r"^%s%s\n.*?^%s%s\n" % (re.escape(indent), re.escape(BEGIN), re.escape(indent), re.escape(END)), re.M | re.S)
    if pat.search(text):
        return pat.sub(lambda m: block, text)
    if anchor not in text:
        raise SystemExit("anchor not found: %r" % anchor)
    return text.replace(anchor, anchor + block, 1)


VTYPE = """	local vt:$(XLEN) = %s;
	local lm:$(XLEN) = vt & 7;
	local sw:$(XLEN) = (vt >> 3) & 7;
	local ill:1 = ((vt >> 8) != 0) || (lm == 4) || (sw > 3);
	vtype_csr = (zext(ill) << ($(XLEN) * 8 - 1)) | (vt * zext(!ill));
"""
CTX_SET = ""
CTX_CLEAR = "[ vknown = 0; globalset(inst_next, vknown); ]"


def vset_constructors():
    return """:vsetivli rd,vzimm5,vtypei10 is rd & vzimm5 & vtypei10 & op3131=0x1 & op3030=0x1 & op1214=0x7 & op0006=0x57 & vl_csr & vtype_csr & vtctx %s
{
	local n:$(XLEN) = vsetivli(vzimm5, vtypei10);
	rd = n;
	vl_csr = n;
%s}

:vsetvli rd,rs1,vtypei11 is rd & rs1 & vtypei11 & op3131=0x0 & op1214=0x7 & op0006=0x57 & vl_csr & vtype_csr & vtctx %s
{
	local n:$(XLEN) = vsetvli(rs1, vtypei11);
	rd = n;
	vl_csr = n;
%s}

:vsetvli rd,rs1,vtypei11 is rd & r0711=0 & rs1 & r1519=0 & vtypei11 & op3131=0x0 & op1214=0x7 & op0006=0x57 & vl_csr & vtype_csr & vtctx %s
{
%s}

:vsetvl rd,rs1,rs2 is rd & rs1 & rs2 & op3131=0x1 & op2530=0x0 & op1214=0x7 & op0006=0x57 & vl_csr & vtype_csr %s
{
	local n:$(XLEN) = vsetvl(rs1, rs2);
	rd = n;
	vl_csr = n;
%s}
""" % (CTX_SET, VTYPE % "vtypei10", CTX_SET, VTYPE % "vtypei11", CTX_SET, VTYPE % "vtypei11", CTX_CLEAR, VTYPE % "rs2")


CONS = re.compile(r"^:(\S+) (.*?) is (.*?)( \[[^\]]*\])?\n\{\n((?:\t[^\n]*\n)*)\}\n", re.M)
OPERAND = re.compile(r"\b(vd|vs1|vs2|vs3)\b")
GROUPED = re.compile(r"\b(vd|vs1|vs2|vs3)_k\d+a\d+\b")
WRITE = re.compile(r"^\t(\w+) = (\w+)\((.*)\);$")


def old_vd_input(body):
    lines = body.rstrip("\n").split("\n")
    w = WRITE.match(lines[0]) if len(lines) == 1 else None
    if w and re.match(r"^v(d|s3)\b", w.group(1)) and w.group(2) != w.group(1):
        args = [a.strip() for a in w.group(3).split(",") if a.strip()]
        if not args or args[0] != w.group(1):
            args.insert(0, w.group(1))
        return "\t%s = %s(%s);\n" % (w.group(1), w.group(2), ", ".join(args))
    return body


def rewrite(rvv):
    tables = {}
    out = []
    pos = 0
    vset_done = False
    for m in CONS.finditer(rvv):
        mn, disp, pat, act, body = m.groups()
        out.append(rvv[pos:m.start()])
        pos = m.end()
        generated = pat.startswith("vknown=1 & ")
        disp, pat, body = (GROUPED.sub(lambda x: x.group(1), t) for t in (disp, pat, body))
        if generated or (mn.startswith("vset") and vset_done):
            if rvv[pos:pos + 1] == "\n":
                pos += 1
            continue
        if mn.startswith("vset"):
            out.append(vset_constructors())
            vset_done = True
            continue
        if re.match(r"^v(l\dre\d+|s\dr|mv\dr)\.v$", mn):
            out.append(m.group(0))
            continue
        cls = {op: v for op, v in classify(mn).items() if re.search(r"\b%s\b" % op, pat)}
        body = old_vd_input(body)

        def emit(sz, ctx):
            ren = {}
            for op in ("vd", "vs1", "vs2", "vs3"):
                if op in sz and sz[op][0] > 1:
                    k, a = sz[op]
                    ren[op] = fixed_name(op, k, a)
                    tables[ren[op]] = (OPERAND_FAMILY[op], k, a)
                else:
                    ren[op] = op
            sub = lambda s: OPERAND.sub(lambda x: ren[x.group(1)], s)
            p = sub(pat) if ctx is None else "vknown=1 & %s & %s" % (ctx, sub(pat))
            return ":%s %s is %s%s\n{\n%s}\n" % (mn, sub(disp), p, act or "", sub(body))
        base = {op: (nf, 1) for op, (nf, kind) in cls.items() if nf > 1}
        out.append(emit(base, None))
        default = {op: base.get(op, (1, 1)) for op in cls}
        variants = {}
        for sew in range(4):
            for raw, l in LMULS.items():
                sz = sizes(cls, sew, l)
                if sz is None or sz == default:
                    continue
                cond = {}
                for op, (nf, kind) in cls.items():
                    f, c = field_code(kind, sew, l)
                    cond.setdefault(f, c)
                key = " & ".join("%s=%d" % kv for kv in sorted(cond.items()))
                if variants.setdefault(key, sz) != sz:
                    raise SystemExit("%s: %s gives two shapes" % (mn, key))
        for key, sz in sorted(variants.items()):
            out.append("\n" + emit(sz, key))
    out.append(rvv[pos:])
    text = "".join(out).rstrip("\n") + "\n"
    inc = '@include "riscv.rvvgroups.sinc"\n'
    if inc not in text:
        first = text.index("\ndefine pcodeop")
        text = text[:first + 1] + inc + "\n" + text[first + 1:]
    return text, tables


def main():
    d = Path(sys.argv[1])
    rvv = (d / "riscv.rvv.sinc").read_text()
    rvv, tables = rewrite(rvv)
    (d / "riscv.rvv.sinc").write_text(rvv)
    (d / "riscv.rvvgroups.sinc").write_text(groups_sinc(tables))
    reg = (d / "riscv.reg.sinc").read_text()
    reg = re.sub(r"^  vg[248]_(0711|2024)=\(\d+,\d+\)\n|^  vlo[248]_(0711|2024)=\(\d+,\d+\)\n", "", reg, flags=re.M)
    reg = re.sub(r"^# register groups of 2, 4 and 8 .*\n(?:define register offset=0x4000 size=\d+ +\[[^\]]*\];\n)+", "", reg, flags=re.M)
    reg = replace_block(reg, token_block(), "  v2024=(20,24)\n", "  ")
    reg = replace_block(reg, register_block(), "\t\t\t\t\t     v24 v25 v26 v27 v28 v29 v30 v31 ];\n")
    reg = re.sub(r"^  (vlmulc|vsewc|vknown|gk|wk|e8k|e16k|e32k|e64k)=\(.*\n", "", reg, flags=re.M)
    if True:
        reg = re.sub(r"^(  Zcmp=\(6,6\).*\n)", lambda m: m.group(1) + CONTEXT_FIELDS, reg, count=1, flags=re.M)
    (d / "riscv.reg.sinc").write_text(reg)
    tab = (d / "riscv.table.sinc").read_text()
    tab = re.sub(r"^attach variables \[ vg[248]_0711 vg[248]_2024 \] \[[^\]]*\];\n", "", tab, flags=re.M)
    tab = re.sub(r"^vdm[248]:.*\n|^vs2m[248]:.*\n", "", tab, flags=re.M)
    (d / "riscv.table.sinc").write_text(tab)
    print("%d group tables, %d constructors" % (len(tables), rvv.count("\n:")))


if __name__ == "__main__":
    main()
