#!/usr/bin/env python3
"""Write ppc_isa31.sinc: the Power ISA 3.1 (POWER10) instructions, including the 8-byte
prefixed forms, MMA and the new VSX/VMX/fixed-point instructions, from isa31_insts.json.

    python3 gen_isa31.py --extract PPC.json   # refresh isa31_insts.json from an llvm-tblgen dump
    python3 gen_isa31.py data/languages        # write data/languages/ppc_isa31.sinc

isa31_insts.json lists every LLVM PowerPC instruction record (TableGen, release/22.x) whose
predicates are IsISA3_1, PrefixInstrs, MMA, HasP10Vector or PairedVectorMemops, plus the four
ISA 3.0 records in EXTRA that the base spec lacks: mnemonic,
operands and the encoding bits (bit 0 is the most significant, as in the ISA). It was
extracted from
    llvm-tblgen -dump-json -I llvm/include -I llvm/lib/Target/PowerPC PPC.td
The instructions use their own 32-bit tokens: p31w for a 4-byte instruction or the suffix
word of a prefixed one, p31p for the prefix word. Semantics are written per mnemonic family
below; anything else is a user operation named after the mnemonic.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NOTE = "# Generated by ../../gen_isa31.py; edit the generator, not this file.\n"
WANT = {"IsISA3_1", "MMA", "PrefixInstrs", "HasP10Vector", "PairedVectorMemops"}
BAD = {"IsISAFuture", "HasSPE", "IsE500", "IsBookE", "IsPPC4xx"}
# Power ISA 3.0 (POWER9) instructions the base PowerPC spec lacks
EXTRA = {"ADDEX", "CP_PASTE_rec", "SCV", "VMSUMUDM"}


def extract(dump):
    d = json.load(open(dump))

    def ops(dag):
        res = []
        for t, v in dag["args"]:
            if isinstance(t, dict) and t.get("kind") == "def":
                res.append([t["def"], v])
            elif isinstance(t, dict) and t.get("kind") == "dag":
                res.append([t["operator"]["def"], [x[1] for x in t["args"]]])
        return res
    out = []
    for n in d["!instanceof"]["Instruction"]:
        r = d[n]
        if r.get("Namespace") != "PPC" or r.get("isCodeGenOnly") or r.get("isPseudo") or r.get("isAsmParserOnly"):
            continue
        preds = {p["def"] for p in r.get("Predicates", [])}
        if not (preds & WANT or n in EXTRA) or preds & BAD:
            continue
        bits = [0 if b is None else b if isinstance(b, int) else [b["var"], b.get("index", 0)] for b in r["Inst"]]
        out.append({"name": n, "asm": r["AsmString"], "outs": ops(r["OutOperandList"]), "ins": ops(r["InOperandList"]),
                    "bits": bits, "size": len(r["Inst"]), "defs": [x["def"] for x in r.get("Defs", [])],
                    "constraints": r.get("Constraints", ""), "preds": sorted(preds)})
    out.sort(key=lambda x: x["name"])
    json.dump(out, open(os.path.join(HERE, "isa31_insts.json"), "w"), indent=0)


if sys.argv[1] == "--extract":
    extract(sys.argv[2])
    sys.exit(0)
OUT = sys.argv[1]
INSTS = json.load(open(os.path.join(HERE, "isa31_insts.json")))
