#!/usr/bin/env python3
"""Write the MSP430 family processor specs (TI_MSP430_<family>.pspec) from TI's MSP430 GCC support files.

Usage: gen_msp430_pspec.py <msp430-gcc-support-files-<version>.zip> [<out-dir>]

The support files are BSD-3-Clause (the header of every file). Each device's <device>_symbols.ld
lists its peripheral registers as PROVIDE(<name> = <address>). For each family below, every address a
device of the family names is labelled with a name every such device gives it (TI keeps legacy aliases
beside current names, so the shared name is the current one; the legacy first-timer names TACTL, TBR, ...
match TA0CTL, TB0R, ..., and the spelling most of the devices use is kept); an address the devices of a family
name differently (LCD_B against LCD_C, Timer_A against Timer_B) is left unlabelled. Byte halves of word
registers (<name>_L, <name>_H) are not labelled, except that a word port's halves take the byte port names
code uses (PAOUT is labelled P1OUT and P2OUT).
"""
import collections
import re
import sys
import zipfile
from pathlib import Path

# family: (description, device-name regex, 20-bit MSP430X core, peripheral space end)
FAMILIES = {
    "f1xx": ("MSP430F1xx", r"msp430f1\d", False, 0x1FF),
    "f2xx": ("MSP430F2xx", r"msp430f2\d", False, 0x1FF),
    "g2xx": ("MSP430G2xx", r"msp430g2\d", False, 0x1FF),
    "f4xx": ("MSP430F4xx, FG4xx, FE4xx, CG4xx", r"msp430(f|fg|fe|cg)4\d", False, 0x1FF),
    "i2xx": ("MSP430i2xx", r"msp430i2\d", False, 0x1FF),
    "f5xx": ("MSP430F5xx, CC430F5xx, RF430F5xx, BT5190", r"(msp430f5|cc430f5|rf430f5|msp430bt5)\d", True, 0xFFF),
    "f6xx": ("MSP430F6xx, FG6xx, CC430F6xx", r"(msp430f6|msp430fg6|cc430f6)\d", True, 0xFFF),
    "fr2xx": ("MSP430FR2xx, FR4xx", r"msp430fr[24]\d", True, 0xFFF),
    "fr5xx": ("MSP430FR5xx", r"msp430fr5\d", True, 0xFFF),
    "fr6xx": ("MSP430FR6xx", r"msp430fr6\d", True, 0xFFF),
}
PROVIDE = re.compile(r"PROVIDE\((\w+)\s*=\s*(0x[0-9A-Fa-f]+)\)")
# Older headers name the first Timer_A/Timer_B without its instance (TACTL, TBR); the current name has it.
LEGACY_TIMER = re.compile(r"^T([AB])(?!\d)")
WORD_PORT = re.compile(r"^P([A-F])(IN|OUT|DIR|REN|DS|SEL\d?|SELC|IES|IE|IFG)$")


def device_names(text):
    names = collections.defaultdict(list)
    for m in PROVIDE.finditer(text):
        name, addr = m.group(1), int(m.group(2), 16)
        if name.endswith("_L") or name.endswith("_H"):
            continue
        names[addr].append(name)
    return names


def family_map(devices):
    """address -> name, for the names every device of the family that defines the address shares
    (the legacy first-timer names compared as the current ones); the spelling most devices use."""
    canon = lambda n: LEGACY_TIMER.sub(r"T\g<1>0", n)
    votes = collections.defaultdict(collections.Counter)
    spelled = collections.defaultdict(collections.Counter)
    common = {}
    for regs in devices.values():
        for addr, names in regs.items():
            votes[addr][canon(names[0])] += 1
            for n in names:
                spelled[(addr, canon(n))][n] += 1
            shared = {canon(n) for n in names}
            common[addr] = shared if addr not in common else common[addr] & shared
    out = {}
    for addr, shared in common.items():
        if not shared:
            continue
        name = max(sorted(shared), key=lambda n: votes[addr][n])
        out[addr] = max(sorted(spelled[(addr, name)]), key=lambda n: spelled[(addr, name)][n])
    # A word port names its halves after the byte ports code reads: PAIN is P1IN, PAIN + 1 is P2IN.
    for addr, name in list(out.items()):
        m = WORD_PORT.match(name)
        if m:
            low = 2 * (ord(m.group(1)) - ord("A")) + 1
            out[addr] = "P%d%s" % (low, m.group(2))
            out.setdefault(addr + 1, "P%d%s" % (low + 1, m.group(2)))
    return out, sum(1 for s in common.values() if not s)


def write_pspec(path, family, desc, version, devices, regs, x, end):
    lines = ['<?xml version="1.0" encoding="UTF-8"?>', "",
             "<!-- Generated by tools/gen_msp430_pspec.py from TI MSP430 GCC support files %s (BSD-3-Clause):" % version,
             "     the peripheral registers of the %s devices (%s). -->" % (desc, ", ".join(d.upper() for d in sorted(devices))),
             "<processor_spec>"]
    if x:
        lines += ['  <properties>',
                  '    <property key="assemblyRating:TI_MSP430X:LE:32:%s" value="PLATINUM"/>' % family,
                  '  </properties>']
    lines += ['  <programcounter register="PC"/>']
    if x:
        lines += ['  <context_data>',
                  '    <context_set space="RAM" first="0x0000" last="0xFFFF">',
                  '      <set name="ctx_isHi" val="1" description="1 instruction starts &gt; 64K"/>',
                  '    </context_set>',
                  '  </context_data>']
    lines += ['  <volatile outputop="ioWrite" inputop="ioRead">',
              '    <range space="RAM" first="0x0" last="0x%x"/>' % end,
              '  </volatile>',
              '  <default_symbols>']
    for addr in sorted(regs):
        lines.append('    <symbol name="%s" address="RAM:0x%04x" entry="false"/>' % (regs[addr], addr))
    lines += ['  </default_symbols>', '</processor_spec>', '']
    Path(path).write_text("\n".join(lines))


def main():
    pack = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / "specs/Ghidra/Processors/TI_MSP430/data/languages"
    with zipfile.ZipFile(pack) as z:
        version = re.search(r"support-files-(\d+(?:\.\d+)*)", pack.name)
        version = version.group(1) if version else "unknown"
        files = {Path(n).name[: -len("_symbols.ld")]: n for n in z.namelist() if n.endswith("_symbols.ld")}
        for family, (desc, pattern, x, end) in FAMILIES.items():
            devices = {d: device_names(z.read(n).decode("latin-1")) for d, n in sorted(files.items()) if re.match(pattern, d)}
            regs, dropped = family_map(devices)
            regs = {a: n for a, n in regs.items() if a <= end}
            write_pspec(out / ("TI_MSP430_%s.pspec" % family), family, desc, version, devices, regs, x, end)
            sys.stderr.write("%s: %d devices, %d names, %d addresses named differently\n" % (family, len(devices), len(regs), dropped))


if __name__ == "__main__":
    main()
