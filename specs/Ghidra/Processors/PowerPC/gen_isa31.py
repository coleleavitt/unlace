fields = {"w": {}, "p": {}}
attach, names_attach, subs, pcodeops = {}, {}, {}, set()

GPR = [f"r{i}" for i in range(32)]
VSA = [f"vs{i}" for i in range(32)]
VSB = [f"vs{i}" for i in range(32, 64)]
VN = [f"v{i}" for i in range(32)]
FPR = [f"f{i}" for i in range(32)]
CRF = [f"cr{i}" for i in range(8)]
ACC = [f"acc{i}" for i in range(8)]


def fld(t, lo, hi, signed=False, kind="x"):
    n = f"{t}_{kind}{'s' if signed else ''}{lo}_{hi}"
    fields[t][n] = f"{n}=({lo},{hi})" + (" signed" if signed else "")
    return n


def att(t, lo, hi, kind, regs, names=False):
    n = fld(t, lo, hi, kind=kind)
    (names_attach if names else attach).setdefault(tuple(regs), set()).add(n)
    return n


def locate(ins):
    """{var: {index: (token, lsb position)}} in each 32-bit word's own bit numbering."""
    size = ins["size"]
    out = {}
    for i, b in enumerate(ins["bits"]):
        if not isinstance(b, list):
            continue
        if size == 32:
            t, pos = "w", 31 - i
        elif i < 32:
            t, pos = "p", 31 - i
        else:
            t, pos = "w", 63 - i
        out.setdefault(b[0], {})[b[1]] = (t, pos)
    return out


def fixed_runs(ins):
    size = ins["size"]
    res = {"w": [], "p": []}
    for i, b in enumerate(ins["bits"]):
        if isinstance(b, int):
            if size == 32:
                res["w"].append((31 - i, b))
            elif i < 32:
                res["p"].append((31 - i, b))
            else:
                res["w"].append((63 - i, b))
    out = {"w": [], "p": []}
    for t, lst in res.items():
        lst.sort()
        run = []
        for pos, b in lst + [(None, None)]:
            if run and (pos is None or pos != run[-1][0] + 1):
                lo, hi = run[0][0], run[-1][0]
                val = sum(bb << (p - lo) for p, bb in run)
                out[t].append(f"{fld(t, lo, hi)}={val}")
                run = []
            if pos is not None:
                run.append((pos, b))
    return out


def contig(posmap):
    """(token, lo, hi) when the indices sit in one word, low index at the low bit, contiguous."""
    toks = {t for t, _ in posmap.values()}
    if len(toks) != 1:
        return None
    t = toks.pop()
    ps = [posmap[i][1] for i in sorted(posmap)]
    lo = ps[0]
    if ps != list(range(lo, lo + len(ps))):
        return None
    return t, lo, lo + len(ps) - 1


def subtable(name, text):
    subs.setdefault(name, text)
    return name


def operand(t_, v, pm):
    """(display, pattern pieces {tok: [..]}, symbol, kind)"""
    pat = {"w": [], "p": []}
    if t_ in ("gprc", "g8rc"):
        tk, lo, hi = contig(pm)
        f = att(tk, lo, hi, "r", GPR)
        pat[tk].append(f)
        return f, pat, f, "gpr"
    if t_ == "gprc_nor0":
        tk, lo, hi = contig(pm)
        f = att(tk, lo, hi, "r", GPR)
        z = fld(tk, lo, hi)
        s = subtable(f"RA0{tk}{lo}", f"RA0{tk}{lo}: {f} is {f} {{ export {f}; }}\nRA0{tk}{lo}: 0 is {z}=0 {{ export 0:$(REGISTER_SIZE); }}\n")
        pat[tk].append(s)
        return s, pat, s, "gpr"
    if t_ in ("f8rc", "f4rc", "fpairrc"):
        tk, lo, hi = contig(pm)
        f = att(tk, lo, hi, "f", FPR)
        pat[tk].append(f)
        return f, pat, f, "fpr"
    if t_ in ("vrrc", "vfrc"):
        tk, lo, hi = contig(pm)
        rn = att(tk, lo, hi, "vr", VSB)
        dn = att(tk, lo, hi, "vn", VN, names=True)
        s = subtable(f"VR{tk}{lo}", f"VR{tk}{lo}: {dn} is {dn} & {rn} {{ export {rn}; }}\n")
        pat[tk].append(s)
        return s, pat, s, "vr"
    if t_ == "vsrc":
        low = {i: pm[i] for i in range(5)}
        tk, lo, hi = contig(low)
        ht, hp = pm[5]
        a = att(tk, lo, hi, "vsa", VSA)
        b = att(tk, lo, hi, "vsb", VSB)
        x = fld(ht, hp, hp)
        s = f"VS{tk}{lo}{ht}{hp}"
        if ht == tk:
            subtable(s, f"{s}: {a} is {a} & {x}=0 {{ export {a}; }}\n{s}: {b} is {b} & {x}=1 {{ export {b}; }}\n")
        else:
            raise KeyError("split vsr")
        pat[tk].append(s)
        return s, pat, s, "vsr"
    if t_ in ("vsrprc", "vsrpevenrc"):
        low = {i: pm[i] for i in range(4)}
        tk, lo, hi = contig(low)
        ht, hp = pm[4]
        x = fld(ht, hp, hp)
        ea = att(tk, lo, hi, "vpa", [f"vs{2 * i}" for i in range(16)])
        eb = att(tk, lo, hi, "vpb", [f"vs{32 + 2 * i}" for i in range(16)])
        oa = att(tk, lo, hi, "vqa", [f"vs{2 * i + 1}" for i in range(16)])
        ob = att(tk, lo, hi, "vqb", [f"vs{33 + 2 * i}" for i in range(16)])
        s0, s1 = f"VP{tk}{lo}{hp}", f"VQ{tk}{lo}{hp}"
        subtable(s0, f"{s0}: {ea} is {ea} & {x}=0 {{ export {ea}; }}\n{s0}: {eb} is {eb} & {x}=1 {{ export {eb}; }}\n")
        subtable(s1, f"{s1}: {oa} is {oa} & {x}=0 {{ export {oa}; }}\n{s1}: {ob} is {ob} & {x}=1 {{ export {ob}; }}\n")
        pat[tk] += [s0, s1]
        return s0, pat, (s0, s1), "vsp"
    if t_ == "acc":
        tk, lo, hi = contig(pm)
        f = att(tk, lo, hi, "acc", ACC)
        pat[tk].append(f)
        return f, pat, f, "acc"
    if t_ == "crrc":
        tk, lo, hi = contig(pm)
        f = att(tk, lo, hi, "crf", CRF)
        pat[tk].append(f)
        return f, pat, f, "crf"
    if t_ == "crbitrc":
        tk, lo, hi = contig(pm)
        cf = att(tk, lo + 2, hi, "crf", CRF)
        bit = fld(tk, lo, lo + 1)
        whole = fld(tk, lo, hi)
        s = subtable(f"CRB{tk}{lo}", f"CRB{tk}{lo}: {whole} is {cf} & {bit} & {whole} {{ local b:1 = ({cf} >> (3 - {bit})) & 1; export b; }}\n")
        pat[tk].append(s)
        return s, pat, s, "crbit"
    if t_ == "immZero":
        tk, lo, hi = contig(pm)
        pat[tk].append(f"{fld(tk, lo, hi)}=0")
        return "0", pat, None, "zero"
    if t_.startswith(("u", "s", "i")) and "imm" in t_:
        signed = t_.startswith("s")
        c = contig(pm)
        if c:
            tk, lo, hi = c
            f = fld(tk, lo, hi, signed)
            pat[tk].append(f)
            return f, pat, f, "imm"
        return ("split", pm, signed), pat, None, "split"
    raise KeyError(t_)


def split_imm(name, pm, signed, pat, actions):
    """An immediate across the prefix and the suffix: a value assembled in a disassembly action."""
    parts = []
    idx = sorted(pm)
    run = [idx[0]]
    for i in idx[1:] + [None]:
        if i is not None and i == run[-1] + 1 and pm[i][0] == pm[run[0]][0] and pm[i][1] == pm[run[-1]][1] + 1:
            run.append(i)
            continue
        tk, lo = pm[run[0]]
        f = fld(tk, lo, lo + len(run) - 1)
        pat[tk].append(f)
        parts.append((f, run[0]))
        run = [i]
    total = len(pm)
    expr = " | ".join(f"({f} << {sh})" if sh else f for f, sh in parts)
    if signed:
        expr = f"((({expr}) ^ {1 << (total - 1)}) - {1 << (total - 1)})"
    sym = f"imm_{name.lower()}"
    actions.append(f"{sym} = {expr};")
    return sym


def mem_operand(t_, sub, pm_all, pat, actions):
    """(display, effective-address expression)"""
    if t_ in ("memri34", "memri34_pcrel"):
        d, ra = sub
        sym = split_imm("D", pm_all[d], True, pat, actions)
        if t_ == "memri34_pcrel":
            tk, lo, hi = contig(pm_all[ra])
            pat[tk].append(f"{fld(tk, lo, hi)}=0")
            return f"{sym}(0)", f"(inst_start + {sym})"
        disp, p2, s, k = operand("gprc_nor0", ra, pm_all[ra])
        for tk in "wp":
            pat[tk] += p2[tk]
        return f"{sym}({disp})", f"({s} + {sym})"
    if t_ == "memrr":
        ra, rb = sub
        d1, p1, s1, _ = operand("gprc_nor0", ra, pm_all[ra])
        d2, p2, s2, _ = operand("gprc", rb, pm_all[rb])
        for tk in "wp":
            pat[tk] += p1[tk] + p2[tk]
        return f"{d1},{d2}", f"({s1} + {s2})"
    if t_ == "memrix16":
        dq, ra = sub
        tk, lo, hi = contig(pm_all[dq])
        f = fld(tk, lo, hi, True)
        pat[tk].append(f)
        d1, p1, s1, _ = operand("gprc_nor0", ra, pm_all[ra])
        pat[tk] += p1[tk]
        actions.append(f"imm_dq = {f} << 4;")
        return f"imm_dq({d1})", f"({s1} + imm_dq)"
    raise KeyError(t_)


# ---------------------------------------------------------------- p-code helpers
class B:
    def __init__(s):
        s.lines, s.n = [], 0

    def t(s, size, expr):
        s.n += 1
        nm = f"t{s.n}"
        s.lines.append(f"local {nm}:{size} = {expr};")
        return nm

    def l(s, text):
        s.lines.append(text)

    def text(s):
        return " ".join(s.lines)


def lanes(b, v, e):
    return [b.t(e, f"{v}:{e}" if (16 - e * (i + 1)) == 0 else f"{v}({16 - e * (i + 1)})") for i in range(16 // e)]


def combine(b, parts, e):
    if e == 16:
        return parts[0]
    n = len(parts)
    return b.t(16, " | ".join(f"(zext({p}) << {8 * e * (n - 1 - i)})" if n - 1 - i else f"zext({p})" for i, p in enumerate(parts)))


def lanewise(b, e, srcs, fn):
    ls = [lanes(b, b.t(16, s), e) for s in srcs]
    return combine(b, [b.t(e, fn(*[l[i] for l in ls])) for i in range(16 // e)], e)


def bswap(b, x, e):
    bs = [b.t(1, f"{x}:1" if k == 0 else f"{x}({k})") for k in range(e)]
    return b.t(e, " | ".join(f"(zext({bs[k]}) << {8 * (e - 1 - k)})" if e - 1 - k else f"zext({bs[k]})" for k in range(e)))


LOADS = {"plbz": (1, "z"), "plhz": (2, "z"), "plha": (2, "s"), "plwz": (4, "z"), "plwa": (4, "s"), "pld": (8, "z")}
STORES = {"pstb": 1, "psth": 2, "pstw": 4, "pstd": 8}
SZ = {"b": 1, "h": 2, "w": 4, "d": 8, "q": 16}


def sem(mn, O, I, ea):
    """The p-code for mn, or None for a user operation. O: output symbols, I: the other inputs, in
    LLVM operand order; ea: the effective address of a memory operand."""
    b = B()
    if ea is not None:
        ea = b.t("$(REGISTER_SIZE)", ea)
    if mn in LOADS:
        n, ext = LOADS[mn]
        v = b.t(n, f"*:{n} {ea}")
        b.l(f"{O[0]} = {'sext' if ext == 's' else 'zext'}({v});" if n < 8 else f"{O[0]} = {v};")
    elif mn in STORES:
        n = STORES[mn]
        b.l(f"*:{n} {ea} = {I[0]}:{n};" if n < 8 else f"*:8 {ea} = {I[0]};")
    elif mn == "plfs":
        v = b.t(4, f"*:4 {ea}")
        b.l(f"{O[0]} = float2float({v});")
    elif mn == "plfd":
        b.l(f"{O[0]} = *:8 {ea};")
    elif mn == "pstfs":
        b.l(f"*:4 {ea} = float2float({I[0]});")
    elif mn == "pstfd":
        b.l(f"*:8 {ea} = {I[0]};")
    elif mn == "plxv":
        b.l(f"{O[0]} = *:16 {ea};")
    elif mn == "pstxv":
        b.l(f"*:16 {ea} = {I[0]};")
    elif mn in ("plxsd", "plxssp"):
        v = b.t(8, f"*:8 {ea}") if mn == "plxsd" else b.t(8, f"float2float({b.t(4, f'*:4 {ea}')})")
        b.l(f"{O[0]} = zext({v}) << 64;")
    elif mn in ("pstxsd", "pstxssp"):
        hi = b.t(8, f"{I[0]}(8)")
        b.l(f"*:8 {ea} = {hi};" if mn == "pstxsd" else f"*:4 {ea} = float2float({hi});")
    elif mn in ("lxvp", "lxvpx", "plxvp"):
        a, c = O[0]
        b.l("@if ENDIAN == \"big\"")
        b.l(f"{a} = *:16 {ea}; {c} = *:16 ({ea} + 16);")
        b.l("@else")
        b.l(f"{c} = *:16 {ea}; {a} = *:16 ({ea} + 16);")
        b.l("@endif")
    elif mn in ("stxvp", "stxvpx", "pstxvp"):
        a, c = I[0]
        b.l("@if ENDIAN == \"big\"")
        b.l(f"*:16 {ea} = {a}; *:16 ({ea} + 16) = {c};")
        b.l("@else")
        b.l(f"*:16 {ea} = {c}; *:16 ({ea} + 16) = {a};")
        b.l("@endif")
    elif re.fullmatch(r"lxvr(b|h|w|d)x", mn):
        e = SZ[mn[4]]
        b.l(f"{O[0]} = zext(*:{e} {ea});")
    elif re.fullmatch(r"stxvr(b|h|w|d)x", mn):
        e = SZ[mn[5]]
        b.l(f"*:{e} {ea} = {I[0]}:{e};")
    elif mn == "paddi":
        if len(I) == 1:
            b.l(f"{O[0]} = inst_start + {I[0]};")
        else:
            b.l(f"{O[0]} = {I[0]} + {I[1]};")
    elif mn == "pli":
        b.l(f"{O[0]} = {I[0]};")
    elif mn in ("brd", "brw", "brh"):
        e = {"brd": 8, "brw": 4, "brh": 2}[mn]
        src = b.t(8, I[0])
        parts = []
        for i in range(8 // e):
            off = 8 - e * (i + 1)
            x = b.t(e, f"{src}:{e}" if off == 0 else f"{src}({off})")
            parts.append(bswap(b, x, e))
        n = len(parts)
        b.l(f"{O[0]} = " + " | ".join(f"(zext({p}) << {8 * e * (n - 1 - i)})" if n - 1 - i else f"zext({p})" for i, p in enumerate(parts)) + ";")
    elif re.fullmatch(r"setn?bcr?", mn):
        neg, rev = mn.startswith("setn"), mn.endswith("r")
        t = b.t(1, f"{I[0]} == {0 if rev else 1}")
        b.l(f"{O[0]} = 0 - zext({t});" if neg else f"{O[0]} = zext({t});")
    elif mn == "xxspltiw":
        w = b.t(4, I[0])
        b.l(f"{O[0]} = (zext({w}) << 96) | (zext({w}) << 64) | (zext({w}) << 32) | zext({w});")
    elif mn == "xxspltidp":
        w = b.t(4, I[0])
        d = b.t(8, f"float2float({w})")
        b.l(f"{O[0]} = (zext({d}) << 64) | zext({d});")
    elif mn == "xxsplti32dx":
        ix, im = I
        x = O[0]
        w = b.t(16, f"zext({b.t(4, im)})")
        i1 = b.t(16, f"zext({b.t(1, ix)})")
        lo = b.t(16, f"(1 - {i1}) * 32")
        hi = b.t(16, f"{lo} + 64")
        m = b.t(16, f"(0xffffffff << {hi}) | (0xffffffff << {lo})")
        b.l(f"{x} = ({x} & ~{m}) | ({w} << {hi}) | ({w} << {lo});")
    elif re.fullmatch(r"xxblendv(b|h|w|d)", mn):
        e = SZ[mn[-1]]
        r = lanewise(b, e, I, lambda a, c, k: f"({c} * zext({k} s< 0)) + ({a} * zext({k} s>= 0))")
        b.l(f"{O[0]} = {r};")
    elif mn in ("vsldbi", "vsrdbi"):
        c = b.t(32, f"(zext({I[0]}) << 128) | zext({I[1]})")
        sh = b.t(32, f"zext({b.t(1, I[2])})")
        if mn == "vsldbi":
            t = b.t(32, f"{c} << {sh}")
            b.l(f"{O[0]} = {t}(16);")
        else:
            t = b.t(32, f"{c} >> {sh}")
            b.l(f"{O[0]} = {t}:16;")
    elif re.fullmatch(r"vmul(ld|hsd|hud|hsw|huw)", mn):
        k = mn[4:]
        e = 8 if k.endswith("d") else 4
        if k == "ld":
            r = lanewise(b, 8, I, lambda x, y: f"{x} * {y}")
        else:
            ext = "sext" if k[1] == "s" else "zext"

            def hi(x, y):
                p = b.t(2 * e, f"{ext}({x}) * {ext}({y})")
                return f"{p}({e})"
            r = lanewise(b, e, I, hi)
        b.l(f"{O[0]} = {r};")
    elif re.fullmatch(r"vmul(e|o)(s|u)d", mn):
        a = lanes(b, b.t(16, I[0]), 8)
        c = lanes(b, b.t(16, I[1]), 8)
        i = 0 if mn[4] == "e" else 1
        ext = "sext" if mn[5] == "s" else "zext"
        b.l(f"{O[0]} = {ext}({a[i]}) * {ext}({c[i]});")
    elif mn == "vextsd2q":
        lo = b.t(8, f"{I[0]}:8")
        b.l(f"{O[0]} = sext({lo});")
    elif re.fullmatch(r"vcmp(equq|gtsq|gtuq)\.?", mn):
        o = {"equq": "==", "gtsq": "s>", "gtuq": ">"}[mn[4:8]]
        a, c = b.t(16, I[0]), b.t(16, I[1])
        t = b.t(1, f"{a} {o} {c}")
        b.l(f"{O[0]} = 0 - zext({t});")
        if mn.endswith("."):
            b.l(f"cr6 = ({t} << 3) | ((!{t}) << 1);")
    elif mn in ("vcmpsq", "vcmpuq"):
        a, c = b.t(16, I[0]), b.t(16, I[1])
        lt = "s<" if mn == "vcmpsq" else "<"
        b.l(f"{O[0]} = (zext({a} {lt} {c}) << 3) | (zext({c} {lt} {a}) << 2) | (zext({a} == {c}) << 1);")
    elif mn in ("vslq", "vsrq", "vsraq", "vrlq"):
        a, c = b.t(16, I[0]), b.t(16, I[1])
        sh = b.t(16, f"zext({b.t(1, f'{c}(8)')} & 0x7f)")
        if mn == "vrlq":
            b.l(f"{O[0]} = ({a} << {sh}) | ({a} >> ((128 - {sh}) & 127));")
        else:
            o = {"vslq": "<<", "vsrq": ">>", "vsraq": "s>>"}[mn]
            b.l(f"{O[0]} = {a} {o} {sh};")
    elif mn in ("vclrlb", "vclrrb"):
        a = b.t(16, I[0])
        n = b.t(8, I[1])
        k = b.t(16, f"zext((16 - {n}) * zext({n} < 16)) * 8")
        mk = b.t(16, "-1")
        b.l(f"{O[0]} = {a} & ({mk} >> {k});" if mn == "vclrlb" else f"{O[0]} = {a} & ({mk} << {k});")
    elif re.fullmatch(r"v(div|mod)(s|u)(w|d|q)", mn):
        e = SZ[mn[-1]]
        op = {("div", "s"): "s/", ("div", "u"): "/", ("mod", "s"): "s%", ("mod", "u"): "%"}[(mn[1:4], mn[4])]
        r = lanewise(b, e, I, lambda x, y: f"{x} {op} {y}")
        b.l(f"{O[0]} = {r};")
    elif re.fullmatch(r"vextract(b|h|w|d|q)m", mn):
        e = SZ[mn[8]]
        ls = lanes(b, b.t(16, I[0]), e)
        n = len(ls)
        bits = [b.t(8, f"zext({x} s< 0)") for x in ls]
        b.l(f"{O[0]} = " + " | ".join(f"({x} << {n - 1 - i})" if n - 1 - i else x for i, x in enumerate(bits)) + ";")
    elif re.fullmatch(r"vexpand(b|h|w|d|q)m", mn):
        e = SZ[mn[7]]
        r = lanewise(b, e, I, lambda x: f"0 - zext({x} s< 0)")
        b.l(f"{O[0]} = {r};")
    elif re.fullmatch(r"mtvsr(b|h|w|d|q)mi?", mn):
        e = SZ[mn[5]]
        n = 16 // e
        src = b.t(8, I[0])
        parts = [b.t(e, f"0 - zext((({src} >> {n - 1 - i}) & 1) != 0)") for i in range(n)]
        b.l(f"{O[0]} = {combine(b, parts, e)};")
    elif re.fullmatch(r"vcntmb(b|h|w|d)", mn):
        e = SZ[mn[6]]
        ls = lanes(b, b.t(16, I[0]), e)
        mp = b.t(1, I[1])
        cnt = b.t(8, " + ".join(f"zext(zext({x} s< 0) == {mp})" for x in ls))
        b.l(f"{O[0]} = {cnt} << {56 + {1: 0, 2: 1, 4: 2, 8: 3}[e]};")
    elif re.fullmatch(r"vstri(b|h)(l|r)\.?", mn):
        e = SZ[mn[5]]
        ls = lanes(b, b.t(16, I[0]), e)
        order = range(len(ls)) if mn[6] == "l" else range(len(ls) - 1, -1, -1)
        f = b.t(1, "0")
        kept = {}
        for i in order:
            kept[i] = b.t(e, f"{ls[i]} * zext({f} == 0)")
            b.l(f"{f} = {f} | ({ls[i]} == 0);")
        b.l(f"{O[0]} = {combine(b, [kept[i] for i in range(len(ls))], e)};")
        if mn.endswith("."):
            b.l(f"cr6 = {f} << 1;")
    elif mn == "xxsetaccz":
        b.l(f"{O[0]} = 0;")
    elif mn in ("xxmtacc", "xxmfacc"):
        b.l(f"{O[0]} = {O[0]};")
    else:
        return None
    return "\n\t".join(b.lines).replace("\t@", "@")


