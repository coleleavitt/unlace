#!/usr/bin/env python3
"""GFX11 MIMG: image loads, stores, atomics, samples, gathers and the BVH ray queries.

Layout from llvm-mc -mcpu=gfx1100 -show-encoding: word 0 bits 31-26 = 111100, op 25-18,
d16 17, a16 16, r128 15, glc 14, dlc 13, slc 12, dmask 11-8, unorm 7, dim 4-2, nsa 0; word 1
ssamp 30-26 (x4), lwe 22, tfe 21, srsrc 20-16 (x4), vdata 15-8, vaddr 7-0.  With nsa set a
third word holds four more address VGPRs, one per byte; a fifth and later address share the
last byte as a tuple.  The address count of each opcode, dim and a16 comes from the table
tools/amdgpu_gfx11_probe.py reads out of llvm-objdump.  The data count is the dmask's bit
count (4 for gather4 and msaa_load), halved and rounded up with d16, plus one with tfe: MD/MF
set it in the context field mi_vdn (declared in the base spec), and MV (display), MW (write)
and MX (read) pick the data tuple by it.  Every operation is a user-op that takes the
resource, the sampler and the first address; the data passes through mimg_data.

usage: gen_amdgpu_gfx11_mimg.py mimg_ops.txt amdgcn_gfx11.slaspec ... > amdgcn_gfx11_mimg.sinc
"""
import re
import sys

BVH = {25: ('image_bvh_intersect_ray', 11, 8), 26: ('image_bvh64_intersect_ray', 12, 9)}


def vreg(s, n):
    """Register name of the n-VGPR tuple at s (the base spec and the VOP3P include name 1, 2, 4, 8)."""
    return {1: 'v%d' % s, 2: 'v%d_%d' % (s, s + 1), 4: 'wv%d_%d' % (s, s + 3)}.get(n, 'mv%d_%d' % (s, s + n - 1))


def rng(s, n):
    return ('v%d' % s) if n == 1 else 'v[%d:%d]' % (s, s + n - 1)


def main():
    table = [l.split() for l in open(sys.argv[1]) if l.strip()]
    have = set(re.findall(r'define pcodeop (\w+);', ''.join(open(f).read() for f in sys.argv[2:])))
    sregs = re.search(r'define register offset=0x0+ size=4 \[([^\]]*)\]', open(sys.argv[2]).read()).group(1).split()

    def sgpr(s, k):
        """Display of the k-SGPR tuple at s (ttmp tuples as LLVM prints them) and its first register."""
        nm = sregs[s]
        if nm.startswith('ttmp'):
            t = int(nm[4:])
            return 'ttmp[%d:%d]' % (t, t + k - 1), nm
        return 's[%d:%d]' % (s, s + k - 1), nm

    o = []
    w = o.append
    w('# Generated by tools/gen_amdgpu_gfx11_mimg.py; edit the generator.')
    for n in (3, 5):
        for k in range(n):
            names = [vreg(s, n) for s in range(k, 256 - n + 1, n)]
            w('define register offset=0x%x size=%d [ %s ];' % (0x1000 + 4 * k, 4 * n, ' '.join(names)))
    w('define register offset=0x4000 size=32 [ mimg_data ];')
    w('define token mi0(32) mi_nsa = (0,0) mi_dim = (2,4) mi_unorm = (7,7) mi_dmask = (8,11) mi_slc = (12,12)'
      ' mi_dlc = (13,13) mi_glc = (14,14) mi_r128 = (15,15) mi_a16 = (16,16) mi_d16 = (17,17) mi_op = (18,25)'
      ' mi_e6 = (26,31);')
    w('define token mi1(32) mi_va = (0,7) mi_vd = (8,15) mi_rs = (16,20) mi_tfe = (21,21) mi_lwe = (22,22)'
      ' mi_ss = (26,30);')
    w('define token mi2(32) mi_b0 = (0,7) mi_b1 = (8,15) mi_b2 = (16,23) mi_b3 = (24,31) mi_b3v = (24,31);')
    vlist = ' '.join('v%d' % i for i in range(256))
    w('attach variables [ mi_b0 mi_b1 mi_b2 mi_b3v ] [ %s ];' % vlist)
    ops = {}
    dims = {}
    for op, mn, samp, dim, dn, a16, n in table:
        ops.setdefault(int(op), [mn, int(samp), {}])[2][(int(dim), int(a16))] = int(n)
        dims[int(dim)] = dn
    names = sorted({v[0] for v in ops.values()} | {v[0] for v in BVH.values()})
    for nm in names:
        if nm not in have:
            w('define pcodeop %s;' % nm)
    w('')
    # data count from dmask/d16/tfe/lwe (MD) or four (MF, gather4 and msaa_load), into mi_vdn
    for dm in range(16):
        for d16 in (0, 1):
            for x in range(4):
                for fixed in (0, 1):
                    c = 4 if fixed else max(1, bin(dm).count('1'))
                    if d16:
                        c = (c + 1) // 2
                    c += x & 1
                    w('M%s: is mi_dmask=%d & mi_d16=%d ; mi_tfe=%d & mi_lwe=%d [ mi_vdn = %d; ] { }'
                      % ('F' if fixed else 'D', dm, d16, x & 1, x >> 1, c))
    # the data tuple: MV displays it, MW copies mimg_data into it, MX copies it into mimg_data
    for n in range(1, 6):
        for s in range(256 - n + 1):
            pat = 'mi_vdn=%d & mi_e6=0x3c ; mi_vd=%d' % (n, s)
            w('MV: "%s" is %s { }' % (rng(s, n), pat))
            w('MW: is %s { %s = mimg_data:%d; }' % (pat, vreg(s, n), 4 * n))
            w('MX: is %s { mimg_data = zext(%s); }' % (pat, vreg(s, n)))
    for n in range(1, 14):
        for s in range(256 - n + 1):
            w('MA%d: "%s" is mi_e6=0x3c ; mi_va=%d { export v%d; }' % (n, rng(s, n), s, s))
    for n in range(2, 10):
        for s in range(256 - n + 1):
            w('MT%d: "%s" is mi_b3=%d { export v%d; }' % (n, rng(s, n), s, s))
    for k, t in ((8, 'MRS'), (4, 'MRB')):
        for s in range(32):
            d, nm = sgpr(4 * s, k)
            w('%s: "%s" is mi_e6=0x3c ; mi_rs=%d { export %s; }' % (t, d, s, nm))
    for s in range(32):
        d, nm = sgpr(4 * s, 4)
        w('MS: "%s" is mi_e6=0x3c ; mi_ss=%d { export %s; }' % (d, s, nm))
    for d, dn in sorted(dims.items()):
        w('MDIM: "%s" is mi_dim=%d { }' % (dn, d))
    # the modifier suffix, in LLVM's order; one table keeps the operand count down
    fl = ['unorm', 'glc', 'slc', 'dlc', 'r128', 'a16', 'tfe', 'lwe', 'd16']
    for v in range(1 << len(fl)):
        on = [f for i, f in enumerate(fl) if (v >> i) & 1]
        p0 = ' & '.join('mi_%s=%d' % (f, (v >> i) & 1) for i, f in enumerate(fl) if f not in ('tfe', 'lwe'))
        p1 = ' & '.join('mi_%s=%d' % (f, (v >> i) & 1) for i, f in enumerate(fl) if f in ('tfe', 'lwe'))
        w('MFL: %sis %s ; %s { }' % ('"%s" ' % ''.join(' ' + f for f in on) if on else '', p0, p1))
    w('')
    body = []
    for op, (mn, samp, shapes) in sorted(ops.items()):
        fixed = mn.startswith('image_gather4') or mn == 'image_msaa_load'
        cnt = 'MF' if fixed else 'MD'
        store = mn.startswith('image_store')
        atomic = mn.startswith('image_atomic')
        byn = {}
        for (dim, a16), n in sorted(shapes.items()):
            byn.setdefault(n, []).append((dim, a16))
        for n, shp in sorted(byn.items()):
            sel = ' | '.join('(mi_dim=%d & mi_a16=%d)' % s for s in shp)
            for nsa in ((0, 1) if n > 1 else (0,)):
                if nsa:
                    singles = ['MA1'] + ['mi_b0', 'mi_b1', 'mi_b2', 'mi_b3v'][:min(n, 5) - 1]
                    if n > 5:
                        singles = singles[:4] + ['MT%d' % (n - 4)]
                    disp_addr = '"["^' + '^", "^'.join(singles) + '^"]"'
                else:
                    disp_addr = 'MA%d' % n
                    singles = ['MA%d' % n]
                srcs = [disp_addr, 'MRS'] + (['MS'] if samp else [])
                disp = '%s %s^MV, %s^" dmask:"^mi_dmask^" dim:"^MDIM^MFL' % (mn, cnt, ', '.join(srcs))
                w0 = 'mi_e6=0x3c & mi_op=%d & (%s) & mi_nsa=%d & mi_dmask & MDIM' % (op, sel, nsa)
                io = 'MX' if store else ('MW & MX' if atomic else 'MW')
                pat = '(%s ; mi_va) & MFL & %s & MV & %s & MRS%s & %s' % (w0, cnt, io, ' & MS' if samp else '', singles[0])
                if nsa:
                    pat = '(%s) ; %s' % (pat, ' & '.join(singles[1:]))
                args = 'MRS, ' + ('MS, ' if samp else '') + singles[0]
                if store:
                    sem = 'build MX; %s(%s, mimg_data);' % (mn, args)
                elif atomic:
                    sem = 'build MX; mimg_data = %s(%s, mimg_data); build MW;' % (mn, args)
                else:
                    sem = 'mimg_data = %s(%s); build MW;' % (mn, args)
                body.append(':%s is %s { %s }' % (disp, pat, sem))
    for op, (mn, n, n16) in sorted(BVH.items()):
        for a16, c in ((0, n), (1, n16)):
            body.append(':%s MF^MV, MA%d, MRB%s is (mi_e6=0x3c & mi_op=%d & mi_a16=%d & mi_nsa=0 & mi_dmask=0xf '
                        '& mi_r128=1 & mi_d16=0 ; mi_tfe=0 & mi_lwe=0) & MF & MV & MW & MA%d & MRB '
                        '{ mimg_data = %s(MRB, MA%d); build MW; }' % (mn, c, '^" a16"' if a16 else '', op, a16, c, mn, c))
    w('\n'.join(body))
    print('\n'.join(o))


main()
