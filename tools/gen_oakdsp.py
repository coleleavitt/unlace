#!/usr/bin/env python3
"""Generate the CEVA OakDSP language from the vendored TeakLite II module.

TeakLite II keeps OakDSP's encodings and adds instructions in Oak's free code space and in the operand
values Oak leaves reserved (r6/r7 as pointers, 18-bit branch targets, more bank-exchange flags...).  This
script decodes every first word with the teak language (through an unlace binary), compares each word with
the OakDSP map in tools/oakdsp_oracle.txt (tools/oakdsp_probe.py), and writes oakdsp_*.sinc:

* a teak constructor none of whose words is an Oak instruction is dropped;
* a constructor that is only partly valid on Oak is split into copies whose extra single-bit constraints
  (ob_N fields) cover exactly its Oak-valid words;
* Oak forms TeakLite reassigned are added by hand (EXTRA below).

Words the oracle decodes only because it ignores reserved bits (aliases of a canonical encoding) stay
undecoded.  Usage: gen_oakdsp.py --unlace BIN [--sleighpath SPECS_DIR]
"""
import argparse, json, os, re, struct, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
LANG = os.path.join(HERE, '..', 'specs', 'Ghidra', 'Processors', 'TeakLite', 'data', 'languages')
ALIAS = {('lpg', 'load_page'), ('maxd', 'max_ge_r0'), ('maxd', 'max_gt_r0'), ('reti', 'retic')}
HEADER = '# Generated by tools/gen_oakdsp.py from teak_*.sinc and tools/oakdsp_oracle.txt: do not edit.\n'

# mov Ax, Register: OakDSP accepts a0/a1 (register codes 0x18/0x19) as the source of the register move and
# stores the saturated low word; TeakLite II gave these codes to mma_mov.
EXTRA = r'''
:mov Ax_0,Register_5 is f_10_15=0x16 & f_1_4=0xc & Ax_0 & Register_5 & RegisterN_5 & WrR_5
{
    local v:8 = 0;
    GetSatAcc(v, Ax_0);
    wb = v:2;
    build WrR_5;
}
'''

def oracle():
    m = [None] * 65536
    for l in open(os.path.join(HERE, 'oakdsp_oracle.txt')):
        if l.startswith('#'):
            continue
        a, b, n, mn = l.split()
        for w in range(int(a, 16), int(b, 16) + 1):
            m[w] = (int(n), mn)
    return m

def elf(code):
    base, ehsz, phsz, shsz = 0x1000, 64, 56, 64
    shstr = b'\0.text\0.shstrtab\0'
    off_code = ehsz + phsz
    off_shstr = off_code + len(code)
    off_sh = (off_shstr + len(shstr) + 7) & ~7
    e = b'\x7fELF' + bytes([2, 1, 1, 64]) + b'\0' * 8
    e += struct.pack('<HHIQQQIHHHHHH', 2, 224, 1, base, ehsz, off_sh, 0, ehsz, phsz, 1, shsz, 3, 2)
    ph = struct.pack('<IIQQQQQQ', 1, 5, off_code, base, base, len(code), len(code), 4)
    sh1 = struct.pack('<IIQQQQIIQQ', 1, 1, 6, base, off_code, len(code), 0, 0, 4, 0)
    sh2 = struct.pack('<IIQQQQIIQQ', 7, 3, 0, 0, off_shstr, len(shstr), 0, 0, 1, 0)
    d = e + ph + code + shstr
    return d + b'\0' * (off_sh - len(d)) + b'\0' * shsz + sh1 + sh2

def teak_decode(unlace, sleighpath):
    code = b''.join(struct.pack('<HHHH', w, 0x1234, 0, 0) for w in range(65536))
    with tempfile.TemporaryDirectory() as d:
        p = os.path.join(d, 'words.elf')
        open(p, 'wb').write(elf(code))
        cmd = [unlace, 'disassemble', p, '0x1000-0x81000', '--target', 'teak:LE:16:default', '--json']
        if sleighpath:
            cmd += ['--sleighpath', sleighpath]
        j = json.loads(subprocess.run(cmd, capture_output=True, check=True).stdout)
    dec = {}
    for i in j['instructions']:
        off = i['address'] - 0x1000
        if off % 8 == 0:
            t = i['text'].split()
            dec[off // 8] = (t[0] if t and not t[0].startswith('.') else '', i['size'] // 2)
    return [dec.get(w, ('', 0)) for w in range(65536)]

def compatible(ida, teak):
    n, mi = ida
    mt, sz = teak
    return n != 0 and n == sz and (mt == mi or mt.startswith(mi + '_') or (mi, mt) in ALIAS)

def cover(fixed_mask, fixed_val, good, bad):
    free = [1 << b for b in range(15, -1, -1) if not fixed_mask >> b & 1]
    cubes, left = [], set(good)
    for v in sorted(good):
        if v not in left:
            continue
        cm = 0xffff
        for bit in free:
            m2 = cm & ~bit
            if not any(w & m2 == v & m2 for w in bad):
                cm = m2
        cubes.append((cm, v & cm))
        left -= {w for w in left if w & cm == v & cm}
    return cubes

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--unlace', required=True)
    ap.add_argument('--sleighpath')
    ap.add_argument('--report', help='write the oracle-valid first words left undecoded to this JSON file')
    a = ap.parse_args()
    ida = oracle()
    teak = teak_decode(a.unlace, a.sleighpath)
    src = open(os.path.join(LANG, 'teak_insts.sinc')).read().split('\n')
    starts = [i for i, l in enumerate(src) if l.startswith(':')]
    out = [HEADER]
    stats = {'kept': 0, 'split': 0, 'dropped': 0, 'copies': 0}
    covered = set()
    for k, s in enumerate(starts):
        e = starts[k + 1] if k + 1 < len(starts) else len(src)
        block = src[s:e]
        m = re.match(r':(\S*)\s.*?\bis\s+(.*)$', block[0])
        mn, pat = m.group(1), m.group(2).split(';')[0]
        mask = val = 0
        for lo, hi, v in re.findall(r'\bf_(\d+)_(\d+)=(0x[0-9a-f]+|\d+)', pat):
            lo, hi = int(lo), int(hi)
            mask |= ((1 << (hi - lo + 1)) - 1) << lo
            val |= int(v, 0) << lo
        att = [w for w in range(65536) if w & mask == val and teak[w][0] == mn]
        good = [w for w in att if compatible(ida[w], teak[w])]
        bad = [w for w in att if w not in set(good)]
        if att and not good:
            stats['dropped'] += 1
            continue
        if not bad:
            stats['kept'] += 1
            out.extend(block)
            covered.update(att)
            continue
        stats['split'] += 1
        covered.update(good)
        for cm, cv in cover(mask, val, good, set(bad)):
            extra = ' & '.join('ob_%d=%d' % (b, cv >> b & 1) for b in range(16) if (cm & ~mask) >> b & 1)
            head = block[0]
            i = head.index(' is ') + 4
            if head[i] == '(':
                depth, end = 0, i
                for end in range(i, len(head)):
                    depth += {'(': 1, ')': -1}.get(head[end], 0)
                    if depth == 0:
                        break
                head = head[:end] + ' & ' + extra + head[end:]
            else:
                semi = head.find(';', i)
                end = semi if semi >= 0 else (head.find('{', i) if '{' in head[i:] else len(head))
                head = head[:end].rstrip() + ' & ' + extra + (' ' + head[end:] if end < len(head) else '')
            out.append(head)
            out.extend(block[1:])
            stats['copies'] += 1
    out.append(EXTRA)
    open(os.path.join(LANG, 'oakdsp_insts.sinc'), 'w').write('\n'.join(out).rstrip() + '\n')
    tok = open(os.path.join(LANG, 'teak_tokens.sinc')).read()
    tok = tok.replace('# Generated by tools/gen_teak.py: do not edit.\n', HEADER)
    tok = tok.replace('define token teakop (16)\n', 'define token teakop (16)\n' + ''.join('    ob_%d = (%d,%d)\n' % (b, b, b) for b in range(16)), 1)
    open(os.path.join(LANG, 'oakdsp_tokens.sinc'), 'w').write(tok)
    sla = open(os.path.join(LANG, 'teak.slaspec')).read()
    sla = sla.replace('# sleigh specification file for the Teak / TeakLite II DSP (Nintendo DSi and 3DS DSP)',
                      '# sleigh specification file for the CEVA OakDSP core, generated by tools/gen_oakdsp.py from teak.slaspec: do not edit.\n'
                      '# The registers, tables and macros are TeakLite II\'s (a superset of Oak); oakdsp_insts.sinc keeps the Oak encodings.')
    sla = sla.replace('"teak_tokens.sinc"', '"oakdsp_tokens.sinc"').replace('"teak_insts.sinc"', '"oakdsp_insts.sinc"')
    open(os.path.join(LANG, 'oakdsp.slaspec'), 'w').write(sla)
    print(stats, file=sys.stderr)
    if a.report:
        miss = [w for w in range(65536) if ida[w][0] and w not in covered]
        print('oracle-valid words not covered:', len(miss), file=sys.stderr)
        json.dump(miss, open(a.report, 'w'))

if __name__ == '__main__':
    main()
