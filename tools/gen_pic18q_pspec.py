#!/usr/bin/env python3
"""Write the PIC18 Q-series processor specs (pic18q_<family>.pspec) from Microchip's PIC18F-Q device pack.

Usage: gen_pic18q_pspec.py <Microchip.PIC18F-Q_DFP.<version>.atpack> [<out-dir>]

The pack is Apache-2.0 (its LICENSE.txt). For each family (Q20, Q24, ...) every SFR of every
device (edc:SFRDef in edc/PIC18F*.PIC) becomes a <default_symbols> label in DATA space under its
datasheet name; an address with several SFRDefs (a register shared by two modes, CRCOUTL/CRCSHFTL)
takes the first. A family's devices share one map; a family where two devices name one address
differently is left out and reported. The core registers (STATUS..TOSU, the top 0x28 bytes of the
SFR page) are left out: SLEIGH names them, and a label would make WREG a global the decompiler keeps. Families whose core registers sit at 0x4d8 (K42/Q core) use
pic18q.sla, the others pic18.sla; the script prints the ldefs rows for the families it wrote.
"""
import re
import sys
import zipfile
from collections import defaultdict
from pathlib import Path

SFR = re.compile(r'<edc:SFRDef [^>]*?edc:cname="([^"]+)"[^>]*?edc:_addr="(0x[0-9A-Fa-f]+)"')


def main():
    pack = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / "specs/Ghidra/Processors/PIC/data/languages"
    families = defaultdict(dict)
    devices = defaultdict(list)
    clashes = defaultdict(list)
    with zipfile.ZipFile(pack) as z:
        version = re.search(r"<release version=\"([^\"]+)\"", z.read(next(n for n in z.namelist() if n.endswith(".pdsc"))).decode()).group(1)
        for name in sorted(n for n in z.namelist() if re.fullmatch(r"edc/PIC18F\d+Q\d+\.PIC", n)):
            dev = Path(name).stem
            family = re.fullmatch(r"PIC18F\d+(Q\d+)", dev).group(1)
            devices[family].append(dev)
            regs = families[family]
            own = {}
            for cname, addr in SFR.findall(z.read(name).decode("utf-8", "replace")):
                own.setdefault(int(addr, 16), cname)
            for addr, cname in own.items():
                if regs.setdefault(addr, cname) != cname:
                    clashes[family].append(f"{dev}: 0x{addr:03x} {cname} vs {regs[addr]}")
    for family in sorted(families):
        if clashes[family]:
            print(f"skipped {family}: {len(clashes[family])} clashes, e.g. {clashes[family][0]}", file=sys.stderr)
            continue
        regs = families[family]
        qcore = regs.get(0x4D8) == "STATUS"
        if not qcore and regs.get(0xFD8) != "STATUS":
            print(f"skipped {family}: STATUS at neither 0x4d8 nor 0xfd8", file=sys.stderr)
            continue
        sfr_lo, sfr_hi = (0x460, 0x4FF) if qcore else (0xF60, 0xFFF)
        volatile = sorted(a for a in regs if not sfr_lo + 0x78 <= a <= sfr_hi)
        ranges = []
        for a in volatile:
            if ranges and ranges[-1][1] == a - 1:
                ranges[-1][1] = a
            else:
                ranges.append([a, a])
        lines = [
            '<?xml version="1.0" encoding="UTF-8"?>',
            "",
            f"<!-- Generated by tools/gen_pic18q_pspec.py from Microchip PIC18F-Q_DFP {version} (Apache-2.0):",
            f"     the SFRs of the PIC18F {family} devices ({', '.join(devices[family])}). -->",
            "<processor_spec>",
            '  <programcounter register="PC"/>',
            '  <volatile outputop="write_sfr" inputop="read_sfr">',
        ]
        lines += [f'    <range space="DATA" first="0x{a:03x}" last="0x{b:03x}"/>' for a, b in ranges]
        lines += ["  </volatile>", "  <default_symbols>"]
        lines += [f'    <symbol name="{regs[a]}" address="DATA:0x{a:03x}"/>' for a in volatile]
        lines += ["  </default_symbols>", "</processor_spec>", ""]
        (out / f"pic18q_{family.lower()}.pspec").write_text("\n".join(lines))
        sla = "pic18q.sla" if qcore else "pic18.sla"
        print(f'{family} {sla}')


if __name__ == "__main__":
    main()
