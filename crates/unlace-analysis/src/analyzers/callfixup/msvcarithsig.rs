//! (kuna) Recognize the statically linked MSVC x86-32 64-bit arithmetic CRT
//! helpers in a stripped PE by their bytes, so the `kuna_arithhelpers`
//! call-fixups reach them.
//!
//! The fixups are installed by name, and a stripped image names nothing: a
//! `long long` multiply, divide, remainder or shift then prints as a call with
//! four 32-bit words (`sub_10106380(a2,a3,0xffffd8f0,0xffffffff)`), and the
//! helper's own body as a `CONCAT44` of its halves. Each recognized entry is
//! reported as a function symbol under its CRT name and as a [`CallFixupFact`],
//! which the commit resolves by that name, exactly as
//! [`super::kuna_msvcftolsig`] does for the `__ftol` family.
//!
//! Signatures are the complete instruction streams of the CRT's `llmul.asm`,
//! `lldiv.asm`, `llrem.asm`, `lldvrm.asm`, `ulldiv.asm`, `ullrem.asm`,
//! `ulldvrm.asm`, `llshl.asm`, `llshr.asm` and `ullshr.asm` objects up to the
//! last `ret`; none of them has a relocation. The bytes are those Windows'
//! SysWOW64 `ntdll.dll` exports under the same names, and each stream recurs
//! once per image across 2,555 SysWOW64 PE files (`__allmul` in 1,094 of them),
//! always at a function entry.

