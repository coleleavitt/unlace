def emit_branches():
    for k, mn in BNAMES.items():
        c = COND[k]
        for opc, tok in ((0x60 + k, "REL8"), (0x70 + k, "REL16")):
            if k == 10:
                w(":%s %s is op=0x%02x; %s { goto %s; }" % (mn, tok, opc, tok, tok))
            else:
                w(":%s %s is op=0x%02x; %s { if (%s) goto %s; }" % (mn, tok, opc, tok, c, tok))
    w(":bsr REL16 is op=0x48; REL16 { SP = SP - 4; *:4 SP = inst_next; call REL16; }")
    # F6: decrement and branch
    for base, odd in ((0xC6, 0), (0xC7, 1)):
        for hi in range(8):
            k = hi * 2 + odd
            if k == 11:
                w(":tb c_reg, REL16 is op=0xc7; c_hi3=5 & c_reg; REL16 { if (c_reg == 0) goto REL16; }")
                continue
            mn = "db" + BNAMES[k][1:]
            cond = "(c_reg != 0)" if k == 10 else "(c_reg != 0) && %s" % COND[k]
            w(":%s c_reg, REL16 is op=0x%02x; c_hi3=%d & c_reg; REL16 "
              "{ c_reg = c_reg - 1; if (%s) goto REL16; }" % (mn, base, hi, cond))
    w(":halt is op=0x00 { halt(); }")
    w(":clrtlba is op=0x10 { clrtlba(); }")
    w(":brk is op=0xc8 { brk(); }")
    w(":brkv is op=0xc9 { if (!OV) goto inst_next; packpsw(); brkTrap(); }")
    w(":rsr is op=0xca { local ra:4 = *:4 SP; SP = SP + 4; return [ra]; }")
    w(":trapfl is op=0xcb { packpsw(); trapfl(); }")
    w(":dispose is op=0xcc { SP = FP; FP = *:4 SP; SP = SP + 4; }")
    w(":nop is op=0xcd { }")
    w("")


