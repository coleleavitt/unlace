fn decompile(name: &str, addr: &str) -> String {
    let bin = scratch_file(name, "bin");
    std::fs::write(&bin, IMAGE).unwrap();
    let (stdout, stderr, code) = run_kuna(&[
        "decompile",
        bin.to_str().unwrap(),
        addr,
        "--raw-image",
        "--target",
        "lanai:BE:32:default",
        "--base",
        "0x0",
    ]);
    assert_eq!(code, 0, "{stderr}");
    let lower = stdout.to_lowercase();
    assert!(!lower.contains("unimplemented"), "{stdout}");
    assert!(!lower.contains("bad instruction"), "{stdout}");
    stdout
}

#[test]
fn lanai_compare_branch_decompiles() {
    let out = decompile("lanai_compare_branch_decompiles", "0x0");
    assert!(out.contains("int sub_0(int a0,int a1)"), "{out}");
    assert!(out.contains("if (a1 <= a0)"), "{out}");
    assert!(out.contains("a0 *= 3;"), "{out}");
    assert!(out.contains("return a1 + a0;"), "{out}");
}

#[test]
fn lanai_call_decompiles() {
    let out = decompile("lanai_call_decompiles", "0x68");
    assert!(out.contains("return sub_94(a0 + 1) + 2;"), "{out}");
}
