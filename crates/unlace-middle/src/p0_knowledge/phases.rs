// --- The catalog JSON emitter (byte-compatible with unlaceEmitSettableJson) ----

/// Append `str` to `out` as a JSON string literal — byte-for-byte port of
/// `unlace_console.cc unlaceJsonString` (quotes + minimal escaping; control chars
/// below 0x20 other than `\n` collapse to a single space).
fn json_string(out: &mut String, s: &str) {
    out.push('"');
    for ch in s.chars() {
        if ch == '"' || ch == '\\' {
            out.push('\\');
            out.push(ch);
        } else if ch == '\n' {
            out.push_str("\\n");
        } else if (ch as u32) < 0x20 {
            // C++ drops other control chars to a single space.
            out.push(' ');
        } else {
            out.push(ch);
        }
    }
    out.push('"');
}

/// Emit one settable as a JSON object onto `out` — byte-for-byte port of
/// `unlace_console.cc unlaceEmitSettableJson`.
///
/// `live` is the live current value (C++ joins it from the `Architecture`);
/// pass `None` to suppress the `current` field, exactly as the C++ does when
/// `unlaceLiveValue` returns `""` (no program loaded, or no live reader).
pub fn emit_settable_json(out: &mut String, st: &UnlaceSettable, live: Option<&str>) {
    out.push_str("  {");
    out.push_str("\"option\": ");
    json_string(out, st.option);
    out.push_str(", \"values\": [");
    // Split the pipe-separated values into a JSON array. The C++ walks
    // `pos <= vals.size()` so a trailing empty token (vals ending in '|') would
    // emit an empty "" — replicate that with the inclusive loop below; the
    // catalog never ends a values string in '|', so this matches in practice.
    let vals = st.values;
    let mut first = true;
    let mut pos = 0usize;
    loop {
        let rest = &vals[pos..];
        let (tok, next) = match rest.find('|') {
            Some(bar) => (&rest[..bar], Some(pos + bar + 1)),
            None => (rest, None),
        };
        if !first {
            out.push_str(", ");
        }
        json_string(out, tok);
        first = false;
        match next {
            Some(p) => pos = p,
            None => break,
        }
    }
    out.push(']');
    out.push_str(", \"default\": ");
    json_string(out, st.shipped);
    if let Some(live) = live
        && !live.is_empty() {
            out.push_str(", \"current\": ");
            json_string(out, live);
        }
    out.push_str(", \"destructive_as_default\": ");
    out.push_str(if st.destructive { "true" } else { "false" });
    out.push_str(", \"phase\": ");
    json_string(out, st.phase.code());
    out.push_str(", \"subphase\": ");
    json_string(out, st.subphase);
    out.push_str(", \"strength\": ");
    json_string(out, st.strength.catalog_code());
    out.push_str(", \"rewind\": ");
    json_string(out, st.rewind.code());
    out.push_str(", \"issue\": ");
    json_string(out, st.issue);
    out.push_str(", \"summary\": ");
    json_string(out, st.summary);
    out.push_str(", \"use_when\": ");
    json_string(out, st.use_when);
    out.push_str(", \"example\": ");
    json_string(out, st.example);
    out.push_str(", \"source_decompiler\": ");
    json_string(out, st.source_decompiler);
    out.push_str(", \"inspiration\": ");
    json_string(out, st.inspiration);
    out.push_str(", \"change_kind\": ");
    json_string(out, st.change_kind);
    out.push_str(", \"tier\": ");
    json_string(out, st.tier);
    out.push_str(", \"symptoms\": [");
    // Split the pipe-separated symptom phrases into a JSON array, with the
    // same inclusive walk as `values` above (a symptoms string never ends in
    // '|', so no trailing empty token arises in practice).
    let syms = st.symptoms;
    let mut first = true;
    let mut pos = 0usize;
    loop {
        let rest = &syms[pos..];
        let (tok, next) = match rest.find('|') {
            Some(bar) => (&rest[..bar], Some(pos + bar + 1)),
            None => (rest, None),
        };
        if !first {
            out.push_str(", ");
        }
        json_string(out, tok);
        first = false;
        match next {
            Some(p) => pos = p,
            None => break,
        }
    }
    out.push(']');
    out.push('}');
}

/// Emit the full settable catalog as JSON — byte-for-byte port of
/// `IfcUnlacePhaseCatalog::execute`'s no-argument form (`phase catalog`).
///
/// `live` maps an option name to its live current value (or `None`); pass a
/// closure returning `None` for every option to get the static catalog (the
/// no-program-loaded form, which is what `tests/catalog_bytecompat.rs` pins).
/// The output is the exact bytes the console writes (including the trailing
/// newline after each row and the final `]\n`).
///
/// (unlace) The closure yields a [`Cow`] rather than a `&'static str` because a
/// VALUED option's live value need not come from a fixed token set —
/// `dyldimage` reports a name. Every fixed-token arm still borrows, so
/// the emitted bytes are unchanged.
pub fn emit_catalog_json(live: impl Fn(&str) -> Option<Cow<'static, str>>) -> String {
    let mut out = String::new();
    out.push_str("[\n");
    let n = unlace_num_settables();
    for i in 0..n {
        let st = unlace_settable_by_index(i);
        emit_settable_json(&mut out, st, live(st.option).as_deref());
        if i + 1 < n {
            out.push(',');
        }
        out.push('\n');
    }
    out.push_str("]\n");
    out
}

/// The `###` heading of an option's section, inline code included.
fn option_heading(st: &UnlaceSettable) -> String {
    format!(
        "`{}` -- {}, default `{}`{}",
        st.option,
        st.values.replace('|', " | "),
        st.shipped,
        if st.destructive {
            " (destructive opt-in)"
        } else {
            ""
        },
    )
}

/// GitHub's anchor for a heading: the rendered text (code backticks and
/// raw `<...>` spans gone) lowercased, punctuation dropped, spaces to hyphens.
fn github_anchor(markdown_heading: &str) -> String {
    let mut text = String::new();
    let mut in_tag = false;
    for ch in markdown_heading.chars() {
        match ch {
            '<' => in_tag = true,
            '>' if in_tag => in_tag = false,
            _ if in_tag => {}
            '`' => {}
            _ => text.push(ch),
        }
    }
    text.chars()
        .filter_map(|ch| match ch {
            ' ' => Some('-'),
            'A'..='Z' | 'a'..='z' | '0'..='9' | '-' | '_' => Some(ch.to_ascii_lowercase()),
            _ => None,
        })
        .collect()
}

fn option_anchor(st: &UnlaceSettable) -> String {
    github_anchor(&option_heading(st))
}

/// Render the whole settable catalog as the tier-grouped Markdown document
/// committed at `docs/options.md` (regenerate: `unlace catalog --markdown >
/// docs/options.md`; freshness fenced by `tests/options_md_fresh.rs`).
///
/// Built straight from [`SETTABLE_TABLE`] (no live values -- the document
/// describes the shipped defaults). Sections run transform -> analysis ->
/// core so the control surface leads; a generated symptom index maps
/// output-shaped phrases to options.
pub fn emit_catalog_markdown() -> String {
    let mut out = String::new();
    out.push_str("# unlace option catalog\n\n");
    out.push_str(
        "**Generated** by `unlace catalog --markdown` from `settableTable` in \
         `crates/unlace-decomp/phases.toml` -- do not edit by hand; \
         edit the registry row and regenerate.\n\n",
    );
    out.push_str(
        "Set any option per run: `unlace decompile <bin> <fn> --option <name> <value>` \
         (repeatable), `unlace decompile-all <bin> --option <name> <value>`, or the \
         console `option <name> <value>`. Defaults are the shipped values; what a \
         default does is described in its row below. The algorithms behind these \
         options are described in `docs/spec/`.\n\n",
    );
    out.push_str("Three tiers:\n\n");
    out.push_str(
        "- **Toggleable transforms** -- restructure, duplicate, remove, or insert \
         code; near-always better on the right source shape and wrong on the wrong \
         one. **This is the on/off control surface.**\n",
    );
    out.push_str(
        "- **Analysis & loader passes** -- what gets discovered/decoded/named \
         before decompilation.\n",
    );
    out.push_str(
        "- **Core rendering defaults** -- near-always-better rendering/naming/\
         peepholes; part of the decompiler, not the control surface. Flip only for \
         upstream byte-parity or unusual consumers.\n\n",
    );

    // ---- symptom index ------------------------------------------------------
    out.push_str("## Symptom index\n\n");
    out.push_str("| If the output shows... | Try |\n|---|---|\n");
    for tier in ["transform", "analysis", "core"] {
        for i in 0..unlace_num_settables() {
            let st = unlace_settable_by_index(i);
            if st.tier != tier {
                continue;
            }
            for phrase in st.symptoms.split('|') {
                if phrase.is_empty() {
                    continue;
                }
                out.push_str("| ");
                out.push_str(phrase);
                out.push_str(" | [`");
                out.push_str(st.option);
                out.push_str("`](#");
                out.push_str(&option_anchor(st));
                out.push_str(") |\n");
            }
        }
    }
    out.push('\n');

    // ---- per-tier sections --------------------------------------------------
    let sections = [
        (
            "transform",
            "## Toggleable transforms",
            "The control surface: each of these can make output worse on the wrong source shape, so each stays flippable.",
        ),
        (
            "analysis",
            "## Analysis & loader passes",
            "Program-prep enablement: what is discovered, decoded, and named before any function is decompiled.",
        ),
        (
            "core",
            "## Core rendering defaults",
            "Part of the decompiler; not the control surface. Flip only to reproduce upstream Ghidra output byte-for-byte or for unusual downstream consumers.",
        ),
    ];
    for (tier, heading, blurb) in sections {
        out.push_str(heading);
        out.push_str("\n\n");
        out.push_str(blurb);
        out.push_str("\n\n");
        for i in 0..unlace_num_settables() {
            let st = unlace_settable_by_index(i);
            if st.tier != tier {
                continue;
            }
            out.push_str("### ");
            out.push_str(&option_heading(st));
            out.push_str("\n\n");
            out.push_str("- **Symptoms:** ");
            out.push_str(&st.symptoms.replace('|', "; "));
            out.push_str(".\n- **What it does:** ");
            out.push_str(st.summary);
            out.push_str("\n- **When to flip:** ");
            out.push_str(st.use_when);
            out.push_str("\n- **Where / provenance:** ");
            out.push_str(st.phase.code());
            out.push('/');
            out.push_str(st.subphase);
            out.push_str(" \u{b7} ");
            out.push_str(st.source_decompiler);
            out.push_str(" \u{b7} ");
            out.push_str(st.change_kind);
            if !st.issue.is_empty() {
                out.push_str(" \u{b7} ");
                out.push_str(st.issue);
            }
            out.push('\n');
            if !st.example.is_empty() {
                out.push_str("- **Example:** `");
                out.push_str(st.example);
                out.push_str("`\n");
            }
            out.push('\n');
        }
    }
    out.push_str(
        "## Programmatic use\n\n```bash\n# discover (machine-readable; includes tier + symptoms):\nunlace catalog --json\n\n# transforms only:\nunlace catalog --tier transform\n\n# decompile with an option flipped (repeatable):\nunlace decompile ./a.out main --option gotoreduce off\nunlace decompile ./sparc.elf main --option returnpair single\n```\n",
    )
;
    out
}

/// Emit a single settable's catalog JSON — byte-for-byte port of
/// `IfcUnlacePhaseCatalog::execute`'s one-argument form (`phase catalog <option>`).
///
/// Returns `None` if the option is unknown (the C++ throws an
/// `IfaceExecutionError`); the row is followed by a single newline.
pub fn emit_catalog_json_one(option: &str, live: Option<&str>) -> Option<String> {
    let st = lookup_settable(option)?;
    let mut out = String::new();
    emit_settable_json(&mut out, st, live);
    out.push('\n');
    Some(out)
}

