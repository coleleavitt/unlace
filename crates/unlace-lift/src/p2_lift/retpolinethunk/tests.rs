use super::*;

fn reader(bytes: &[u8]) -> impl Fn(u64) -> Option<u8> + '_ {
    move |i| bytes.get(i as usize).copied()
}

#[test]
fn clang_and_gcc_thunks_name_their_register() {
    let clang = [
        0xe8, 0x0b, 0, 0, 0, 0xf3, 0x90, 0x0f, 0xae, 0xe8, 0xeb, 0xf9, 0x0f, 0x1f, 0x40, 0x00,
        0x4c, 0x89, 0x1c, 0x24, 0xc3,
    ];
    assert_eq!(thunk_register(reader(&clang)), Some("r11"));
    let gcc = [
        0xe8, 0x07, 0, 0, 0, 0xf3, 0x90, 0x0f, 0xae, 0xe8, 0xeb, 0xf9, 0x48, 0x89, 0x04, 0x24, 0xc3,
    ];
    assert_eq!(thunk_register(reader(&gcc)), Some("rax"));
    let i386 = [
        0xe8, 0x07, 0, 0, 0, 0xf3, 0x90, 0x0f, 0xae, 0xe8, 0xeb, 0xf9, 0x89, 0x0c, 0x24, 0xc3,
    ];
    assert_eq!(thunk_register(reader(&i386)), Some("ecx"));
    let plain_call = [
        0xe8, 0x07, 0, 0, 0, 0x90, 0x90, 0x90, 0x90, 0x90, 0x90, 0x90, 0x48, 0x89, 0x04, 0x24, 0xc3,
    ];
    assert_eq!(thunk_register(reader(&plain_call)), None);
}
