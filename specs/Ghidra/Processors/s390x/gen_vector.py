def extract(dump):
    d = json.load(open(dump))

    def ops(dag):
        res = []
        for t, v in dag["args"]:
            if isinstance(t, dict) and t.get("kind") == "def":
                res.append([t["def"], v])
            elif isinstance(t, dict) and t.get("kind") == "dag":
                res.append([t["operator"]["def"], [x[1] for x in t["args"]]])
        return res
    out = []
    for n in d["!instanceof"]["Instruction"]:
        r = d[n]
        if r.get("Namespace") != "SystemZ" or r.get("isCodeGenOnly") or r.get("isPseudo") or r.get("isAsmParserOnly"):
            continue
        inst = r.get("Inst")
        if not inst or len(inst) != 48 or not all(isinstance(inst[i], int) for i in range(40, 48)):
            continue
        if sum(inst[i] << (i - 40) for i in range(40, 48)) not in (0xE6, 0xE7):
            continue
        bits = [b if isinstance(b, int) else [b["var"], b["index"]] for b in inst]
        out.append({"name": n, "asm": r["AsmString"], "outs": ops(r["OutOperandList"]), "ins": ops(r["InOperandList"]),
                    "bits": bits, "defs": [x["def"] for x in r.get("Defs", [])], "constraints": r.get("Constraints", ""),
                    "load": r.get("mayLoad"), "store": r.get("mayStore")})
    out.sort(key=lambda x: x["name"])
    json.dump(out, open(os.path.join(HERE, "vector_insts.json"), "w"), indent=0)


