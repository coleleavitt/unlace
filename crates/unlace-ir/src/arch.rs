//! Target architecture identifier.

use std::fmt;

/// Target architecture identifier, derived from the ELF `e_machine` field
/// (or equivalent in PE/Mach-O).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub enum ArchId {
    X86,
    X86_64,
    Arm,
    AArch64,
    RiscV64,
    Mips,
    Mips64,
    Ppc,
    Ppc64,
    V850,
    Arc,
    TriCore,
    Wasm,
    Ebpf,
    Sbpf,
    Avr,
    Msp430,
    AmdGpu,
    Stm8,
    Z80,
    RxRenesas,
    Agx,
    Sparc,
    M68k,
    SuperH,
    NvidiaSass,
    Xtensa,
    Mos6502,
    I8051,
    Hexagon,
    Pic16,
    Sharc,
    SharcBlackfin,
    TiC6x,
    TiC28x,
    Evm,
    NvSass,
    SpirV,
    AppleAgx,
    M6502,
    Unknown(u16),
}

impl fmt::Display for ArchId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::X86 => f.write_str("x86"),
            Self::X86_64 => f.write_str("x86_64"),
            Self::Arm => f.write_str("arm"),
            Self::AArch64 => f.write_str("aarch64"),
            Self::RiscV64 => f.write_str("riscv64"),
            Self::Mips => f.write_str("mips"),
            Self::Mips64 => f.write_str("mips64"),
            Self::Ppc => f.write_str("ppc"),
            Self::Ppc64 => f.write_str("ppc64"),
            Self::V850 => f.write_str("v850"),
            Self::Arc => f.write_str("arc"),
            Self::TriCore => f.write_str("tricore"),
            Self::Wasm => f.write_str("wasm"),
            Self::Ebpf => f.write_str("ebpf"),
            Self::Sbpf => f.write_str("sbpf"),
            Self::Avr => f.write_str("avr"),
            Self::Msp430 => f.write_str("msp430"),
            Self::AmdGpu => f.write_str("amdgpu"),
            Self::Stm8 => f.write_str("stm8"),
            Self::Z80 => f.write_str("z80"),
            Self::RxRenesas => f.write_str("rx"),
            Self::Agx => f.write_str("agx"),
            Self::Sparc => f.write_str("sparc"),
            Self::M68k => f.write_str("m68k"),
            Self::SuperH => f.write_str("superh"),
            Self::NvidiaSass => f.write_str("nvidia-sass"),
            Self::Xtensa => f.write_str("xtensa"),
            Self::Mos6502 => f.write_str("6502"),
            Self::I8051 => f.write_str("i8051"),
            Self::Hexagon => f.write_str("hexagon"),
            Self::Pic16 => f.write_str("pic16"),
            Self::Sharc => f.write_str("sharc"),
            Self::SharcBlackfin => f.write_str("sharc-blackfin"),
            Self::TiC6x => f.write_str("tic6x"),
            Self::TiC28x => f.write_str("ti-c28x"),
            Self::Evm => f.write_str("evm"),
            Self::NvSass => f.write_str("nvsass"),
            Self::SpirV => f.write_str("spirv"),
            Self::AppleAgx => f.write_str("appleagx"),
            Self::M6502 => f.write_str("m6502"),
            Self::Unknown(id) => write!(f, "unknown({id:#x})"),
        }
    }
}
