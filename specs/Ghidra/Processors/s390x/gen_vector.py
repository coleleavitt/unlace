fields = {}          # name -> "name=(lo,hi)[ signed]"
subs = {}            # subtable name -> text
pcodeops = set()
cons = []


def field(lo, hi, signed=False):
    n = f"c_x{'s' if signed else ''}{lo}_{hi}"
    fields[n] = f"{n}=({lo},{hi})" + (" signed" if signed else "")
    return n


VK = {"VR128": "Q", "VF128": "Q", "VR64": "D", "VR32": "S"}
VNAMES = {"Q": ([f"v{i}" for i in range(16)], [f"v{i}" for i in range(16, 32)]),
          "D": ([f"f{i}" for i in range(16)], [f"f{i}" for i in range(16, 32)]),
          "S": ([f"f{i}s" for i in range(16)], [f"f{i}s" for i in range(16, 32)])}
attaches = {}        # (kind, part) -> [field names]


def vreg(kind, lo, rx):
    name = f"VR{kind}_{lo}_{rx}"
    if name not in subs:
        fl, fh = f"c_v{kind.lower()}l{lo}", f"c_v{kind.lower()}h{lo}"
        fields[fl] = f"{fl}=({lo},{lo + 3})"
        fields[fh] = f"{fh}=({lo},{lo + 3})"
        attaches.setdefault((kind, 0), set()).add(fl)
        attaches.setdefault((kind, 1), set()).add(fh)
        x = field(rx, rx)
        subs[name] = (f"{name}: {fl} is {fl} & {x}=0 {{ export {fl}; }}\n"
                      f"{name}: {fh} is {fh} & {x}=1 {{ export {fh}; }}\n")
    return name


GRN = {36: "A", 32: "B", 28: "C", 12: "G"}
SIZES = {"b": 1, "h": 2, "f": 4, "g": 8, "q": 16}


def runs(positions):
    """[(lo, hi)] of the sorted bit positions."""
    out, start = [], None
    for p in sorted(positions):
        if start is None:
            start = prev = p
        elif p == prev + 1:
            prev = p
        else:
            out.append((start, prev)); start = prev = p
    if start is not None:
        out.append((start, prev))
    return out


SHV = ("SHV: c_d12(c_rC) is c_rC & c_d12 { local n:8 = c_rC + c_d12; export n; }\n"
       "SHV: c_d12 is c_nC=0 & c_d12 { export *[const]:8 c_d12; }\n")
VBD = ("VBD_{V}: c_d12({V},c_rC) is c_rC & c_d12 & {V} {{ local ix:16 = {V}; export ix; }}\n")


def operands(ins):
    """{var: (kind, symbol)} and the pattern pieces of one instruction."""
    varbits = {}
    for pos, b in enumerate(ins["bits"]):
        if isinstance(b, list):
            varbits.setdefault(b[0], {})[b[1]] = pos
    ty = {}
    for t, v in ins["outs"] + ins["ins"]:
        if isinstance(v, list):
            ty[tuple(v)] = t
        else:
            ty[v] = t
    tied = {}
    for m in re.finditer(r"\$(\w+) = \$(\w+)", ins["constraints"]):
        tied[m.group(2)] = m.group(1)
    sym, pat, kinds = {}, [], {}
    for key, t in ty.items():
        if isinstance(key, tuple):
            if t in ("bdxaddr12only",):
                sym[key] = "XBDE6"; pat.append("XBDE6")
            elif t in ("bdaddr12only",):
                sym[key] = "BDA6"; pat.append("BDA6")
            elif t == "shift12only":
                subs["SHV"] = SHV; sym[key] = "SHV"; pat.append("SHV")
            elif t == "bdvaddr12only":
                b, d, v = key
                vb = varbits[v]
                vr = vreg("Q", vb[0], vb[4])
                sub = f"VBD_{vr}"
                subs[sub] = VBD.format(V=vr).replace(f"VBD_{vr}", sub)
                sym[key] = sub; pat.append(sub)
            else:
                raise KeyError(t)
            kinds[key] = t
            continue
        v = key
        if v in tied:
            continue
        vb = varbits.get(v)
        if t in VK:
            s = vreg(VK[t], vb[0], vb[4]); sym[v] = s; pat.append(s); kinds[v] = VK[t]
        elif t in ("GR64", "GR32"):
            lo = vb[0]
            s = f"c_r{'l' if t == 'GR32' else ''}{GRN[lo]}"; sym[v] = s; pat.append(s); kinds[v] = t
        elif t.startswith("imm"):
            lo, hi = min(vb.values()), max(vb.values())
            s = field(lo, hi, "sx" in t); sym[v] = s; pat.append(s); kinds[v] = "imm"
        else:
            raise KeyError(t)
    for a, b in tied.items():
        sym[a] = sym[b]
    fixed = [p for p, b in enumerate(ins["bits"]) if isinstance(b, int) and 8 <= p < 40]
    for lo, hi in runs(fixed):
        val = sum(ins["bits"][p] << (p - lo) for p in range(lo, hi + 1))
        pat.append(f"{field(lo, hi)}={val}")
    for p in range(8, 12):           # RXB bits that carry no register stay zero
        if ins["bits"][p] == 0 and f"c_x{p}_{p}" not in " ".join(pat):
            pass
    return sym, pat, kinds, tied


# ---------------------------------------------------------------- p-code helpers
class B:
    def __init__(s):
        s.lines, s.n = [], 0

    def t(s, size, expr):
        s.n += 1
        nm = f"t{s.n}"
        s.lines.append(f"local {nm}:{size} = {expr};")
        return nm

    def l(s, text):
        s.lines.append(text)

    def text(s):
        return " ".join(s.lines)


def lane(b, v, i, e):
    off = 16 - e * (i + 1)
    return b.t(e, f"{v}:{e}" if off == 0 else f"{v}({off})")


def lanes_of(b, v, e):
    return [lane(b, v, i, e) for i in range(16 // e)]


def combine(b, parts, e):
    if e == 16:
        return parts[0]
    n = len(parts)
    terms = []
    for i, p in enumerate(parts):
        sh = 8 * e * (n - 1 - i)
        terms.append(f"(zext({p}) << {sh})" if sh else f"zext({p})")
    return b.t(16, " | ".join(terms))


def lanewise(b, e, srcs, fn):
    ls = [lanes_of(b, b.t(16, s), e) for s in srcs]
    res = [b.t(e, fn(*[l[i] for l in ls])) for i in range(16 // e)]
    return combine(b, res, e)


def bswap(b, x, e):
    if e == 1:
        return x
    bs = [b.t(1, f"{x}:1" if k == 0 else f"{x}({k})") for k in range(e)]
    return b.t(e, " | ".join(f"(zext({bs[k]}) << {8 * (e - 1 - k)})" if e - 1 - k else f"zext({bs[k]})" for k in range(e)))


def ccmask(b, res):
    """CC 0 when every element is true, 3 when none is, 1 when mixed."""
    inv = b.t(16, f"~{res}")
    a = b.t(1, f"{inv} == 0")
    z = b.t(1, f"{res} == 0")
    b.l(f"CC0 = {a}; CC1 = !{a} && !{z}; CC2 = 0; CC3 = {z}; ccAux();")


ONE = {4: "0x3f800000", 8: "0x3ff0000000000000"}

# ---------------------------------------------------------------- semantics
def sem(ins, mn, sym, kinds):
    """Exact p-code for the families modelled, else None."""
    b = B()
    cache = {}

    def S(v):
        if kinds.get(v) == "imm":
            if v not in cache:
                cache[v] = b.t(8, sym[v])
            return cache[v]
        return sym[v]
    m = re.fullmatch(r"v(a|s|ml|mx|mn|mxl|mnl|avg|avgl)(b|h|f|g|q|hw)", mn)
    if m and m.group(1) in ("a", "s", "ml", "mx", "mn", "mxl", "mnl"):
        e = SIZES[{"hw": "h"}.get(m.group(2), m.group(2))]
        op = m.group(1)
        if op == "ml" and e == 16:
            return None
        f = {"a": lambda x, y: f"{x} + {y}", "s": lambda x, y: f"{x} - {y}", "ml": lambda x, y: f"{x} * {y}",
             "mx": lambda x, y: f"({x} * zext({x} s>= {y})) + ({y} * zext({x} s< {y}))",
             "mn": lambda x, y: f"({x} * zext({x} s<= {y})) + ({y} * zext({x} s> {y}))",
             "mxl": lambda x, y: f"({x} * zext({x} >= {y})) + ({y} * zext({x} < {y}))",
             "mnl": lambda x, y: f"({x} * zext({x} <= {y})) + ({y} * zext({x} > {y}))"}[op]
        r = lanewise(b, e, [S("V2"), S("V3")], f)
        b.l(f"{S('V1')} = {r};")
        return b.text()
    m = re.fullmatch(r"v(lc|lp)(b|h|f|g)", mn)
    if m:
        e = SIZES[m.group(2)]
        f = (lambda x: f"0 - {x}") if m.group(1) == "lc" else (lambda x: f"({x} ^ ({x} s>> {8 * e - 1})) - ({x} s>> {8 * e - 1})")
        b.l(f"{S('V1')} = {lanewise(b, e, [S('V2')], f)};")
        return b.text()
    m = re.fullmatch(r"v(ceq|ch|chl)(b|h|f|g)(s?)", mn)
    if m:
        e = SIZES[m.group(2)]
        o = {"ceq": "==", "ch": "s>", "chl": ">"}[m.group(1)]
        r = lanewise(b, e, [S("V2"), S("V3")], lambda x, y: f"0 - zext({x} {o} {y})")
        b.l(f"{S('V1')} = {r};")
        if m.group(3):
            ccmask(b, r)
        return b.text()
    logic = {"vn": "{a} & {c}", "vnc": "{a} & ~{c}", "vo": "{a} | {c}", "vx": "{a} ^ {c}", "vnn": "~({a} & {c})",
             "vno": "~({a} | {c})", "vnx": "~({a} ^ {c})", "voc": "{a} | ~{c}"}
    if mn in logic:
        a, c = b.t(16, S("V2")), b.t(16, S("V3"))
        b.l(f"{S('V1')} = {logic[mn].format(a=a, c=c)};")
        return b.text()
    if mn == "vsel":
        a, c, d = b.t(16, S("V2")), b.t(16, S("V3")), b.t(16, S("V4"))
        b.l(f"{S('V1')} = ({a} & {d}) | ({c} & ~{d});")
        return b.text()
    if mn == "vlr":
        b.l(f"{S('V1')} = {S('V2')};")
        return b.text()
    if mn == "vlvgp":
        b.l(f"{S('V1')} = (zext({S('R2')}) << 64) | zext({S('R3')});")
        return b.text()
    if mn == "vgbm":
        bits_ = [b.t(1, b.t(8, f"({S('I2')} >> {15 - i}) & 1") + ":1") for i in range(16)]
        parts = [b.t(1, f"0 - {x}") for x in bits_]
        b.l(f"{S('V1')} = {combine(b, parts, 1)};")
        return b.text()
    m = re.fullmatch(r"vrepi(b|h|f|g)", mn)
    if m:
        e = SIZES[m.group(1)]
        x = b.t(2, f"{S('I2')}:2")
        el = b.t(e, f"sext({x})" if e > 2 else f"{x}:{e}")
        b.l(f"{S('V1')} = {combine(b, [el] * (16 // e), e)};")
        return b.text()
    m = re.fullmatch(r"vrep(b|h|f|g)", mn)
    if m:
        e = SIZES[m.group(1)]; n = 16 // e
        k = b.t(8, f"({n - 1} - ({S('I2')} & {n - 1})) * {8 * e}")
        x = b.t(16, f"{S('V3')} >> {k}")
        el = b.t(e, f"{x}:{e}")
        b.l(f"{S('V1')} = {combine(b, [el] * n, e)};")
        return b.text()
    m = re.fullmatch(r"vgm(b|h|f|g)", mn)
    if m:
        e = SIZES[m.group(1)]; bits = 8 * e; ones = (1 << bits) - 1
        st = b.t(e, f"{S('I2')}:{e} & {bits - 1}"); en = b.t(e, f"{S('I3')}:{e} & {bits - 1}")
        mh = b.t(e, f"0x{ones:x} >> {st}"); ml = b.t(e, f"0x{ones:x} << ({bits - 1} - {en})")
        el = b.t(e, f"({mh} & {ml}) | ((0 - zext({st} > {en})) & ({mh} | {ml}))")
        b.l(f"{S('V1')} = {combine(b, [el] * (16 // e), e)};")
        return b.text()
    m = re.fullmatch(r"vlvg(b|h|f|g)", mn)
    if m:
        e = SIZES[m.group(1)]; n = 16 // e
        k = b.t(8, f"({n - 1} - ({S(('B2', 'D2'))} & {n - 1})) * {8 * e}")
        sh = b.t(16, f"zext({k})")
        mk = b.t(16, f"0x{(1 << 8 * e) - 1:x} << {sh}")
        r3 = b.t(e, f"{S('R3')}:{e}")
        val = b.t(16, f"zext({r3}) << {sh}")
        b.l(f"{S('V1')} = ({S('V1')} & ~{mk}) | {val};")
        return b.text()
    m = re.fullmatch(r"vlgv(b|h|f|g)", mn)
    if m:
        e = SIZES[m.group(1)]; n = 16 // e
        k = b.t(8, f"({n - 1} - ({S(('B2', 'D2'))} & {n - 1})) * {8 * e}")
        x = b.t(16, f"{S('V3')} >> {k}")
        y = b.t(e, f"{x}:{e}")
        b.l(f"{S('R1')} = zext({y});")
        return b.text()
    m = re.fullmatch(r"vmr(h|l)(b|h|f|g)", mn)
    if m:
        e = SIZES[m.group(2)]; n = 16 // e
        a = lanes_of(b, b.t(16, S("V2")), e); c = lanes_of(b, b.t(16, S("V3")), e)
        base = 0 if m.group(1) == "h" else n // 2
        res = []
        for k in range(n // 2):
            res += [a[base + k], c[base + k]]
        b.l(f"{S('V1')} = {combine(b, res, e)};")
        return b.text()
    if mn == "vpdi":
        a, c = b.t(16, S("V2")), b.t(16, S("V3"))
        ah, al, ch, cl = b.t(8, f"{a}(8)"), b.t(8, f"{a}:8"), b.t(8, f"{c}(8)"), b.t(8, f"{c}:8")
        d0 = b.t(8, f"({ah} * zext(({S('M4')} & 4) == 0)) + ({al} * zext(({S('M4')} & 4) != 0))")
        d1 = b.t(8, f"({ch} * zext(({S('M4')} & 1) == 0)) + ({cl} * zext(({S('M4')} & 1) != 0))")
        b.l(f"{S('V1')} = (zext({d0}) << 64) | zext({d1});")
        return b.text()
    if mn == "vsldb":
        c = b.t(32, f"(zext({S('V2')}) << 128) | zext({S('V3')})")
        k = b.t(32, f"zext({S('I4')} & 15) * 8")
        t = b.t(32, f"{c} << {k}")
        b.l(f"{S('V1')} = {t}(16);")
        return b.text()
    m = re.fullmatch(r"vs(l|rl|ra)b", mn)
    if m:
        a = b.t(16, S("V2")); c = b.t(16, S("V3"))
        by = b.t(1, f"{c}(8)")
        cnt = b.t(16, f"zext(({by} >> 3) & 15) * 8")
        o = {"l": "<<", "rl": ">>", "ra": "s>>"}[m.group(1)]
        b.l(f"{S('V1')} = {a} {o} {cnt};")
        return b.text()
    m = re.fullmatch(r"vs(l|rl|ra)", mn)
    if m:
        # each byte shifts by bits 5-7 of the matching byte of V3, taking bits from its neighbour
        a = lanes_of(b, b.t(16, S("V2")), 1); c = lanes_of(b, b.t(16, S("V3")), 1)
        res = []
        for i in range(16):
            s = b.t(1, f"{c[i]} & 7")
            if m.group(1) == "l":
                nxt = a[i + 1] if i < 15 else "0:1"
                res.append(b.t(1, f"({a[i]} << {s}) | ({nxt} >> (8 - {s}))"))
            else:
                prev = a[i - 1] if i else ("0:1" if m.group(1) == "rl" else b.t(1, f"{a[0]} s>> 7"))
                res.append(b.t(1, f"({a[i]} >> {s}) | ({prev} << (8 - {s}))"))
        b.l(f"{S('V1')} = {combine(b, res, 1)};")
        return b.text()
    m = re.fullmatch(r"v(esl|esrl|esra|erll)(v?)(b|h|f|g)", mn)
    if m:
        e = SIZES[m.group(3)]; bits = 8 * e
        if m.group(2):
            srcs = [S("V2"), S("V3")]
            f2 = lambda x, y: (x, f"({y} & {bits - 1})")
        else:
            cnt = b.t(e, b.t(8, f"{S(('B2', 'D2'))} & {bits - 1}") + f":{e}")
            srcs = [S("V3")]
            f2 = lambda x, y=None: (x, cnt)
        def fn(*xs):
            x, k = f2(*xs)
            if m.group(1) == "esl": return f"{x} << {k}"
            if m.group(1) == "esrl": return f"{x} >> {k}"
            if m.group(1) == "esra": return f"{x} s>> {k}"
            return f"({x} << {k}) | ({x} >> (({bits} - {k}) & {bits - 1}))"
        b.l(f"{S('V1')} = {lanewise(b, e, srcs, fn)};")
        return b.text()
    m = re.fullmatch(r"vup(h|lh|l|ll)(b|h|hw|f)", mn)
    if m:
        e = SIZES[{"hw": "h"}.get(m.group(2), m.group(2))]; n = 16 // e
        a = lanes_of(b, b.t(16, S("V2")), e)
        half = a[:n // 2] if m.group(1) in ("h", "lh") else a[n // 2:]
        ext = "sext" if m.group(1) in ("h", "l") else "zext"
        res = [b.t(2 * e, f"{ext}({x})") for x in half]
        b.l(f"{S('V1')} = {combine(b, res, 2 * e)};")
        return b.text()
    m = re.fullmatch(r"vpk(h|f|g)", mn)
    if m:
        e = SIZES[m.group(1)]
        a = lanes_of(b, b.t(16, S("V2")), e) + lanes_of(b, b.t(16, S("V3")), e)
        res = [b.t(e // 2, f"{x}:{e // 2}") for x in a]
        b.l(f"{S('V1')} = {combine(b, res, e // 2)};")
        return b.text()
    if mn in ("vzero", "vone"):
        z = b.t(16, "0")
        b.l(f"{S('V1')} = {'~' if mn == 'vone' else ''}{z};")
        return b.text()
    m = re.fullmatch(r"v(l|st)(er|br)(h|f|g|q)", mn)
    if m:
        e = SIZES[m.group(3)]
        src = b.t(16, "*:16 XBDE6") if m.group(1) == "l" else b.t(16, S("V1"))
        ls = lanes_of(b, src, e)
        if m.group(2) == "er":
            if e == 16:
                return None
            ls = ls[::-1]
        else:
            ls = [bswap(b, x, e) for x in ls]
        r = combine(b, ls, e)
        b.l(f"{S('V1')} = {r};" if m.group(1) == "l" else f"*:16 XBDE6 = {r};")
        return b.text()
    m = re.fullmatch(r"vlbrrep(h|f|g)", mn)
    if m:
        e = SIZES[m.group(1)]
        el = bswap(b, b.t(e, f"*:{e} XBDE6"), e)
        b.l(f"{S('V1')} = {combine(b, [el] * (16 // e), e)};")
        return b.text()
    m = re.fullmatch(r"v(lebr|stebr)(h|f|g)", mn)
    if m:
        e = SIZES[m.group(2)]; n = 16 // e
        k = b.t(8, f"({n - 1} - ({S('M3')} & {n - 1})) * {8 * e}")
        sh = b.t(16, f"zext({k})")
        if m.group(1) == "stebr":
            x = b.t(16, f"{S('V1')} >> {sh}")
            b.l(f"*:{e} XBDE6 = {bswap(b, b.t(e, f'{x}:{e}'), e)};")
            return b.text()
        val = bswap(b, b.t(e, f"*:{e} XBDE6"), e)
        mk = b.t(16, f"0x{(1 << 8 * e) - 1:x} << {sh}")
        b.l(f"{S('V1')} = ({S('V1')} & ~{mk}) | (zext({val}) << {sh});")
        return b.text()
    m = re.fullmatch(r"vllebrz(h|f|g|e)", mn)
    if m:
        e = {"h": 2, "f": 4, "g": 8, "e": 4}[m.group(1)]
        el = bswap(b, b.t(e, f"*:{e} XBDE6"), e)
        b.l(f"{S('V1')} = zext({el}) << {96 if m.group(1) == 'e' else 64};")
        return b.text()
    # loads and stores
    if mn == "vl":
        b.l(f"{S('V1')} = *:16 XBDE6;")
        return b.text()
    if mn == "vst":
        b.l(f"*:16 XBDE6 = {S('V1')};")
        return b.text()
    m = re.fullmatch(r"vlrep(b|h|f|g)", mn)
    if m:
        e = SIZES[m.group(1)]
        el = b.t(e, f"*:{e} XBDE6")
        b.l(f"{S('V1')} = {combine(b, [el] * (16 // e), e)};")
        return b.text()
    m = re.fullmatch(r"v(le|ste|lei)(b|h|f|g)", mn)
    if m:
        e = SIZES[m.group(2)]; n = 16 // e
        k = b.t(8, f"({n - 1} - ({S('M3')} & {n - 1})) * {8 * e}")
        sh = b.t(16, f"zext({k})")
        if m.group(1) == "ste":
            x = b.t(16, f"{S('V1')} >> {sh}")
            b.l(f"*:{e} XBDE6 = {x}:{e};")
            return b.text()
        if m.group(1) == "le":
            val = b.t(e, f"*:{e} XBDE6")
        else:
            i2 = b.t(2, f"{S('I2')}:2")
            val = b.t(e, f"sext({i2})") if e > 2 else b.t(e, f"{i2}:{e}") if e < 2 else i2
        mk = b.t(16, f"0x{(1 << 8 * e) - 1:x} << {sh}")
        b.l(f"{S('V1')} = ({S('V1')} & ~{mk}) | (zext({val}) << {sh});")
        return b.text()
    m = re.fullmatch(r"vllez(b|h|f|g|lf)", mn)
    if m:
        if m.group(1) == "lf":
            el = b.t(4, "*:4 XBDE6")
            b.l(f"{S('V1')} = zext({el}) << 96;")
        else:
            e = SIZES[m.group(1)]
            el = b.t(e, f"*:{e} XBDE6")
            b.l(f"{S('V1')} = zext({el}) << 64;")
        return b.text()
    return fpsem(mn, S, b)


MODE = {"v": None}
TRUNC_NEG = "local {r}:{e} = 0; if ({x} f< 0) goto <neg{u}>; {r} = floor({x}); goto <done{u}>; <neg{u}> {r} = ceil({x}); <done{u}>"


def rnd(b, x, e, mode):
    """x rounded to an integral value under BFP rounding mode M5 (1, 5, 6, 7), or None."""
    if mode == 1:
        # p-code ROUND is floor(x + 0.5); ties away from zero needs the sign split
        b.n += 1
        r = f"t{b.n}"
        b.l(f"local {r}:{e} = 0; if ({x} f< 0) goto <rn{b.n}>; {r} = round({x}); goto <rd{b.n}>; <rn{b.n}> {r} = f- round(f- {x}); <rd{b.n}>")
        return r
    if mode == 6:
        return b.t(e, f"ceil({x})")
    if mode == 7:
        return b.t(e, f"floor({x})")
    if mode == 5:
        b.n += 1
        r = f"t{b.n}"
        b.l(TRUNC_NEG.format(r=r, e=e, x=x, u=b.n))
        return r
    return None


def fpsem(mn, S, b):
    mode = MODE["v"]
    m = re.fullmatch(r"wfi(sb|db|xb)", mn)
    if m and mode is not None:
        e = {"sb": 4, "db": 8, "xb": 16}[m.group(1)]
        r = rnd(b, b.t(e, S("V2")), e, mode)
        if r is None:
            return None
        b.l(f"{S('V1')} = {r};")
        return b.text()
    m = re.fullmatch(r"vfi(sb|db)", mn)
    if m and mode in (6, 7):
        e = {"sb": 4, "db": 8}[m.group(1)]
        f = {6: "ceil", 7: "floor"}[mode]
        b.l(f"{S('V1')} = {lanewise(b, e, [S('V2')], lambda x: f'{f}({x})')};")
        return b.text()
    m = re.fullmatch(r"(v|w)c(dg|dlg|ef|elf)b", mn)
    if m:
        w, k = m.groups()
        e = 8 if k in ("dg", "dlg") else 4
        def cv(x):
            return f"int2float({x})" if k in ("dg", "ef") else f"int2float(zext({x}))"
        if w == "w":
            x = b.t(e, S("V2"))
            if k in ("dlg", "elf"):
                x = b.t(e + 1, f"zext({x})")
            b.l(f"{S('V1')} = int2float({x});")
        else:
            ls = lanes_of(b, b.t(16, S("V2")), e)
            res = []
            for x in ls:
                if k in ("dlg", "elf"):
                    x = b.t(e + 1, f"zext({x})")
                res.append(b.t(e, f"int2float({x})"))
            b.l(f"{S('V1')} = {combine(b, res, e)};")
        return b.text()
    m = re.fullmatch(r"(v|w)c(gd|lgd|fe|lfe)b", mn)
    if m and mode in (1, 5, 6, 7):
        w, k = m.groups()
        e = 8 if k in ("gd", "lgd") else 4
        def cv(x):
            r = rnd(b, x, e, mode)
            if k in ("lgd", "lfe"):
                u = b.t(e + 1, f"trunc({r})")
                return b.t(e, f"{u}:{e}")
            return b.t(e, f"trunc({r})")
        if w == "w":
            b.l(f"{S('V1')} = {cv(b.t(e, S('V2')))};")
        else:
            ls = lanes_of(b, b.t(16, S("V2")), e)
            b.l(f"{S('V1')} = {combine(b, [cv(x) for x in ls], e)};")
        return b.text()
    m = re.fullmatch(r"(v|w)ftci(sb|db|xb)", mn)
    if m:
        w, fm = m.groups()
        e, eb, fb = {"sb": (4, 8, 23), "db": (8, 11, 52), "xb": (16, 15, 112)}[fm]
        def cls(x):
            hi = b.t(8, f"{x}(8)") if e == 16 else (b.t(8, f"zext({x})") if e == 4 else x)
            top = 64 if e == 16 else 8 * e
            fbh = fb - 64 if e == 16 else fb
            sg = b.t(1, f"(({hi} >> {top - 1}) & 1) == 1")
            ex = b.t(8, f"({hi} >> {fbh}) & 0x{(1 << eb) - 1:x}")
            frx = b.t(8, f"{hi} & 0x{(1 << fbh) - 1:x}")
            if e == 16:
                lo = b.t(8, f"{x}:8")
                frx = b.t(8, f"{frx} | {lo}")
            q = b.t(1, f"(({hi} >> {fbh - 1}) & 1) == 1")
            em = b.t(1, f"{ex} == 0x{(1 << eb) - 1:x}")
            k = b.t(8, f"zext({sg}) + 2 * zext({ex} != 0 && !{em}) + 4 * zext({ex} == 0 && {frx} != 0) + 6 * zext({em} && {frx} == 0) + 8 * zext({em} && {frx} != 0 && {q}) + 10 * zext({em} && {frx} != 0 && !{q})")
            return b.t(1, b.t(8, f"({S('I3')} >> (11 - {k})) & 1") + ":1")
        if w == "w" or e == 16:
            bit = cls(b.t(e, S("V2")))
            b.l(f"{S('V1')} = 0 - zext({bit});")
            b.l(f"CC0 = {bit} != 0; CC1 = 0; CC2 = 0; CC3 = {bit} == 0; ccAux();")
        else:
            ls = lanes_of(b, b.t(16, S("V2")), e)
            res = [b.t(e, f"0 - zext({cls(x)})") for x in ls]
            r = combine(b, res, e)
            b.l(f"{S('V1')} = {r};")
            ccmask(b, r)
        return b.text()
    m = re.fullmatch(r"(v|w)f(a|s|m|d|sq)(sb|db|xb)", mn)
    if m:
        w, op, fm = m.groups()
        e = {"sb": 4, "db": 8, "xb": 16}[fm]
        o = {"a": "f+", "s": "f-", "m": "f*", "d": "f/"}.get(op)
        if w == "w" or e == 16:
            x = b.t(e, S("V2"))
            if op == "sq":
                b.l(f"{S('V1')} = sqrt({x});")
            else:
                y = b.t(e, S("V3"))
                b.l(f"{S('V1')} = {x} {o} {y};")
            return b.text()
        srcs = [S("V2")] if op == "sq" else [S("V2"), S("V3")]
        fn = (lambda x: f"sqrt({x})") if op == "sq" else (lambda x, y: f"{x} {o} {y}")
        b.l(f"{S('V1')} = {lanewise(b, e, srcs, fn)};")
        return b.text()
    m = re.fullmatch(r"(v|w)f(ma|ms|nma|nms)(sb|db|xb)", mn)
    if m:
        w, op, fm = m.groups()
        e = {"sb": 4, "db": 8, "xb": 16}[fm]
        def fn(x, y, z):
            r = f"({x} f* {y}) {'f+' if op in ('ma', 'nma') else 'f-'} {z}"
            return f"f- ({r})" if op.startswith("n") else r
        if w == "w" or e == 16:
            x, y, z = b.t(e, S("V2")), b.t(e, S("V3")), b.t(e, S("V4"))
            b.l(f"{S('V1')} = {fn(x, y, z)};")
        else:
            b.l(f"{S('V1')} = {lanewise(b, e, [S('V2'), S('V3'), S('V4')], fn)};")
        return b.text()
    m = re.fullmatch(r"(v|w)fl(c|n|p)(sb|db|xb)", mn)
    if m:
        w, op, fm = m.groups()
        e = {"sb": 4, "db": 8, "xb": 16}[fm]
        fn = {"c": lambda x: f"f- {x}", "n": lambda x: f"f- abs({x})", "p": lambda x: f"abs({x})"}[op]
        if w == "w" or e == 16:
            b.l(f"{S('V1')} = {fn(b.t(e, S('V2')))};")
        else:
            b.l(f"{S('V1')} = {lanewise(b, e, [S('V2')], fn)};")
        return b.text()
    m = re.fullmatch(r"wf(c|k)(sb|db|xb)", mn)
    if m:
        e = {"sb": 4, "db": 8, "xb": 16}[m.group(2)]
        x, y = b.t(e, S("V1")), b.t(e, S("V2"))
        b.l(f"ccCmpF({x}, {y});")
        return b.text()
    m = re.fullmatch(r"(v|w)fk?c(e|h|he)(sb|db|xb)(s?)", mn)
    if m:
        w, rel, fm, s = m.groups()
        e = {"sb": 4, "db": 8, "xb": 16}[fm]
        o = {"e": "f==", "h": "f>", "he": "f>="}[rel]
        if w == "w" or e == 16:
            x, y = b.t(e, S("V2")), b.t(e, S("V3"))
            r = b.t(e, f"0 - zext({x} {o} {y})")
            b.l(f"{S('V1')} = {r};")
            if s:
                b.l(f"CC0 = ({x} {o} {y}); CC1 = 0; CC2 = 0; CC3 = !CC0; ccAux();")
        else:
            r = lanewise(b, e, [S("V2"), S("V3")], lambda x, y: f"0 - zext({x} {o} {y})")
            b.l(f"{S('V1')} = {r};")
            if s:
                ccmask(b, r)
        return b.text()
    if mn in ("wldeb", "wflls"):
        b.l(f"{S('V1')} = float2float({b.t(4, S('V2') + '(4)' if False else S('V2'))});")
        return b.text()
    if mn == "wflrx":
        b.l(f"{S('V1')} = float2float({b.t(16, S('V2'))});")
        return b.text()
    if mn in ("wflld",):
        b.l(f"{S('V1')} = float2float({b.t(8, S('V2'))});")
        return b.text()
    if mn in ("vldeb", "vflls"):
        a = lanes_of(b, b.t(16, S("V2")), 4)
        res = [b.t(8, f"float2float({a[0]})"), b.t(8, f"float2float({a[2]})")]
        b.l(f"{S('V1')} = {combine(b, res, 8)};")
        return b.text()
    return None


