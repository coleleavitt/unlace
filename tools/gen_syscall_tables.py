#!/usr/bin/env python3
"""Generate crates/unlace-middle/src/substrate/syscalltables.rs.

Linux numbers come from the kernel's uapi headers (zig's copy: lib/libc/include/
{aarch64,arm}-linux-any/asm/unistd*.h), the x86-64 ones from the kernel's
arch/x86/entry/syscalls/syscall_64.tbl (the common and 64 ABIs), the Darwin BSD numbers
from the SYS_* macros of IDA 9.5's XNU type library and the Mach traps (with their
prototypes) from Hex-Rays ARM's svc_codes_t enum, both read out of the IDA 9.5 SQLite dumps.
Argument counts come from the i386 table in linuxsyscall.rs by name, from the prototype for
a Mach trap, and for an x86-64 name the i386 table lacks, from the kernel's declaration of
the table's entry point in include/linux/syscalls.h.

usage: gen_syscall_tables.py ZIG_LIBC_INCLUDE IDA_TILS_SQLITE HEXARM_SQLITE LINUX_SRC \
           > syscalltables.rs
"""
import re
import sqlite3
import sys

inc, tils, hexarm, kernel = sys.argv[1:5]

def arities():
    src = open("crates/unlace-lift/src/p2_lift/linuxsyscall.rs").read()
    return {m.group(2): int(m.group(3)) for m in re.finditer(r'\((\d+), "(\w+)", (\d+)\)', src)}

ARITY = arities()

def linux(path, base_expr):
    out = {}
    for line in open(path):
        m = re.match(r"#define __NR_(\w+)\s+\(?(?:__NR_SYSCALL_BASE \+ )?(\d+)\)?\s*$", line)
        if m:
            out[int(m.group(2))] = m.group(1)
    return sorted(out.items())

def x86_64_table(src):
    out = {}
    for line in open(f"{src}/arch/x86/entry/syscalls/syscall_64.tbl"):
        f = line.split()
        if len(f) >= 3 and not f[0].startswith("#") and f[1] in ("common", "64"):
            out[int(f[0])] = (f[2], f[3] if len(f) > 3 else None)
    return sorted(out.items())

def kernel_arities(src):
    out = {}
    text = open(f"{src}/include/linux/syscalls.h").read()
    for m in re.finditer(r"\basmlinkage\s+long\s+sys_(\w+)\s*\(([^)]*)\)", text):
        params = " ".join(m.group(2).split())
        n = 0 if params in ("", "void") else params.count(",") + 1
        out.setdefault(m.group(1), set()).add(n)
    return {name: n.pop() for name, n in out.items() if len(n) == 1}

def darwin():
    db = sqlite3.connect(f"file:{tils}?mode=ro", uri=True)
    til = db.execute("select id from tils where description like 'Darwin Kernel headers for ARM64 macOS (xnu-12377%'").fetchone()[0]
    out = {}
    for name, value in db.execute("select name, value from til_macros where til_id=? and name like 'SYS\\_%' escape '\\'", (til,)):
        if value and value.isdigit() and name != "SYS_MAXSYSCALL":
            out.setdefault(int(value), name[4:])
    return sorted(out.items())

def mach():
    db = sqlite3.connect(f"file:{hexarm}?mode=ro", uri=True)
    enum = db.execute("select text from strings where text like 'enum svc_codes_t%'").fetchone()[0]
    protos = [t for (t,) in db.execute("select text from strings where text like '%(%);' and (text like 'kern_return_t %' or text like 'mach_%' or text like 'uint64_t mach_%' or text like 'boolean_t swtch%')")]
    byname = {}
    for p in protos:
        m = re.match(r"[\w\s\*]+?\b(\w+)\s*\((.*)\);$", p)
        if m:
            args = m.group(2).strip()
            n = 0 if args in ("", "void") else args.count(",") + 1
            byname[m.group(1)] = n
    def key(s):
        return s.lower().strip("_").replace("_trap", "")
    keyed = {key(n): (n, a) for n, a in byname.items()}
    out = []
    for name, value in re.findall(r"(\w+) = (0x[0-9a-f]+)", enum):
        v = int(value, 16)
        if v >= 0x80000000 and v != 0x80000000:
            num = v - (1 << 32)
            k = key(name)
            fn, n = keyed.get(k, keyed.get("_" + k, (None, None)))
            if fn is None:
                fn = name.lower()
                n = None
            out.append((num, fn, n))
    return sorted(out)

def row(n, name, a):
    a = "None" if a is None else f"Some({a})"
    return f'    ({n}, "{name}", {a}),'

print("//! (unlace `syscallnames`) System-call number tables, generated by")
print("//! `tools/gen_syscall_tables.py`; do not edit by hand.")
print()
print("/// `(number, name, arguments)`: Linux AArch64 (asm-generic numbering).")
print("pub static LINUX_AARCH64: &[(i64, &str, Option<u8>)] = &[")
for n, name in linux(f"{inc}/aarch64-linux-any/asm/unistd_64.h", None):
    print(row(n, name, ARITY.get(name)))
print("];")
print()
print("/// Linux ARM EABI (`svc 0`, number in `r7`).")
print("pub static LINUX_ARM_EABI: &[(i64, &str, Option<u8>)] = &[")
for n, name in linux(f"{inc}/arm-linux-any/asm/unistd-eabi.h", None):
    print(row(n, name, ARITY.get(name)))
print("];")
print()
print("/// Darwin BSD system calls (`svc #0x80`, positive number in `x16`).")
print("pub static DARWIN_BSD: &[(i64, &str, Option<u8>)] = &[")
for n, name in darwin():
    print(row(n, name, ARITY.get(name)))
print("];")
print()
print("/// Darwin Mach traps (`svc #0x80`, negative number in `x16`).")
print("pub static MACH_TRAPS: &[(i64, &str, Option<u8>)] = &[")
for n, name, a in mach():
    print(row(n, name, a))
print("];")
print()
print("/// Linux x86-64 (`syscall`, number in `rax`).")
print("pub static LINUX_X86_64: &[(i64, &str, Option<u8>)] = &[")
DEFINED = kernel_arities(kernel)
for n, (name, entry) in x86_64_table(kernel):
    a = ARITY.get(name)
    if a is None and entry and entry.startswith("sys_"):
        a = DEFINED.get(entry[4:])
    print(row(n, name, a))
print("];")