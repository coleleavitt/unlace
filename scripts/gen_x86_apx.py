#!/usr/bin/env python3
"""Generate the Intel APX SLEIGH tables of the x86-64 language.

Writes two files next to ia.sinc in specs/Ghidra/Processors/x86/data/languages:

  apx_map4.sinc     the legacy instructions promoted to EVEX map 4 (NDD, NF, ZU,
                    CCMP/CTEST, CMOVcc/CFCMOVcc, SETcc.zu, PUSH2/POP2, ...),
                    written from the operation tables below;
  apx_rex2map1.sinc every 64-bit legacy-map-1 (0x0F xx) constructor of the x86
                    sources, re-keyed so that it decodes after a REX2 prefix with
                    M0=1 (REX2 replaces the 0x0F escape byte).

Source: Intel APX Architecture Specification 355828-009, sections 3.1.2-3.1.5.
Run from the repository root:  python3 scripts/gen_x86_apx.py
"""
import re
import sys
from pathlib import Path

LANG = Path(__file__).resolve().parent.parent / "specs/Ghidra/Processors/x86/data/languages"

HEADER = "# GENERATED by scripts/gen_x86_apx.py from the Intel APX Architecture Specification\n# (355828-009); edit the generator, not this file.\n"

SIZES = (1, 2, 4, 8)


def bits(s):
    return s * 8


def osz(s):
    return {1: "", 2: "opsize=0 & ", 4: "opsize=1 & ", 8: "opsize=2 & "}[s]


def mask(s):
    return "0x3f" if s == 8 else "0x1f"


def b(s):
    return bits(s)


def rm(s):
    return "rm%d" % b(s)


def reg(s):
    return "Reg%d" % b(s)


def ndd(s):
    return "apxNDD%d" % b(s)


def ndd_pat(s):
    return "apxNDD%d" % b(s) if s == 8 else "apxNDD%d & apxNDD64" % b(s)


def ndd_write(s, val):
    return "apxNDD64 = %s;" % val if s == 8 else "apxNDD64 = zext(%s);" % val


def rm_dest_pat(s):
    return " & check_rm32_dest ..." if s == 4 else ""


def rm_write(s, val):
    w = "%s = %s;" % (rm(s), val)
    return w + " build check_rm32_dest;" if s == 4 else w


def reg_dest_pat(s):
    return " & check_Reg32_dest ..." if s == 4 else ""


def reg_write(s, val):
    w = "%s = %s;" % (reg(s), val)
    return w + " build check_Reg32_dest;" if s == 4 else w


MAP4 = "$(APX_MAP4)"
VPP = "$(APX_PP_V) & "
NFSUF = {0: "", 1: '^".NF"'}


def hd(*parts):
    """Join pattern pieces with ' & ', dropping empty ones."""
    return " & ".join(p.strip().rstrip("&").strip() for p in parts if p and p.strip().rstrip("&").strip())


def ctor(mn, ops, pat, body):
    return ":%s %s is %s { %s }" % (mn, ops, pat, body) if ops else ":%s is %s { %s }" % (mn, pat, body)


# --- two-source ALU: (mnemonic, base opcode, /reg of 80/81/83, supports NF)
ALU = [("ADD", 0x00, 0, True), ("OR", 0x08, 1, True), ("ADC", 0x10, 2, False), ("SBB", 0x18, 3, False),
       ("AND", 0x20, 4, True), ("SUB", 0x28, 5, True), ("XOR", 0x30, 6, True)]


def alu_body(mn, nf):
    if nf:
        op = {"ADD": "+", "OR": "|", "AND": "&", "SUB": "-", "XOR": "^"}[mn]
        return "local res = a %s b;" % op
    return {
        "ADD": "addflags(a, b); local res = a + b; resultflags(res);",
        "OR": "local res = a | b; logicalflags(); resultflags(res);",
        "ADC": "local res = a; addCarryFlags(res, b); resultflags(res);",
        "SBB": "local res = a; subCarryFlags(res, b); resultflags(res);",
        "AND": "local res = a & b; logicalflags(); resultflags(res);",
        "SUB": "subflags(a, b); local res = a - b; resultflags(res);",
        "XOR": "local res = a ^ b; logicalflags(); resultflags(res);",
    }[mn]


def imm_forms(s):
    """(opcode, immediate operand, extra pattern after the ModRM) of the 80/81/83 group."""
    if s == 1:
        return [(0x80, "imm8", "; imm8")]
    iz = {2: "imm16", 4: "imm32", 8: "simm32"}[s]
    i8 = "simm8_%d" % b(s)
    return [(0x81, iz, "; " + iz), (0x83, i8, "; " + i8)]


def gen_alu(out):
    out.append("# ADD OR ADC SBB AND SUB XOR (3.1.2.3.1 rule 2a): ND=1 writes the zero-uppered NDD.")
    for mn, base, ext, nfok in ALU:
        for nf in ((0, 1) if nfok else (0,)):
            m = mn + NFSUF[nf]
            for s in SIZES:
                opc_rmr = base + (0 if s == 1 else 1)
                opc_rrm = base + (2 if s == 1 else 3)
                vp = "" if s == 1 else VPP
                head = hd(MAP4, "apxNF=%d" % nf, vp, osz(s))
                st = "local a:%d = %s; local b:%d = %s; %s " % (s, "%s", s, "%s", alu_body(mn, nf))
                # rm, reg
                out.append(ctor(m, "%s,%s" % (rm(s), reg(s)),
                                "%s & apxND=0 & byte=0x%02x; %s & %s ...%s" % (head, opc_rmr, rm(s), reg(s), rm_dest_pat(s)),
                                st % (rm(s), reg(s)) + rm_write(s, "res")))
                out.append(ctor(m, "%s,%s,%s" % (ndd(s), rm(s), reg(s)),
                                "%s & apxND=1 & %s & byte=0x%02x; %s & %s ..." % (head, ndd_pat(s), opc_rmr, rm(s), reg(s)),
                                st % (rm(s), reg(s)) + ndd_write(s, "res")))
                # reg, rm
                out.append(ctor(m, "%s,%s" % (reg(s), rm(s)),
                                "%s & apxND=0 & byte=0x%02x; %s & %s ...%s" % (head, opc_rrm, rm(s), reg(s), reg_dest_pat(s)),
                                st % (reg(s), rm(s)) + reg_write(s, "res")))
                out.append(ctor(m, "%s,%s,%s" % (ndd(s), reg(s), rm(s)),
                                "%s & apxND=1 & %s & byte=0x%02x; %s & %s ..." % (head, ndd_pat(s), opc_rrm, rm(s), reg(s)),
                                st % (reg(s), rm(s)) + ndd_write(s, "res")))
                # rm, imm
                for opc, imm, tail in imm_forms(s):
                    out.append(ctor(m, "%s,%s" % (rm(s), imm),
                                    "%s & apxND=0 & byte=0x%02x; %s & reg_opcode=%d ...%s%s" % (head, opc, rm(s), ext, rm_dest_pat(s), tail),
                                    st % (rm(s), imm) + rm_write(s, "res")))
                    out.append(ctor(m, "%s,%s,%s" % (ndd(s), rm(s), imm),
                                    "%s & apxND=1 & %s & byte=0x%02x; %s & reg_opcode=%d ...%s" % (head, ndd_pat(s), opc, rm(s), ext, tail),
                                    st % (rm(s), imm) + ndd_write(s, "res")))
    out.append("")


# --- one-source group: (mnemonic, 8-bit opcode, /reg, supports NF)
UNARY = [("INC", 0xFE, 0, True), ("DEC", 0xFE, 1, True), ("NOT", 0xF6, 2, False), ("NEG", 0xF6, 3, True)]


def unary_body(mn, nf):
    if nf or mn == "NOT":
        return {"INC": "local res = a + 1;", "DEC": "local res = a - 1;", "NOT": "local res = ~a;", "NEG": "local res = -a;"}[mn]
    return {
        "INC": "OF = scarry(a, 1); local res = a + 1; resultflags(res);",
        "DEC": "OF = sborrow(a, 1); local res = a - 1; resultflags(res);",
        "NEG": "negflags(a); local res = -a; resultflags(res);",
    }[mn]


def gen_unary(out):
    out.append("# INC DEC NOT NEG")
    for mn, op8, ext, nfok in UNARY:
        for nf in ((0, 1) if nfok else (0,)):
            m = mn + NFSUF[nf]
            for s in SIZES:
                opc = op8 + (0 if s == 1 else 1)
                vp = "" if s == 1 else VPP
                head = hd(MAP4, "apxNF=%d" % nf, vp, osz(s))
                st = "local a:%d = %s; %s " % (s, rm(s), unary_body(mn, nf))
                out.append(ctor(m, rm(s), "%s & apxND=0 & byte=0x%02x; %s & reg_opcode=%d ...%s" % (head, opc, rm(s), ext, rm_dest_pat(s)),
                                st + rm_write(s, "res")))
                out.append(ctor(m, "%s,%s" % (ndd(s), rm(s)), "%s & apxND=1 & %s & byte=0x%02x; %s & reg_opcode=%d ..." % (head, ndd_pat(s), opc, rm(s), ext),
                                st + ndd_write(s, "res")))
    out.append("")


# --- shifts and rotates: (mnemonic, /reg list, supports NF)
SHIFTS = [("ROL", (0,), True), ("ROR", (1,), True), ("RCL", (2,), False), ("RCR", (3,), False),
          ("SHL", (4, 6), True), ("SHR", (5,), True), ("SAR", (7,), True)]


def shift_body(mn, s, cnt, nf):
    n = bits(s)
    if mn in ("SHL", "SHR", "SAR"):
        op = {"SHL": "<<", "SHR": ">>", "SAR": "s>>"}[mn]
        fl = "" if nf else " %sflags(a, res, count); shiftresultflags(res, count);" % mn.lower()
        return "local count = %s & %s; local res = a %s count;%s" % (cnt, mask(s), op, fl)
    if mn in ("ROL", "ROR"):
        l, r = ("<<", ">>") if mn == "ROL" else (">>", "<<")
        fl = "" if nf else " %sflags(res, mc);" % mn.lower()
        return "local mc = %s & %s; local cnt = mc %% %d; local res = (a %s cnt) | (a %s (%d - cnt));%s" % (cnt, mask(s), n, l, r, n, fl)
    # RCL / RCR rotate through CF over n+1 bits in a double-width temporary
    modulo = {1: " % 9", 2: " % 17"}.get(s, "")
    w = 2 * s
    if mn == "RCL":
        rot = "t = (t << cnt) | (t >> (%d - cnt));" % (n + 1)
    else:
        rot = "t = (t >> cnt) | (t << (%d - cnt));" % (n + 1)
    return ("local cnt = (%s & %s)%s; local t:%d = (zext(CF) << %d) | zext(a); %s local res:%d = t:%d; CF = ((t >> %d) & 1) != 0;"
            % (cnt, mask(s), modulo, w, n, rot, s, s, n))


def gen_shifts(out):
    out.append("# ROL ROR RCL RCR SHL SHR SAR by 1, CL and imm8")
    for mn, exts, nfok in SHIFTS:
        for nf in ((0, 1) if nfok else (0,)):
            m = mn + NFSUF[nf]
            for s in SIZES:
                vp = "" if s == 1 else VPP
                head = hd(MAP4, "apxNF=%d" % nf, vp, osz(s))
                odd = 0 if s == 1 else 1
                for opc, cname, cnt, tail, extra in ((0xD0 + odd, "n1", "1:1", "", " & n1"), (0xD2 + odd, "CL", "CL", "", " & CL"),
                                                     (0xC0 + odd, "imm8", "imm8", "; imm8", "")):
                    for ext in exts:
                        st = "local a:%d = %s; %s " % (s, rm(s), shift_body(mn, s, cnt, nf))
                        out.append(ctor(m, "%s,%s" % (rm(s), cname),
                                        "%s & apxND=0 & byte=0x%02x; %s & reg_opcode=%d ...%s%s%s" % (head, opc, rm(s), ext, rm_dest_pat(s), extra, tail),
                                        st + rm_write(s, "res")))
                        out.append(ctor(m, "%s,%s,%s" % (ndd(s), rm(s), cname),
                                        "%s & apxND=1 & %s & byte=0x%02x; %s & reg_opcode=%d ...%s%s" % (head, ndd_pat(s), opc, rm(s), ext, extra, tail),
                                        st + ndd_write(s, "res")))
    out.append("")


def gen_shxd(out):
    out.append("# SHLD SHRD (map-4 opcodes 24/2C for imm8, A5/AD for CL)")
    for mn, oi, oc in (("SHLD", 0x24, 0xA5), ("SHRD", 0x2C, 0xAD)):
        for nf in (0, 1):
            m = mn + NFSUF[nf]
            for s in (2, 4, 8):
                n = bits(s)
                head = hd(MAP4, "apxNF=%d" % nf, VPP, osz(s))
                for opc, cname, cnt, tail, extra in ((oi, "imm8", "imm8", "; imm8", ""), (oc, "CL", "CL", "", " & CL")):
                    if mn == "SHLD":
                        expr = "(a << count) | (b >> (%d - count))" % n
                        fl = "" if nf else " shlflags(a, res, count); shiftresultflags(res, count);"
                    else:
                        expr = "(a >> count) | (b << (%d - count))" % n
                        fl = "" if nf else " shrdflags(a, res, count); shiftresultflags(res, count);"
                    st = "local a:%d = %s; local b:%d = %s; local count = %s & %s; local res = %s;%s " % (s, rm(s), s, reg(s), cnt, mask(s), expr, fl)
                    out.append(ctor(m, "%s,%s,%s" % (rm(s), reg(s), cname),
                                    "%s & apxND=0 & byte=0x%02x; %s & %s ...%s%s%s" % (head, opc, rm(s), reg(s), rm_dest_pat(s), extra, tail),
                                    st + rm_write(s, "res")))
                    out.append(ctor(m, "%s,%s,%s,%s" % (ndd(s), rm(s), reg(s), cname),
                                    "%s & apxND=1 & %s & byte=0x%02x; %s & %s ...%s%s" % (head, ndd_pat(s), opc, rm(s), reg(s), extra, tail),
                                    st + ndd_write(s, "res")))
    out.append("")


def gen_imul(out):
    out.append("# IMUL: 0xAF with NDD, 0x69/0x6B with ZU (EVEX.ND), F6/F7 /5 one-operand forms come from ia.sinc")
    for nf in (0, 1):
        m = "IMUL" + NFSUF[nf]
        mz = "IMULZU" + NFSUF[nf]
        for s in (2, 4, 8):
            head = hd(MAP4, "apxNF=%d" % nf, VPP, osz(s))
            fl = "" if nf else " imultflags(res, t);"
            st = "local a:%d = %s; local b:%d = %s; local t:%d = sext(a) * sext(b); local res:%d = t:%d;%s " % (s, "%s", s, "%s", 2 * s, s, s, fl)
            out.append(ctor(m, "%s,%s" % (reg(s), rm(s)), "%s & apxND=0 & byte=0xaf; %s & %s ...%s" % (head, rm(s), reg(s), reg_dest_pat(s)),
                            st % (reg(s), rm(s)) + reg_write(s, "res")))
            out.append(ctor(m, "%s,%s,%s" % (ndd(s), reg(s), rm(s)), "%s & apxND=1 & %s & byte=0xaf; %s & %s ..." % (head, ndd_pat(s), rm(s), reg(s)),
                            st % (reg(s), rm(s)) + ndd_write(s, "res")))
            iz = {2: "simm16_16", 4: "simm32_32", 8: "simm32_64"}[s]
            for opc, imm in ((0x69, iz), (0x6B, "simm8_%d" % b(s))):
                out.append(ctor(m, "%s,%s,%s" % (reg(s), rm(s), imm), "%s & apxND=0 & byte=0x%02x; (%s & %s ...%s); %s" % (head, opc, rm(s), reg(s), reg_dest_pat(s), imm),
                                st % (rm(s), imm) + reg_write(s, "res")))
                zu = "Reg64 = res;" if s == 8 else "Reg64 = zext(res);"
                r64 = "" if s == 8 else " & Reg64 ..."
                out.append(ctor(mz, "%s,%s,%s" % (reg(s), rm(s), imm), "%s & apxND=1 & byte=0x%02x; (%s & %s ...%s); %s" % (head, opc, rm(s), reg(s), r64, imm),
                                st % (rm(s), imm) + zu))
    out.append("")


def gen_cmov(out):
    out.append("# CMOVcc (NDD) and CFCMOVcc (Table 3.5); a false condition suppresses the memory access of CFCMOVcc")
    for s in (2, 4, 8):
        head = hd(MAP4, VPP, osz(s))
        r, mm, rg = rm(s), "m%d" % b(s), reg(s)
        z = (lambda d, v: "%s = %s;" % (d, v)) if s == 8 else (lambda d, v: "%s = zext(%s);" % (d, v))
        # ND=0 NF=0: CFCMOVcc reg, r/m  (reg := cc ? r/m : 0)
        out.append(ctor("CFCMOV^cc", "%s,%s" % (rg, r), "%s & apxND=0 & apxNF=0 & row=4 & cc; %s & %s ...%s" % (head, r, rg, "" if s == 8 else " & Reg64 ..."),
                        "local v:%d = 0; if (!cc) goto <z>; v = %s; <z> %s" % (s, r, z("Reg64", "v"))))
        # ND=0 NF=1: CFCMOVcc r/m, reg
        out.append(ctor("CFCMOV^cc", "%s,%s" % ("Rmr%d" % b(s), rg), "%s & apxND=0 & apxNF=1 & row=4 & cc; mod=3 & Rmr%d%s & %s" % (head, b(s), "" if s == 8 else " & Rmr64", rg),
                        "local v:%d = 0; if (!cc) goto <z>; v = %s; <z> %s" % (s, rg, z("Rmr64", "v"))))
        out.append(ctor("CFCMOV^cc", "%s,%s" % (mm, rg), "%s & apxND=0 & apxNF=1 & row=4 & cc; %s & %s ..." % (head, mm, rg),
                        "if (!cc) goto inst_next; %s = %s;" % (mm, rg)))
        # ND=1 NF=0: CMOVcc ndd, reg, r/m (the r/m read always happens)
        out.append(ctor("CMOV^cc", "%s,%s,%s" % (ndd(s), rg, r), "%s & apxND=1 & apxNF=0 & %s & row=4 & cc; %s & %s ..." % (head, ndd_pat(s), r, rg),
                        "local t:%d = %s; local v:%d = %s; if (!cc) goto <z>; v = t; <z> %s" % (s, r, s, rg, ndd_write(s, "v"))))
        # ND=1 NF=1: CFCMOVcc ndd, reg, r/m
        out.append(ctor("CFCMOV^cc", "%s,%s,%s" % (ndd(s), rg, r), "%s & apxND=1 & apxNF=1 & %s & row=4 & cc; %s & %s ..." % (head, ndd_pat(s), r, rg),
                        "local v:%d = %s; if (!cc) goto <z>; v = %s; <z> %s" % (s, rg, r, ndd_write(s, "v"))))
    out.append("# SETcc and SETcc.zu (F2, row 4; EVEX.ND selects zero-upper for a register destination)")
    out.append(ctor("SET^cc", "rm8", "%s & apxND=0 & prefix_f2=1 & row=4 & cc; rm8" % MAP4, "rm8 = cc;"))
    out.append(ctor("SETZU^cc", "Rmr8", "%s & apxND=1 & prefix_f2=1 & row=4 & cc; mod=3 & Rmr8 & Rmr64" % MAP4, "Rmr64 = zext(cc);"))
    out.append(ctor("SETZU^cc", "m8", "%s & apxND=1 & prefix_f2=1 & row=4 & cc; m8" % MAP4, "m8 = cc;"))
    out.append("")


def gen_ccmp(out):
    out.append("# CCMPscc / CTESTscc (3.1.3.2.1): a false SCC sets OF SF ZF CF from dfv, PF from dfv.CF, clears AF")
    dflt = "<dflt> OF = apxDfvOF; SF = apxDfvSF; ZF = apxDfvZF; CF = apxDfvCF; PF = apxDfvCF; AF = 0;"
    cmpb = "subflags(a, b); local d = a - b; resultflags(d);"
    tstb = "local d = a & b; logicalflags(); resultflags(d);"
    for mn, body in (("CCMP", cmpb), ("CTEST", tstb)):
        forms = []
        for s in SIZES:
            vp = "" if s == 1 else VPP
            head = hd(MAP4, "apxND=0", vp, osz(s))
            odd = 0 if s == 1 else 1
            if mn == "CCMP":
                forms.append((s, "%s,%s" % (rm(s), reg(s)), "%s & byte=0x%02x; %s & %s ..." % (head, 0x38 + odd, rm(s), reg(s)), rm(s), reg(s)))
                forms.append((s, "%s,%s" % (reg(s), rm(s)), "%s & byte=0x%02x; %s & %s ..." % (head, 0x3A + odd, rm(s), reg(s)), reg(s), rm(s)))
                for opc, imm, tail in imm_forms(s):
                    forms.append((s, "%s,%s" % (rm(s), imm), "%s & byte=0x%02x; %s & reg_opcode=7 ...%s" % (head, opc, rm(s), tail), rm(s), imm))
            else:
                forms.append((s, "%s,%s" % (rm(s), reg(s)), "%s & byte=0x%02x; %s & %s ..." % (head, 0x84 + odd, rm(s), reg(s)), rm(s), reg(s)))
                imm = {1: "imm8", 2: "imm16", 4: "imm32", 8: "simm32"}[s]
                forms.append((s, "%s,%s" % (rm(s), imm), "%s & byte=0x%02x; %s & (reg_opcode=0 | reg_opcode=1) ...; %s" % (head, 0xF6 + odd, rm(s), imm), rm(s), imm))
        for s, ops, pat, x, y in forms:
            out.append(ctor(mn + "^apxScc", "apxDfv " + ops, pat.replace("byte=", "apxScc & apxDfv & apxDfvOF & apxDfvSF & apxDfvZF & apxDfvCF & byte=", 1),
                            "local a:%d = %s; local b:%d = %s; local sc:1 = apxScc; if (sc == 0) goto <dflt>; %s goto inst_next; %s" % (s, x, s, y, body, dflt)))
    out.append("")


def gen_misc(out):
    out.append("# PUSH2 / POP2 (3.1.3.1.1): ND=1, Mod=3, EVEX.W is the PPX hint")
    for w, suf in ((0, ""), (1, "P")):
        out.append(ctor("PUSH2" + suf, "apxNDD64,Rmr64", "%s & apxND=1 & rexWprefix=%d & apxNDD64 & byte=0xff; mod=3 & reg_opcode=6 & Rmr64" % (MAP4, w),
                        "push88(apxNDD64); push88(Rmr64);"))
        out.append(ctor("POP2" + suf, "apxNDD64,Rmr64", "%s & apxND=1 & rexWprefix=%d & apxNDD64 & byte=0x8f; mod=3 & reg_opcode=0 & Rmr64" % (MAP4, w),
                        "pop88(apxNDD64); pop88(Rmr64);"))
    out.append("# MOVBE (map-4 0x60/0x61, the register form included)")
    for s in (2, 4, 8):
        head = hd(MAP4, "apxND=0 & apxNF=0", VPP, osz(s))
        out.append(ctor("MOVBE", "%s,%s" % (reg(s), rm(s)), "%s & byte=0x60; %s & %s ...%s" % (head, rm(s), reg(s), reg_dest_pat(s)),
                        "local v:%d = %s; %s" % (s, rm(s), reg_write(s, "swap_bytes(v)"))))
        out.append(ctor("MOVBE", "%s,%s" % (rm(s), reg(s)), "%s & byte=0x61; %s & %s ...%s" % (head, rm(s), reg(s), rm_dest_pat(s)),
                        "local v:%d = %s; %s" % (s, reg(s), rm_write(s, "swap_bytes(v)"))))
    out.append("# ADCX (66) / ADOX (F3), map-4 0x66, with NDD")
    for mn, pfx, fl in (("ADCX", "prefix_66=1", "CF"), ("ADOX", "prefix_f3=1", "OF")):
        for s in (4, 8):
            head = "%s & apxNF=0 & %s & rexWprefix=%d" % (MAP4, pfx, 1 if s == 8 else 0)
            st = "local t:%d = zext(%s) + zext(%s) + zext(%s); local c:1 = t(%d); %s = c != 0; local res:%d = t:%d; " % (s + 1, reg(s), rm(s), fl, s, fl, s, s)
            out.append(ctor(mn, "%s,%s" % (reg(s), rm(s)), "%s & apxND=0 & byte=0x66; %s & %s ...%s" % (head, rm(s), reg(s), reg_dest_pat(s)),
                            st + reg_write(s, "res")))
            out.append(ctor(mn, "%s,%s,%s" % (ndd(s), reg(s), rm(s)), "%s & apxND=1 & %s & byte=0x66; %s & %s ..." % (head, ndd_pat(s), rm(s), reg(s)),
                            st + ndd_write(s, "res")))
    out.append("# CRC32 (map-4 0xF0/0xF1)")
    out.append(ctor("CRC32", "Reg32,rm8", "%s & apxND=0 & apxNF=0 & rexWprefix=0 & mandover=0 & byte=0xf0; rm8 & Reg32 ... & check_Reg32_dest ..." % MAP4,
                    "Reg32 = crc32(Reg32, rm8); build check_Reg32_dest;"))
