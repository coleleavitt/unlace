#!/usr/bin/env python3
"""Write the s390x vector facility (opcodes E6 and E7) as SLEIGH from vector_insts.json.

    python3 gen_vector.py --extract SZ.json     # refresh vector_insts.json from an llvm-tblgen dump
    python3 gen_vector.py data/languages         # write s390x_vector.sinc and vector_fields.txt
    python3 gen_sinc.py data/languages           # (reads vector_fields.txt into the 48-bit token)

vector_insts.json holds, for every E6/E7 instruction of LLVM's SystemZ target (TableGen
records; no codegen-only or parser-only ones), its mnemonic, operands and the 48 encoding
bits (constant, or the operand bit they carry). It was extracted from
`llvm-tblgen -dump-json -I llvm/include -I llvm/lib/Target/SystemZ SystemZ.td` of
LLVM release/22.x. Semantics are written here per mnemonic family: exact p-code for the moves,
logic, lane arithmetic, shifts, compares, loads and stores and for the binary floating point
(the scalar W forms LLVM emits for double, float and long double at -march=z13 and later), and
a user operation named after the mnemonic for the rest (string, packed decimal, Galois field,
NNPA, checksum and multiply-and-add-high forms).
"""
import json
import os
