cons = []
seen = set()
for ins in INSTS:
    asm = ins["asm"]
    mn = asm.split()[0].split("$")[0].strip()
    pm = locate(ins)
    tied = dict((m.group(1), m.group(2)) for m in re.finditer(r"\$(\w+) = \$(\w+)", ins["constraints"]))
    pat = fixed_runs(ins)
    actions, syms, dispmap, ea, mems = [], {}, {}, None, []
    ok = True
    for t_, v in ins["outs"] + ins["ins"]:
        if isinstance(v, list):
            disp, ea = mem_operand(t_, v, pm, pat, actions)
            for x in v:
                dispmap[x] = disp
            mems.append(v)
            continue
        if v in tied:
            continue
        if v not in pm:
            syms[v] = None
            dispmap[v] = "0"
            continue
        disp, p2, sym, kind = operand(t_, v, pm[v])
        if kind == "split":
            _, spm, signed = disp
            sym = split_imm(v, spm, signed, pat, actions)
            disp = sym
        for tk in "wp":
            pat[tk] += p2[tk]
        syms[v] = sym
        dispmap[v] = disp
    for a_, b_ in tied.items():
        syms[a_] = syms.get(b_)
    # display from the assembly string
    order = re.findall(r"\$(\w+)", asm)
    tail = re.sub(r"^\S+\s*", "", asm)
    def dsub(m):
        v = m.group(1)
        if v == "addr" and mems:
            return dispmap[mems[0][0]]
        return dispmap.get(v, v)
    disp = re.sub(r"\s*,\s*", ",", re.sub(r"\$\{?(\w+)\}?", dsub, tail)).strip()
    w = " & ".join(["$(NOTVLE)"] + list(dict.fromkeys(pat["w"]))) if ins["size"] == 32 else None
    if ins["size"] == 64:
        pp = " & ".join(["$(NOTVLE)"] + list(dict.fromkeys(pat["p"])))
        pw = " & ".join(list(dict.fromkeys(pat["w"])))
        pattern = f"{pp} ; {pw}"
    else:
        pattern = w
    key = (mn, pattern)
    if key in seen:
        continue
    seen.add(key)

    O = [syms[v] for t_, v in ins["outs"]]
    I = [syms[v] for t_, v in ins["ins"] if not isinstance(v, list) and v not in tied and syms.get(v) is not None]
    body = sem(mn, O, I, ea)
    if body is None:
        op = "p31_" + mn.replace(".", "_rec")
        pcodeops.add(op)
        args = []
        for t_, v in ins["ins"]:
            if isinstance(v, list):
                args.append(ea)
            elif v in tied:
                continue
            else:
                s = syms.get(v)
                if s is None:
                    continue
                if isinstance(s, tuple):
                    args += list(s)
                else:
                    args.append(s)
        outs = []
        for t_, v in ins["outs"]:
            s = syms.get(v)
            outs += list(s) if isinstance(s, tuple) else [s]
        pre = []
        for i, a in enumerate(args):
            if re.match(r"(p|w)_x|imm_|(p|w)_xs", a) or a.startswith(("w_x", "p_x", "imm_")):
                pre.append(f"local a{i}:8 = {a};")
                args[i] = f"a{i}"
        if outs:
            body = " ".join(pre) + " " + " ".join(f"{o} = {op}({', '.join(args)});" for o in outs)
        else:
            body = " ".join(pre) + f" {op}({', '.join(args)});"
        if mn.endswith("."):
            cr = "cr6" if mn.startswith(("v", "x")) else "cr0"
            pcodeops.add(f"{op}_{cr}")
            body += f" {cr} = {op}_{cr}({', '.join(args)});"
    act = f" [ {' '.join(dict.fromkeys(actions))} ]" if actions else ""
    cons.append(f":{mn} {disp} is {pattern}{act} {{\n\t{body.strip()}\n}}\n".replace("\t@", "@"))

