/// (unlace) One LLM/agent-settable assertion: the machine-readable catalog row —
/// C++ `UnlaceSettable`.
#[derive(Clone, Copy, Debug)]
pub struct UnlaceSettable {
    /// The option name (the `option <name> ...` token).
    pub option: &'static str,
    /// Pipe-separated legal values, e.g. "on|off" or "canonical|original".
    pub values: &'static str,
    /// The value unlace ships as the default (post-DIV-2 where applicable).
    pub shipped: &'static str,
    /// true = NOT safe as a global default (kept opt-in).
    pub destructive: bool,
    /// Owning stage.
    pub phase: UnlacePhase,
    /// Sub-stage name (in the §4-§10 catalog).
    pub subphase: &'static str,
    /// Assertion strength.
    pub strength: UnlaceStrength,
    /// Minimal invalidated stage (REPORTED; Ghidra-actual is whole-function).
    pub rewind: UnlacePhase,
    /// Originating issue (e.g. "GH-558"), or "".
    pub issue: &'static str,
    /// One line: the decision this assertion controls.
    pub summary: &'static str,
    /// Symptom -> when an operator should flip it away from the default.
    pub use_when: &'static str,
    /// A ready-to-use console command, e.g. "option compareform canonical".
    pub example: &'static str,
    /// (unlace) Which decompiler the behavior was observed/ported from.
    pub source_decompiler: &'static str,
    /// (unlace) Concrete origin pointer (upstream issue/PR, or reference class).
    pub inspiration: &'static str,
    /// (unlace) Gates default-on eligibility.
    pub change_kind: &'static str,
    /// Catalog tier: "transform" (restructures/duplicates/removes/inserts
    /// code -- the on/off control surface), "core" (near-always-better
    /// rendering/naming/peephole defaults), or "analysis" (analysis/loader
    /// pass enablement).
    pub tier: &'static str,
    /// (unlace) Pipe-separated output-shaped symptom phrases: what the decompiled
    /// output looks like when this option is the one to reach for (grep bait
    /// for an LLM matching a natural-language symptom to the option). Emitted
    /// into the catalog JSON as the `symptoms` array (split on '|').
    pub symptoms: &'static str,
}

