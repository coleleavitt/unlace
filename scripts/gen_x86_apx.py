def active_lines(text):
    """Yield the lines a 64-bit (IA64, not IA16) compile sees, with their numbers."""
    stack = []
    for n, line in enumerate(text.split("\n"), 1):
        m = re.match(r"\s*@(ifdef|ifndef|else|endif)\b\s*(\w*)", line)
        if m:
            kw, name = m.group(1), m.group(2)
            if kw == "ifdef":
                stack.append(name == "IA64")
            elif kw == "ifndef":
                stack.append(name != "IA64")
            elif kw == "else":
                stack[-1] = not stack[-1]
            else:
                stack.pop()
            continue
        if all(stack):
            yield n, line


def constructors(text):
    """Root-table constructors (lines starting with ':') with their full text."""
    lines = list(active_lines(text))
    i = 0
    while i < len(lines):
        n, line = lines[i]
        if not line.startswith(":") or line.startswith(":^instruction"):
            i += 1
            continue
        buf, depth, opened = [], 0, False
        while i < len(lines):
            _, l = lines[i]
            buf.append(l)
            code = l.split("#", 1)[0]
            for ch in code:
                if ch == "{":
                    depth += 1
                    opened = True
                elif ch == "}":
                    depth -= 1
            i += 1
            if opened and depth == 0:
                break
        yield n, "\n".join(buf)


ESC = re.compile(r"byte=0x0?[fF]\s*;\s*")


def rekey_map1(ctor_text):
    """Re-key a legacy 0x0F xx constructor for REX2.M0=1; None when it does not apply."""
    parts = re.split(r"\s+is\s+", ctor_text, maxsplit=1)
    if len(parts) != 2:
        return None
    head, rest = parts
    brace = rest.find("{")
    pat = rest[:brace]
    if "vexMode=0" not in pat or "LONGMODE_OFF" in pat:
        return None
    first = pat.find("byte=")
    m = ESC.search(pat)
    if not m or m.start() != first:
        return None
    nxt = pat[m.end():]
    nb = re.match(r"\(?\s*byte=0x([0-9a-fA-F]+)", nxt)
    if nb:
        v = int(nb.group(1), 16)
        if v in (0x0F, 0x38, 0x3A) or v >> 4 in (3, 8):
            return None
    elif re.match(r"\(?\s*row\s*=\s*(3|8)\b", nxt):
        return None
    pat2 = pat[:m.start()] + pat[m.end():]
    pat2 = pat2.replace("vexMode=0", "vexMode=3 & vexMMMMM=1", 1)
    return head + " is " + pat2 + rest[brace:]


# files in x86.slaspec / x86-64.slaspec order, and whether they sit in "with : lockprefx=0"
SOURCES = [("ia.sinc", False), ("lockable.sinc", False), ("adx.sinc", True), ("clwb.sinc", True), ("mpx.sinc", True),
           ("lzcnt.sinc", True), ("bmi1.sinc", True), ("smx.sinc", True), ("cet.sinc", True), ("rdrand.sinc", True),
           ("uintr.sinc", True)]


def gen_map1():
    out = [HEADER, "# Legacy map-1 instructions under REX2 with M0=1 (3.1.2.1): the 0x0F escape is implied, so each",
           "# 64-bit map-1 constructor is repeated with vexMode=3 & vexMMMMM=1 in place of the escape byte. Rows 0x3*",
           "# and 0x8* of map 1 #UD under REX2 and are not repeated; maps 2 and 3 have no REX2 form.", ""]
    count = 0
    for name, with_lock in SOURCES:
        text = (LANG / name).read_text()
        got = []
        for n, c in constructors(text):
            r = rekey_map1(c)
            if r:
                got.append("# %s:%d\n%s" % (name, n, r))
        if not got:
            continue
        if with_lock:
            out.append("with : lockprefx=0 {")
        out.extend(got)
        if with_lock:
            out.append("}")
        out.append("")
        count += len(got)
    return "\n".join(out), count


def promote_from(text, mnemonic_re, map4_opc, nf_strip):
    """EVEX map-4 copies of legacy constructors: NF=0 keeps the flags, NF=1 drops the calls matching nf_strip."""
    res = []
    for n, c in constructors(text):
        if not re.match(mnemonic_re, c):
            continue
        parts = re.split(r"\s+is\s+", c, maxsplit=1)
        if len(parts) != 2:
            continue
        head, rest = parts
        brace = rest.find("{")
        pat, body = rest[:brace], rest[brace:]
        if "vexMode=0" not in pat:
            continue
        for k, v in map4_opc.items():
            if k in pat:
                pat = pat.replace(k, v)
                break
        else:
            continue
        for junk in ("$(PRE_F3) & ", "$(PRE_66) & ", "$(REX_W) & "):
            pat = pat.replace(junk, "")
        base = pat.replace("vexMode=0", "%s & apxND=0 & %s" % (MAP4, VPP.rstrip(" &")) if "byte=0xf6" not in pat else "%s & apxND=0" % MAP4, 1)
        res.append("%s is %s%s" % (head, base.replace("apxND=0", "apxND=0 & apxNF=0", 1), body))
        stripped = re.sub(nf_strip, "", body)
        mn = head.split()[0]
        nfhead = head.replace(mn, mn + '^".NF"', 1)
        res.append("%s is %s%s" % (nfhead, base.replace("apxND=0", "apxND=0 & apxNF=1", 1), stripped))
    return res


def gen_map4():
    out = [HEADER, "# Legacy instructions promoted to EVEX map 4 (vexMode=3 & vexMMMMM=4), 3.1.2.3.1 and 3.1.5.", ""]
    gen_alu(out)
    gen_unary(out)
    gen_shifts(out)
    gen_shxd(out)
    gen_imul(out)
    gen_cmov(out)
    gen_ccmp(out)
    gen_misc(out)
    ia = (LANG / "ia.sinc").read_text()
    out.append("# MUL IMUL DIV IDIV one-operand forms (F6/F7 /4-/7), from ia.sinc")
    out.extend(promote_from(ia, r":(MUL|IMUL|DIV|IDIV)\s+rm(8|16|32|64)\s", {"byte=0xf6": "byte=0xf6", "byte=0xf7": "byte=0xf7"},
                            r"\s*i?multflags\([^)]*\);"))
    out.append("# POPCNT (0x88), TZCNT (0xF4), LZCNT (0xF5)")
    out.extend(promote_from(ia, r":POPCNT ", {"byte=0x0F; byte=0xB8": "byte=0x88"}, r"\s*popcountflags\([^)]*\);"))
    out.extend(promote_from((LANG / "bmi1.sinc").read_text(), r":TZCNT ", {"byte=0x0F; byte=0xBC": "byte=0xF4"}, r"\s*tzcntflags\([^)]*\);"))
    out.extend(promote_from((LANG / "lzcnt.sinc").read_text(), r":LZCNT ", {"byte=0x0F; byte=0xBD": "byte=0xF5"}, r"\s*lzcntflags\([^)]*\);"))
    out.append("")
    return "\n".join(out)


